// codebreaker/java/cmake.cpp -- C++ from codebreaker.java.cmake.
//
// cmake.py -- the PC build: a CMakeLists.txt beside a pc_opengl conversion.
//
// Every .cpp in the folder is one executable (the converted program, the runtime, the SDL2/OpenGL platform
// layer and the generated entry). C++17; SDL2 and OpenGL from the system (MSYS2 / a Linux distribution / a
// CMake package). A `Content` folder beside the CMakeLists is copied next to the program: the game's
// resources, as the entry point looks for them.

#include "codebreaker/java/cmake.hpp"

namespace codebreaker::java::cmake {

const py::str _TEMPLATE(R"CMK(# Generated by CodeBreaker (java -> C++, platform pc_opengl). Build:
#   cmake -S . -B build -G Ninja      (or "MinGW Makefiles" / your generator)
#   cmake --build build
cmake_minimum_required(VERSION 3.16)
project({name} CXX)

set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS ON)

file(GLOB J2X_SOURCES CONFIGURE_DEPENDS "${{CMAKE_CURRENT_SOURCE_DIR}}/*.cpp")
add_executable({name} ${{J2X_SOURCES}})
target_include_directories({name} PRIVATE "${{CMAKE_CURRENT_SOURCE_DIR}}")
if(CMAKE_CXX_COMPILER_ID MATCHES "GNU|Clang")
  target_compile_options({name} PRIVATE -w -fpermissive)
endif()

find_package(SDL2 CONFIG QUIET)
if(TARGET SDL2::SDL2)
  target_link_libraries({name} PRIVATE SDL2::SDL2)
else()
  target_link_libraries({name} PRIVATE SDL2)
endif()
find_package(OpenGL REQUIRED)
target_link_libraries({name} PRIVATE OpenGL::GL OpenGL::GLU)
target_link_libraries({name} PRIVATE vorbisfile vorbis ogg)   # the game's .ogg sounds and music
if(WIN32)
  target_link_libraries({name} PRIVATE ws2_32)
endif()

if(EXISTS "${{CMAKE_CURRENT_SOURCE_DIR}}/Content")
  add_custom_command(TARGET {name} POST_BUILD
    COMMAND ${{CMAKE_COMMAND}} -E copy_directory "${{CMAKE_CURRENT_SOURCE_DIR}}/Content" "$<TARGET_FILE_DIR:{name}>/Content")
endif()
)CMK");

namespace {

// _TEMPLATE.format(name=name): `{{` and `}}` become braces, `{name}` the name (inserted as it is)
py::str format_name(const py::str& tmpl, const py::str& name) {
    const std::u32string& t = tmpl.u32();
    std::u32string out;
    for (size_t i = 0; i < t.size(); ++i) {
        if (t[i] == U'{' && i + 1 < t.size() && t[i + 1] == U'{') {
            out.push_back(U'{');
            ++i;
        } else if (t[i] == U'}' && i + 1 < t.size() && t[i + 1] == U'}') {
            out.push_back(U'}');
            ++i;
        } else if (t.compare(i, 6, U"{name}") == 0) {
            out += name.u32();
            i += 5;
        } else {
            out.push_back(t[i]);
        }
    }
    return py::str(out);
}

}  // namespace

// Write out_dir/CMakeLists.txt for an executable called `name`. -> its path
py::str write_cmakelists(const py::str& out_dir, const py::str& name) {
    py::str path = py::os::path::join(out_dir, py::str("CMakeLists.txt"));
    py::file fh = py::open(path, py::str("w"), py::str("utf-8"));
    fh.write(format_name(_TEMPLATE, name));
    fh.close();
    return path;
}

}  // namespace codebreaker::java::cmake
