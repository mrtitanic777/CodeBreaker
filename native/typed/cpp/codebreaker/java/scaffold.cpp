py::list<py::str> _discover(const py::str& java_dir) {
    py::list<py::str> out;
    for (const auto& walked : py::os::walk(java_dir)) {
        const py::str& dp = std::get<0>(walked);
        for (const py::str& f : std::get<2>(walked)) {
            if (f.endswith(py::str(".java"))) {
                out.append(py::os::path::join(dp, f));
            }
        }
    }
    return py::sorted(out);
}

py::str _snake(const py::str& name) {
    py::str s = py::re::sub(py::str("([a-z0-9])([A-Z])"), py::str("\\1_\\2"), name);
    return s.lower();
}

// --- type mapping per language (skeleton fidelity, not exact) --------------
const py::dict<py::str, py::str> _C = {
    {py::str("int"), py::str("int")},         {py::str("long"), py::str("long long")},
    {py::str("short"), py::str("short")},     {py::str("byte"), py::str("signed char")},
    {py::str("char"), py::str("char")},       {py::str("boolean"), py::str("int")},
    {py::str("float"), py::str("float")},     {py::str("double"), py::str("double")},
    {py::str("void"), py::str("void")},       {py::str("String"), py::str("const char*")},
};
const py::dict<py::str, py::str> _CS = {
    {py::str("int"), py::str("int")},         {py::str("long"), py::str("long")},
    {py::str("short"), py::str("short")},     {py::str("byte"), py::str("byte")},
    {py::str("char"), py::str("char")},       {py::str("boolean"), py::str("bool")},
    {py::str("float"), py::str("float")},     {py::str("double"), py::str("double")},
    {py::str("void"), py::str("void")},       {py::str("String"), py::str("string")},
};
const py::dict<py::str, py::str> _RS = {
    {py::str("int"), py::str("i32")},         {py::str("long"), py::str("i64")},
    {py::str("short"), py::str("i16")},       {py::str("byte"), py::str("i8")},
    {py::str("char"), py::str("char")},       {py::str("boolean"), py::str("bool")},
    {py::str("float"), py::str("f32")},       {py::str("double"), py::str("f64")},
    {py::str("void"), py::str("()")},         {py::str("String"), py::str("String")},
};

py::str _jtype_name(const py::ref<jir::JType>& jt) { return jt ? jt->name : py::str("void"); }

int64_t _arr(const py::ref<jir::JType>& jt) { return jt ? jt->array_dims : 0; }

py::str _ctype(const py::ref<jir::JType>& jt) {
    py::str base = _C.get(_jtype_name(jt), py::str("void*"));  // unknown class -> opaque pointer
    bool known = false;                                        // `base not in _C.values()`
    for (const auto& kv : _C.items()) {
        if (std::get<1>(kv) == base) {
            known = true;
            break;
        }
    }
    if (!known) {
        base = py::percent(py::str("%s*"), _jtype_name(jt));   // a known class name -> pointer to its struct
    }
    return base + py::str(_arr(jt) ? "*" : "");
}

py::str _cstype(const py::ref<jir::JType>& jt) {
    py::str n = _jtype_name(jt);
    py::str base = _CS.get(n, n);                              // C# keeps class names as-is
    return base + py::str(_arr(jt) ? "[]" : "");
}

py::str _rstype(const py::ref<jir::JType>& jt) {
    py::str n = _jtype_name(jt);
    py::str base = _RS.get(n, n);
    if (_arr(jt)) {
        return py::percent(py::str("Vec<%s>"), base);
    }
    return base;
}

py::str _params(const py::ref<jir::Method>& method, const std::function<py::str(const py::ref<jir::JType>&)>& render) {
    py::list<py::str> parts;
    for (const py::ref<jir::Param>& p : method->params) {
        parts.append(py::percent(py::str("%s %s"), render(p->jtype), p->name));
    }
    return py::join(py::str(", "), parts);
}

py::str _rparams(const py::ref<jir::Method>& method) {
    py::list<py::str> parts;
    for (const py::ref<jir::Param>& p : method->params) {
        parts.append(py::percent(py::str("%s: %s"), _snake(p->name), _rstype(p->jtype)));
    }
    return py::join(py::str(", "), parts);
}

// --- C ---------------------------------------------------------------------
std::tuple<py::str, py::str> _emit_c(const py::ref<jir::JClass>& cls) {
    py::str guard = _snake(cls->name).upper() + py::str("_H");
    py::list<py::str> L = {
        py::percent(py::str("/* %s.h -- SKELETON (C) generated by CodeBreaker. Not a working translation. */"), cls->name),
        py::percent(py::str("#ifndef %s"), guard),
        py::percent(py::str("#define %s"), guard),
        py::str(""),
        py::percent(py::str("typedef struct %s {"), cls->name),
    };
    py::list<py::ref<jir::Field>> inst;
    for (const py::ref<jir::Field>& f : cls->fields) {
        if (!f->is_static) {
            inst.append(f);
        }
    }
    for (const py::ref<jir::Field>& f : inst) {
        L.append(py::percent(py::str("    %s %s;"), _ctype(f->jtype), f->name));
    }
    if (!py::truthy(inst)) {
        L.append(py::str("    int _placeholder;"));
    }
    L.extend(py::list<py::str>{py::percent(py::str("} %s;"), cls->name), py::str(""),
                               py::str("/* methods (free functions taking the struct as self) */")});
    for (const py::ref<jir::Method>& m : cls->methods) {
        if (m->is_ctor) {
            L.append(py::percent(py::str("%s* %s_new(%s);"), cls->name, cls->name, _params(m, _ctype)));
            continue;
        }
        py::str ret = _ctype(m->return_type);
        py::str args = _params(m, _ctype);
        if (m->is_static) {                                    // static -> no self
            L.append(py::percent(py::str("%s %s_%s(%s);"), ret, cls->name, m->name, args));
        } else {
            py::str sep = py::truthy(args) ? py::str(", ") : py::str("");
            L.append(py::percent(py::str("%s %s_%s(%s* self%s%s);"), ret, cls->name, m->name, cls->name, sep, args));
        }
    }
    L.extend(py::list<py::str>{py::str(""), py::percent(py::str("#endif /* %s */"), guard), py::str("")});
    return {py::percent(py::str("%s.h"), cls->name), py::join(py::str("\n"), L)};
}

// --- C# --------------------------------------------------------------------
std::tuple<py::str, py::str> _emit_csharp(const py::ref<jir::JClass>& cls) {
    py::str base = (cls->parent && py::truthy(*cls->parent)) ? py::percent(py::str(" : %s"), *cls->parent) : py::str("");
    py::list<py::str> L = {
        py::percent(py::str("// %s.cs -- SKELETON (C#) generated by CodeBreaker. Not a working translation."), cls->name),
        py::str(""),
        py::percent(py::str("public class %s%s"), cls->name, base),
        py::str("{"),
    };
    for (const py::ref<jir::Field>& f : cls->fields) {
        py::str st = f->is_static ? py::str("static ") : py::str("");
        L.append(py::percent(py::str("    public %s%s %s;"), st, _cstype(f->jtype), f->name));
    }
    for (const py::ref<jir::Method>& m : cls->methods) {
        if (m->is_ctor) {
            L.append(py::percent(py::str("    public %s(%s) { throw new System.NotImplementedException(); }"), cls->name,
                                 _params(m, _cstype)));
            continue;
        }
        py::str st = m->is_static ? py::str("static ") : py::str("");
        L.append(py::percent(py::str("    public %s%s %s(%s) { throw new System.NotImplementedException(); }"), st,
                             _cstype(m->return_type), m->name, _params(m, _cstype)));
    }
    L.extend(py::list<py::str>{py::str("}"), py::str("")});
    return {py::percent(py::str("%s.cs"), cls->name), py::join(py::str("\n"), L)};
}

// --- Rust ------------------------------------------------------------------
std::tuple<py::str, py::str> _emit_rust(const py::ref<jir::JClass>& cls) {
    py::list<py::str> L = {
        py::percent(py::str("// %s -- SKELETON (Rust) generated by CodeBreaker. Not a working translation."), cls->name),
        py::str(""),
        py::percent(py::str("pub struct %s {"), cls->name),
    };
    py::list<py::ref<jir::Field>> inst;
    for (const py::ref<jir::Field>& f : cls->fields) {
        if (!f->is_static) {
            inst.append(f);
        }
    }
    for (const py::ref<jir::Field>& f : inst) {
        L.append(py::percent(py::str("    pub %s: %s,"), _snake(f->name), _rstype(f->jtype)));
    }
    if (!py::truthy(inst)) {
        L.append(py::str("    _placeholder: (),"));
    }
    L.extend(py::list<py::str>{py::str("}"), py::str(""), py::percent(py::str("impl %s {"), cls->name)});
    for (const py::ref<jir::Method>& m : cls->methods) {
        if (m->is_ctor) {
            L.append(py::percent(py::str("    pub fn new(%s) -> Self { unimplemented!() }"), _rparams(m)));
            continue;
        }
        py::str ret = _rstype(m->return_type);
        py::str arrow = (ret == py::str("()")) ? py::str("") : py::percent(py::str(" -> %s"), ret);
        py::str args = _rparams(m);
        bool selfarg = !m->is_static;
        if (selfarg && py::truthy(args)) {
            args = py::str("&self, ") + args;
        } else if (selfarg) {
            args = py::str("&self");
        }
        L.append(py::percent(py::str("    pub fn %s(%s)%s { unimplemented!() }"), _snake(m->name), args, arrow));
    }
    L.extend(py::list<py::str>{py::str("}"), py::str("")});
    return {py::percent(py::str("%s.rs"), cls->name), py::join(py::str("\n"), L)};
}

const py::dict<py::str, Emitter> _EMIT = {
    {py::str("c"), &_emit_c},
    {py::str("csharp"), &_emit_csharp},
    {py::str("rust"), &_emit_rust},
};
const py::dict<py::str, py::str> LANG_LABEL = {
    {py::str("c"), py::str("C")},
    {py::str("csharp"), py::str("C#")},
    {py::str("rust"), py::str("Rust")},
};

Result run(const py::str& java_dir, const py::str& out_dir, const py::str& language) {
    if (!_EMIT.contains(language)) {
        throw py::ValueError("no scaffold emitter for language " + py::repr(language).utf8());
    }
    Emitter emit = _EMIT[language];
    if (!py::os::path::isdir(out_dir)) {
        py::os::makedirs(out_dir);
    }
    py::list<py::str> written;
    for (const py::str& path : _discover(java_dir)) {
        py::ref<jir::JClass> cls;
        try {
            cls = parse::parse_file(path);
        } catch (const std::exception&) {                      // skip a file that won't parse
            continue;
        }
        if (!cls || !py::truthy(cls->name)) {
            continue;
        }
        auto [name, content] = emit(cls);
        py::file f = py::open(py::os::path::join(out_dir, name), py::str("w"), py::str("utf-8"));
        f.write(content);
        f.close();
        written.append(name);
    }
    // a short README so the skeleton nature is obvious
    py::str label = LANG_LABEL.get(language, language);
    py::file f = py::open(py::os::path::join(out_dir, py::percent(py::str("SKELETON_%s.md"), language.upper())),
                          py::str("w"), py::str("utf-8"));
    f.write(py::percent(py::str("# %s skeleton output\n\nGenerated by CodeBreaker. These are STRUCTURAL skeletons (types, "
                                "fields, method signatures as stubs) showing how the port maps into %s -- not a working "
                                "translation. C++ is the fully-translated target.\n\n- classes: %d\n"),
                        label, label, py::len(written)));
    f.close();
    Result r;
    r.written = written;
    r.classes = py::len(written);
    r.language = language;
    return r;
}

