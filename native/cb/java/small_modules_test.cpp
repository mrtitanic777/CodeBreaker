// ---- paths -----------------------------------------------------------------------------------------------

CB_TEST("java.paths.join", [] {
    JavaData data(stdfs::path("root") / "java");
    CB_CHECK_EQ(fs::to_text(data.path({"platform", "canonical"})), "root/java/platform/canonical");
    CB_CHECK_EQ(fs::to_text(data.path({})), "root/java");
});

CB_TEST("java.paths.locate_from_env", [] {
    fs::ScopedTempDir tmp("cbjava");
    fs::make_dirs(tmp.path() / "codebreaker" / "java");
    fs::ScopedEnv env("CB_CHECKOUT_ROOT", fs::to_text(tmp.path()));
    CB_CHECK(fs::same_path(JavaData::locate().root(), tmp.path() / "codebreaker" / "java"));
});

// ---- textutil --------------------------------------------------------------------------------------------

CB_TEST("java.textutil.literals", [] {
    using textutil::Span;
    const std::string s = R"(a "x\"y" b 'c' "unterminated)";
    auto spans = textutil::literal_spans(s);
    CB_CHECK_EQ(spans.size(), std::size_t{2});
    CB_CHECK_EQ(s.substr(spans[0].begin, spans[0].end - spans[0].begin), R"("x\"y")");
    CB_CHECK_EQ(s.substr(spans[1].begin, spans[1].end - spans[1].begin), "'c'");
    // the other quote kind inside a literal does not end it
    CB_CHECK_EQ(textutil::literal_at("\"it's\"", 0)->end, std::size_t{6});
    // a literal does not start where there is no quote; a backslash before a newline kills it
    CB_CHECK(!textutil::literal_at("abc", 0));
    CB_CHECK(!textutil::literal_at("\"a\\\nb\"", 0));
    CB_CHECK(textutil::literal_spans("").empty());
    // a newline inside is allowed (only an escaped newline is not)
    CB_CHECK(textutil::literal_at("\"a\nb\"", 0).has_value());
});

CB_TEST("java.textutil.read_write", [] {
    fs::ScopedTempDir tmp("cbjava");
    const stdfs::path file = tmp.path() / "sub" / "t.txt";
    textutil::write_text(file, "line1\r\nline2\rline3\n");
    CB_CHECK_EQ(textutil::read_text(file), "line1\nline2\nline3\n");   // newlines normalised on read
    CB_CHECK(!textutil::try_read_text(tmp.path() / "missing.txt"));
    CB_CHECK(!textutil::try_read_text(tmp.path()));                    // a directory is not a text file
    CB_CHECK_THROWS_AS(NotFoundError, textutil::read_text(tmp.path() / "missing.txt"));
});

CB_TEST("java.textutil.decode_modes", [] {
    fs::ScopedTempDir tmp("cbjava");
    const stdfs::path file = tmp.path() / "bad.txt";
    const std::string bad = "ok\xFF" "end";
    fs::write_text(file, bad);
    CB_CHECK_EQ(textutil::read_text(file), "ok\xEF\xBF\xBD" "end");                // replaced by U+FFFD
    CB_CHECK_THROWS_AS(FormatError, textutil::read_text(file, textutil::Decode::Strict));
    CB_CHECK_EQ(textutil::read_text(file, textutil::Decode::Replace).size(), std::size_t{8});
});

// ---- cmake -----------------------------------------------------------------------------------------------

CB_TEST("java.cmake.template", [] {
    const std::string t = java::cmake::cmakelists_text("MinecraftBeta");
    CB_CHECK(t.starts_with("# Generated by CodeBreaker (java -> C++, platform pc_opengl). Build:"));
    CB_CHECK(t.find("project(MinecraftBeta CXX)") != std::string::npos);
    CB_CHECK(t.find("add_executable(MinecraftBeta ${J2X_SOURCES})") != std::string::npos);
    CB_CHECK(t.find("{name}") == std::string::npos);                       // every placeholder filled
    CB_CHECK(t.find("${CMAKE_CURRENT_SOURCE_DIR}/*.cpp") != std::string::npos);   // CMake's own variables untouched
    CB_CHECK(t.find("$<TARGET_FILE_DIR:MinecraftBeta>/Content") != std::string::npos);

    // the text the Python module produced for the same name (reviewed: same CMake, line for line)
    CB_CHECK_EQ(java::cmake::cmakelists_text("Game"), fs::read_text(testing::data_path("java/testdata/cmake_Game.golden.txt")));

    fs::ScopedTempDir tmp("cbjava");
    const stdfs::path written = java::cmake::write_cmakelists(tmp.path(), "Game");
    CB_CHECK_EQ(written.filename().string(), "CMakeLists.txt");
    CB_CHECK_EQ(fs::read_text(written), java::cmake::cmakelists_text("Game"));
});

// ---- overlays --------------------------------------------------------------------------------------------

CB_TEST("java.overlays.project_key", [] {
    using java::overlays::project_key;
    CB_CHECK_EQ(project_key("out/MinecraftBeta"), "MinecraftBeta");
    CB_CHECK_EQ(project_key("out/MinecraftBeta/"), "MinecraftBeta");
    CB_CHECK_EQ(project_key("out/a/../MinecraftAlpha"), "MinecraftAlpha");
    CB_CHECK_EQ(project_key(""), "");
    CB_CHECK(!project_key(".").empty());   // "." is the current folder, named by its own name
});

CB_TEST("java.overlays.resolve", [] {
    using java::overlays::resolve_overlay_dir;
    auto r = resolve_overlay_dir("out/MinecraftBeta", "state/java/overlays");
    CB_CHECK(r.has_value());
    CB_CHECK_EQ(fs::to_text(*r), "state/java/overlays/MinecraftBeta");
    auto e = resolve_overlay_dir("out/X", "root", stdfs::path("elsewhere"));
    CB_CHECK_EQ(fs::to_text(*e), "elsewhere");                               // an explicit folder wins
    CB_CHECK(!resolve_overlay_dir("", "root"));                              // no project, no overlay
});

CB_TEST("java.overlays.apply", [] {
    fs::ScopedTempDir tmp("cbjava");
    const stdfs::path overlay = tmp.path() / "overlay";
    const stdfs::path out = tmp.path() / "out";
    fs::write_text(overlay / "A.cpp", "overlaid");
    fs::write_text(overlay / "sub" / "Socket.cpp", "new file");
    fs::write_text(overlay / "MANIFEST.md", "not copied");
    fs::write_text(out / "A.cpp", "generated");

    std::vector<std::string> log;
    auto applied = java::overlays::apply_overlays(out, overlay, [&](std::string_view s) { log.emplace_back(s); });
    CB_CHECK_EQ(applied.size(), std::size_t{2});
    CB_CHECK_EQ(applied[0], "A.cpp");
    CB_CHECK_EQ(applied[1], "sub/Socket.cpp");
    CB_CHECK_EQ(fs::read_text(out / "A.cpp"), "overlaid");                    // replaced
    CB_CHECK_EQ(fs::read_text(out / "sub" / "Socket.cpp"), "new file");       // added, folder created
    CB_CHECK(!stdfs::exists(out / "MANIFEST.md"));
    CB_CHECK_EQ(log.size(), std::size_t{3});
    CB_CHECK_EQ(log[0], "[overlay] replaced A.cpp");
    CB_CHECK_EQ(log[1], "[overlay] ADDED    sub/Socket.cpp");
    CB_CHECK(log[2].starts_with("[overlay] applied 2 project overlay file(s) (1 new) from "));

    // absent or missing overlay folder: nothing happens
    CB_CHECK(java::overlays::apply_overlays(out, std::nullopt).empty());
    CB_CHECK(java::overlays::apply_overlays(out, tmp.path() / "nope").empty());
});

