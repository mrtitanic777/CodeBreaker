using namespace cb;
namespace fp = cb::recompile::builders::floating;
using cb::recompile::builders::Instruction;
using cb::recompile::builders::MemoryOperand;
using cb::recompile::builders::Operands;

namespace {

// Operand tokens as the recompiler spells them: "f4", "cr6", "r3".
class Tokens : public Operands {
public:
    std::optional<int> reg(std::string_view t) const override { return number(t, "r"); }
    std::optional<int> vreg(std::string_view t) const override { return number(t, "v"); }
    std::optional<int> freg(std::string_view t) const override { return number(t, "f"); }
    std::optional<int> cr(std::string_view t) const override { return number(t, "cr"); }
    std::optional<std::int64_t> imm(std::string_view) const override { return std::nullopt; }
    std::optional<MemoryOperand> mem(std::string_view) const override { return std::nullopt; }
    std::string register_value(int n, std::string_view field) const override { return "ctx.r" + std::to_string(n) + "." + std::string(field); }
    std::string base_expression(int base) const override { return "ctx.r" + std::to_string(base) + ".u32"; }
    std::string address(std::int64_t, int base) const override { return base_expression(base); }

private:
    static std::optional<int> number(std::string_view token, std::string_view prefix) {
        if (!token.starts_with(prefix)) return std::nullopt;
        token.remove_prefix(prefix.size());
        return text::parse_int<int>(token);
    }
};

struct Case {
    std::string mnemonic;
    std::vector<std::string> operands;
    std::vector<std::string> statements;
};

// floating.golden.txt: "## <mnemonic> <operands>" then the statements the builder must give, from the reference
// implementation (generated by testdata/gen_floating_golden.py, reviewed line by line against the builder's rules).
std::vector<Case> golden(std::vector<std::string>& helper_lines) {
    std::vector<Case> cases;
    bool in_helpers = false;
    const std::string body = fs::read_text(testing::data_path("recompile/testdata/floating.golden.txt"));
    for (std::string_view line : text::lines(body)) {
        if (line.starts_with("## helpers")) {
            in_helpers = true;
        } else if (line.starts_with("## ")) {
            const auto words = text::split_ws(line.substr(3));
            Case c;
            c.mnemonic = std::string(words[0]);
            for (std::size_t i = 1; i < words.size(); ++i) c.operands.emplace_back(words[i]);
            cases.push_back(std::move(c));
        } else if (in_helpers) {
            helper_lines.emplace_back(line);
        } else {
            cases.back().statements.emplace_back(line);
        }
    }
    return cases;
}

}  // namespace

CB_TEST("recompile.floating.every_mnemonic_matches_the_reference", [] {
    std::vector<std::string> helper_lines;
    const std::vector<Case> cases = golden(helper_lines);
    CB_CHECK_EQ(cases.size(), 32u);
    const Tokens tokens;
    for (const Case& c : cases) {
        const std::optional<std::vector<std::string>> got = fp::emit({c.mnemonic, c.operands, 0x82000000}, tokens);
        CB_CHECK(got.has_value());
        if (got) CB_CHECK((*got) == (c.statements));
    }
    // the list of mnemonics is the set the builder answers to, in the reference's order
    const auto names = fp::mnemonics();
    CB_CHECK_EQ(names.size(), cases.size());
    for (std::size_t i = 0; i < cases.size() && i < names.size(); ++i) CB_CHECK_EQ(std::string(names[i]), cases[i].mnemonic);
    CB_CHECK_EQ(fp::runtime_helpers(), "#include <cmath>\n#include <climits>\n");
    CB_CHECK((helper_lines) == ((std::vector<std::string>{"#include <cmath>", "#include <climits>"})));
});

CB_TEST("recompile.floating.fused_multiply_add_reads_a_c_b_in_that_order", [] {
    const Tokens tokens;
    const std::vector<std::string> ops = {"f1", "f2", "f3", "f4"};   // d=1, a=2, c=3, b=4
    const auto got = fp::emit({"fmadd", ops, 0}, tokens);
    CB_CHECK(got.has_value());
    if (got) CB_CHECK_EQ(got->at(1), "ctx.f1.f64 = ctx.f2.f64 * ctx.f3.f64 + ctx.f4.f64;");
    const auto sel = fp::emit({"fsel", ops, 0}, tokens);
    CB_CHECK(sel.has_value());
    if (sel) CB_CHECK_EQ(sel->at(1), "ctx.f1.f64 = ctx.f2.f64 >= 0.0 ? ctx.f3.f64 : ctx.f4.f64;");
}
);

CB_TEST("recompile.floating.other_mnemonics_are_not_ours", [] {
    const Tokens tokens;
    const std::vector<std::string> ops = {"r3", "r4", "r5"};
    CB_CHECK(!fp::emit({"add", ops, 0}, tokens).has_value());
    CB_CHECK(!fp::emit({"lfd", ops, 0}, tokens).has_value());     // the memory builder's
    CB_CHECK(!fp::emit({"fctiw", ops, 0}, tokens).has_value());   // no builder for fctiw: only fctiwz
    CB_CHECK(!fp::emit({"", ops, 0}, tokens).has_value());
});

CB_TEST("recompile.floating.bad_operands_are_parse_errors", [] {
    const Tokens tokens;
    const std::vector<std::string> gpr = {"r3", "r4"};
    CB_CHECK_THROWS_AS(ParseError, (void)fp::emit({"fmr", gpr, 0}, tokens));         // not floating-point registers
    const std::vector<std::string> short_list = {"f3"};
    CB_CHECK_THROWS_AS(ParseError, (void)fp::emit({"fmr", short_list, 0}, tokens));  // operand 2 missing
    const std::vector<std::string> no_cr = {"f1", "f2", "f3"};
    CB_CHECK_THROWS_AS(ParseError, (void)fp::emit({"fcmpu", no_cr, 0}, tokens));     // crfD must come first
    const std::vector<std::string> three = {"f1", "f2", "f3"};
    CB_CHECK_THROWS_AS(ParseError, (void)fp::emit({"fmadd", three, 0}, tokens));     // needs four
    CB_CHECK_THROWS_AS(ParseError, (void)fp::emit({"fadd", {}, 0}, tokens));
});
