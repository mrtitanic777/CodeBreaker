// ===========================================================================
//  TEXTURE UNTILER  (real - Xenos tiled surface -> linear)
// ===========================================================================
// The Xenos stores 2D textures in a swizzled ("tiled") layout: 32x32-texel
// macro-tiles with a nested micro-tile swizzle. Converting to a linear texture a
// PC GPU can sample is a pure per-texel address remap (+ endian swap for the
// wider formats). This is the documented Xenos hardware tiling function (the
// swizzle published in the free60/libxenon GPU notes); the implementation here
// is our own. It is bounded and exact - not a stub.
//
// Returns the BYTE offset of texel (x,y) inside a tiled surface whose width is
// `width` blocks and whose texel/block size is 2^log2_bpp bytes.
static uint32_t XeTiledOffset2D(uint32_t x, uint32_t y,
                                uint32_t width, uint32_t log2_bpp) {
    uint32_t aligned_width = (width + 31u) & ~31u;
    // macro tile: which 32x32 tile, scaled by tile byte-size
    uint32_t macro = ((x >> 5) + (y >> 5) * (aligned_width >> 5)) << (log2_bpp + 7);
    // micro tile: position within the 32x32 tile
    uint32_t micro = ((x & 7u) + ((y & 6u) << 2)) << log2_bpp;
    uint32_t offset = macro +
                      ((micro & ~15u) << 1) + (micro & 15u) +
                      ((y & 8u) << (3 + log2_bpp)) + ((y & 1u) << 4);
    // final nested swizzle
    return ((offset & ~511u) << 3) + ((offset & 448u) << 2) + (offset & 63u) +
           ((y & 16u) << 7) + (((((y & 8u) >> 2) + (x >> 3)) & 3u) << 6);
}

// Untile a whole 2D surface into a linear buffer. `bytes_per_texel` is 1/2/4/...;
// `endian` swaps 2- or 4-byte texels (Xenos surfaces are big-endian) when set.
void UntileTexture2D(uint8_t* dst_linear, const uint8_t* src_tiled,
                     uint32_t width, uint32_t height,
                     uint32_t bytes_per_texel, bool endian) {
    uint32_t log2_bpp = 0;
    for (uint32_t b = bytes_per_texel; b > 1; b >>= 1) ++log2_bpp;
    for (uint32_t y = 0; y < height; ++y) {
        uint8_t* row = dst_linear + (size_t)y * width * bytes_per_texel;
        for (uint32_t x = 0; x < width; ++x) {
            uint32_t src = XeTiledOffset2D(x, y, width, log2_bpp);
            uint8_t* d = row + (size_t)x * bytes_per_texel;
            const uint8_t* s = src_tiled + src;
            if (endian && bytes_per_texel == 4) {
                d[0] = s[3]; d[1] = s[2]; d[2] = s[1]; d[3] = s[0];
            } else if (endian && bytes_per_texel == 2) {
                d[0] = s[1]; d[1] = s[0];
            } else {
                std::memcpy(d, s, bytes_per_texel);
            }
        }
    }
}

