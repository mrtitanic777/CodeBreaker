"""Stubs for every kernel/XAM import the recompiled code references that the runtime does not implement.

The imports come from XenonRecomp's function mappings (`__imp__Name`; pass every module's mapping when several are
linked into one program); the implemented ones are the `GUEST_IMPORT(Name)` definitions in the runtime's kernel
sources. Each stub reports the call (its name, arguments and caller) through kernel::UnimplementedImport.

Usage: gen_import_stubs.py <runtime kernel source dir> <output .cpp> <ppc_func_mapping.cpp>...
An argument @<file> stands for the paths listed in that file, one per line (a long list would pass cmd.exe's
8191-character command line).
"""
import os
import re
import sys


def main():
    kernel_dir, out = sys.argv[1:3]
    mappings = []
    for a in sys.argv[3:]:
        if a.startswith('@'):
            mappings += [line.strip() for line in open(a[1:]) if line.strip()]
        else:
            mappings.append(a)
    imports = set()
    for mapping in mappings:
        imports |= set(re.findall(r'\b__imp__(\w+)\b', open(mapping).read()))
    # recompiled functions (__imp__sub_XXXXXXXX) and the fixed symbols (helpers, _xstart) are not imports
    imports = sorted(n for n in imports if not re.match(r'(sub_[0-9A-F]+\w*|__(save|rest)\w+|_xstart\w*)$', n))
    implemented = set()
    for root, _, files in os.walk(kernel_dir):
        for name in files:
            if name.endswith('.cpp'):
                with open(os.path.join(root, name), encoding='utf-8', errors='replace') as f:
                    implemented |= set(re.findall(r'^\s*GUEST_IMPORT\((\w+)\)', f.read(), re.M))
    missing = [n for n in imports if n not in implemented]
    lines = ['// Generated by native/x360/tools/gen_import_stubs.py. Do not edit.',
             f'// {len(imports) - len(missing)} of {len(imports)} imports implemented; {len(missing)} stubs below.',
             '#include "kernel/kernel.h"', '']
    lines += [f'PPC_FUNC(__imp__{name}) {{ kernel::UnimplementedImport("{name}", ctx); }}' for name in missing]
    text = '\n'.join(lines) + '\n'
    if not os.path.exists(out) or open(out).read() != text:
        with open(out, 'w', newline='\n') as f:
            f.write(text)
    print(f'imports: {len(imports)} total, {len(imports) - len(missing)} implemented, {len(missing)} stubbed')


if __name__ == '__main__':
    main()
