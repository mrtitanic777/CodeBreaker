"""Stubs for every kernel/XAM import the recompiled code references that the runtime does not implement.

The imports come from XenonRecomp's function mappings (`__imp__Name`; pass every module's mapping when several are
linked into one program); the implemented ones are the `GUEST_IMPORT(Name)` definitions in the runtime's kernel
sources. Each stub reports the call (its name, arguments and caller) through kernel::UnimplementedImport. A
GUEST_IMPORT no module imports is counted, not an error (a runtime shared by programs implements other modules'
imports).

Usage: gen_import_stubs.py [--forward] <runtime kernel source dir> <output .cpp> <ppc_func_mapping.cpp>...
An argument @<file> stands for the paths listed in that file, one per line (a long list would pass cmd.exe's
8191-character command line). --forward: a stub first asks kernel::XamForward for the import (the recompiled XAM's
export of that name, when the runtime runs one: the Xbox 360 Dashboard's) and reports it unimplemented only when
there is none.
"""
import os
import re
import sys


def main():
    args = sys.argv[1:]
    forward = '--forward' in args
    args = [a for a in args if a != '--forward']
    kernel_dir, out = args[:2]
    mappings = []
    for a in args[2:]:
        if a.startswith('@'):
            mappings += [line.strip() for line in open(a[1:]) if line.strip()]
        else:
            mappings.append(a)
    imports = set()
    for mapping in mappings:
        imports |= set(re.findall(r'\b__imp__(\w+)\b', open(mapping).read()))
    # Recompiled functions (__imp__sub_XXXXXXXX, or a module's own function_prefix: signup_XXXXXXXX; with
    # suffix_function_names also the module's suffix: sub_XXXXXXXX_dash_7258) and the fixed symbols (helpers,
    # _xstart, with their module suffix) are not imports.
    imports = sorted(n for n in imports
                     if not re.match(r'([a-z]+_[0-9A-F]+(_\w+)?|__(save|rest)\w+|_xstart\w*)$', n))
    implemented = set()
    for root, _, files in os.walk(kernel_dir):
        for name in files:
            if name.endswith('.cpp') and name != 'imports_unimplemented.cpp':
                with open(os.path.join(root, name), encoding='utf-8', errors='replace') as f:
                    implemented |= set(re.findall(r'^\s*GUEST_IMPORT\((\w+)\)', f.read(), re.M))
    unused = implemented - set(imports)
    missing = [n for n in imports if n not in implemented]
    lines = ['// Generated by native/x360/tools/gen_import_stubs.py. Do not edit.',
             f'// {len(imports) - len(missing)} of {len(imports)} imports implemented; {len(missing)} stubs below.',
             '#include "kernel/kernel.h"', '']
    for name in missing:
        if forward:
            lines.append(f'PPC_FUNC(__imp__{name}) {{ static PPCFunc* const f = kernel::XamForward("{name}"); '
                         f'if (f) return f(ctx, base); kernel::UnimplementedImport("{name}", ctx); }}')
        else:
            lines.append(f'PPC_FUNC(__imp__{name}) {{ kernel::UnimplementedImport("{name}", ctx); }}')
    text = '\n'.join(lines) + '\n'
    if not os.path.exists(out) or open(out).read() != text:
        with open(out, 'w', newline='\n') as f:
            f.write(text)
    print(f'imports: {len(imports)} total, {len(imports) - len(missing)} implemented, {len(missing)} stubbed'
          f' ({len(unused)} GUEST_IMPORTs not imported by these modules)')


if __name__ == '__main__':
    main()
