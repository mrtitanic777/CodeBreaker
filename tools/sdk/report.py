# SDK phase 0: turns facts.json (inventory.py) into docs/sdk/inventory.md and docs/sdk/inventory_raw.tsv.
import json, sys
from collections import defaultdict

FACTS = sys.argv[1] if len(sys.argv) > 1 else 'work/sdk-inventory/facts.json'
MD = sys.argv[2] if len(sys.argv) > 2 else 'docs/sdk/inventory.md'
TSV = sys.argv[3] if len(sys.argv) > 3 else 'docs/sdk/inventory_raw.tsv'
f = json.load(open(FACTS, encoding='utf-8'))
files, edges, used = f['files'], f['edges'], f['used']

# the intended layering of docs/SDK_DESIGN.md, lowest first; an include from a lower layer into a higher one points up
LAYERS = [['core', 'base'], ['formats', 'symbols', 'store', 'knowledge', 'jobs'],
          ['decompile', 'emulate', 'analyze', 'invert', 'exact', 'coverage', 'compare'],
          ['translate', 'source', 'build', 'dotnet', 'java', 'xna', 'recompile', 'port', 'platforms', 'verify'],
          ['engine'], ['app', 'ui']]
LAYER = {a: i for i, layer in enumerate(LAYERS) for a in layer}

area_lines, area_files = defaultdict(int), defaultdict(int)
for rel, m in files.items():
    area_lines[m['area']] += m['lines']
    area_files[m['area']] += 1
areas = sorted(a for a in area_lines if a != '(root)')

prod = defaultdict(lambda: defaultdict(int))     # area -> area -> include count (product code)
testdep = defaultdict(lambda: defaultdict(int))
hdr_users = defaultdict(lambda: defaultdict(set))   # header -> area -> including files (outside its area)
for frm, to in edges:
    a, b = files[frm]['area'], files[to]['area']
    if a == b or a == '(root)' or b == '(root)':
        continue
    (testdep if files[frm]['test'] else prod)[a][b] += 1
    hdr_users[to][a].add(frm)

# cycles: strongly connected components of the product graph (Tarjan)
idx, low, stack, on, sccs, n = {}, {}, [], set(), [], [0]
def strong(v):
    idx[v] = low[v] = n[0]; n[0] += 1; stack.append(v); on.add(v)
    for w in prod[v]:
        if w not in idx:
            strong(w); low[v] = min(low[v], low[w])
        elif w in on:
            low[v] = min(low[v], idx[w])
    if low[v] == idx[v]:
        comp = []
        while True:
            w = stack.pop(); on.discard(w); comp.append(w)
            if w == v: break
        if len(comp) > 1: sccs.append(sorted(comp))
sys.setrecursionlimit(10000)
for a in areas:
    if a not in idx: strong(a)

up = []   # (from, to, count, worst files)
for a in areas:
    for b, c in prod[a].items():
        if a in LAYER and b in LAYER and LAYER[a] < LAYER[b]:
            worst = defaultdict(int)
            for frm, to in edges:
                if files[frm]['area'] == a and files[to]['area'] == b and not files[frm]['test']:
                    worst[frm] += 1
            up.append((a, b, c, sorted(worst.items(), key=lambda kv: -kv[1])[:3]))
up.sort(key=lambda t: -t[2])

fan_in = {a: sum(prod[x].get(a, 0) for x in areas) for a in areas}
fan_in_areas = {a: sorted(x for x in areas if prod[x].get(a)) for a in areas}
pub = defaultdict(list)    # area -> [(header, users-areas, files)]
for h, by in hdr_users.items():
    pub[files[h]['area']].append((h, sorted(by), sum(len(s) for s in by.values())))
for a in pub:
    pub[a].sort(key=lambda t: (-len(t[1]), -t[2]))

out = []
w = out.append
w('# SDK phase 0: the inventory of src/\n')
w('What each area of `src/` is actually used for by the others: its de facto public surface. Generated by '
  '`tools/sdk/inventory.py` and `tools/sdk/report.py` (`python tools/sdk/inventory.py src work/sdk-inventory/facts.json && python tools/sdk/report.py`) from the `#include` lines of every source file (third_party, testdata and '
  'tests folders left out). The design this feeds is [SDK_DESIGN.md](../SDK_DESIGN.md); phase 1 turns it into one public face per area.\n')
total = sum(area_lines[a] for a in areas)
w(f'{len(areas)} areas, {sum(area_files[a] for a in areas):,} files, {total:,} lines; '
  f'{sum(sum(v.values()) for v in prod.values()):,} includes cross an area boundary in product code, '
  f'{sum(sum(v.values()) for v in testdep.values()):,} more in tests.\n')

w('## Summary\n')
w(f'- **Cycles:** {len(sccs)} group(s) of areas that include each other, directly or around a loop: ' +
  ('; '.join(', '.join(c) for c in sccs) if sccs else 'none') + '.')
w(f'- **Upward includes** (a lower layer reaching into a higher one, against the layering in SDK_DESIGN.md): {len(up)} area pairs, '
  f'{sum(t[2] for t in up):,} includes.')
leaked = [(h, u, c) for a in pub for (h, u, c) in pub[a] if len(u) >= 3]
w(f'- **Widely shared headers** (included from 3 or more other areas): {len(leaked)}.')
w('- **Messiest public faces** (most distinct headers used from outside, then most using areas):')
mess = sorted(areas, key=lambda a: (-len(pub[a]), -len(fan_in_areas[a])))[:8]
for a in mess:
    w(f'  - `{a}`: {len(pub[a])} headers used from {len(fan_in_areas[a])} other areas ({fan_in[a]:,} includes)')
w('')

w('## Areas\n')
w('| Area | Layer | Lines | Files | Used by (areas) | Uses (areas) | Headers used from outside |')
w('|---|---|---:|---:|---:|---:|---:|')
for a in sorted(areas, key=lambda a: (LAYER.get(a, 99), a)):
    w(f'| `{a}` | {LAYER.get(a, "?")} | {area_lines[a]:,} | {area_files[a]:,} | {len(fan_in_areas[a])} | {len(prod[a])} | {len(pub[a])} |')
w('')

w('## Upward includes\n')
w('Each row: a lower area including a higher one, with the files doing most of it. These are the first things phase 1 has to turn '
  'around (move the shared piece down, or invert the dependency with an interface the lower area owns).\n')
w('| From | To | Includes | Worst files |')
w('|---|---|---:|---|')
for a, b, c, worst in up[:60]:
    w(f'| `{a}` | `{b}` | {c} | ' + ', '.join(f'`{p}` ({k})' for p, k in worst) + ' |')
if len(up) > 60:
    w(f'\n({len(up) - 60} smaller pairs in inventory_raw.tsv.)')
w('')

w('## Each area\'s de facto public surface\n')
w('The headers other areas include, most widely used first, with the declarations they use most. A good public face keeps the top '
  'few and makes the rest private.\n')
for a in sorted(areas, key=lambda a: (LAYER.get(a, 99), a)):
    hs = pub[a]
    w(f'### `{a}`\n')
    w(f'{area_lines[a]:,} lines; used by {len(fan_in_areas[a])} areas ({", ".join(fan_in_areas[a]) or "none"}); '
      f'{len(hs)} of its headers are included from outside.\n')
    for h, by, c in hs[:12]:
        top = list(used.get(h, {}).items())[:6]
        w(f'- `{h}`: {c} files in {len(by)} areas ({", ".join(by)})' + (' -- uses ' + ', '.join(f'`{d}`' for d, _ in top) if top else ''))
    if len(hs) > 12:
        w(f'- ... and {len(hs) - 12} more (inventory_raw.tsv)')
    w('')

open(MD, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
with open(TSV, 'w', encoding='utf-8', newline='\n') as t:
    t.write('kind\tfrom\tto\tcount\tdetail\n')
    for a in areas:
        for b, c in sorted(prod[a].items()):
            t.write(f'area\t{a}\t{b}\t{c}\t{"up" if a in LAYER and b in LAYER and LAYER[a] < LAYER[b] else ""}\n')
    for a in areas:
        for h, by, c in pub[a]:
            t.write(f'header\t{",".join(by)}\t{h}\t{c}\t{" ".join(list(used.get(h, {}))[:20])}\n')
print(f'{MD}: {len(sccs)} cycles, {len(up)} upward pairs, {len(leaked)} widely shared headers')
