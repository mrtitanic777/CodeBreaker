# -*- coding: utf-8 -*-
r"""
scaffold.py -- emit SKELETON output for the non-C++ target languages (C / C# / Rust).

C++ is the fully-translated target. The other languages are scaffolds: for each Java class we emit a
single file in the target language with the type/struct shape, the fields, and the method signatures as
unimplemented stubs -- enough to SEE how the port would be structured in that language, not a working
translation. This is what the language picker's "coming soon" options produce so the whole flow is real.
"""

import os
import re


def _discover(java_dir):
    out = []
    for dp, _dirs, files in os.walk(java_dir):
        for f in files:
            if f.endswith('.java'):
                out.append(os.path.join(dp, f))
    return sorted(out)


def _snake(name):
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name)
    return s.lower()


# --- type mapping per language (skeleton fidelity, not exact) --------------
_C = {'int': 'int', 'long': 'long long', 'short': 'short', 'byte': 'signed char', 'char': 'char',
      'boolean': 'int', 'float': 'float', 'double': 'double', 'void': 'void', 'String': 'const char*'}
_CS = {'int': 'int', 'long': 'long', 'short': 'short', 'byte': 'byte', 'char': 'char',
       'boolean': 'bool', 'float': 'float', 'double': 'double', 'void': 'void', 'String': 'string'}
_RS = {'int': 'i32', 'long': 'i64', 'short': 'i16', 'byte': 'i8', 'char': 'char',
       'boolean': 'bool', 'float': 'f32', 'double': 'f64', 'void': '()', 'String': 'String'}


def _jtype_name(jt):
    return getattr(jt, 'name', 'void') if jt is not None else 'void'


def _arr(jt):
    return getattr(jt, 'array_dims', 0) if jt is not None else 0


def _ctype(jt):
    base = _C.get(_jtype_name(jt), 'void*')                # unknown class -> opaque pointer
    if base not in _C.values():
        base = '%s*' % _jtype_name(jt)                     # a known class name -> pointer to its struct
    return base + ('*' if _arr(jt) else '')


def _cstype(jt):
    n = _jtype_name(jt)
    base = _CS.get(n, n)                                   # C# keeps class names as-is
    return base + ('[]' if _arr(jt) else '')


def _rstype(jt):
    n = _jtype_name(jt)
    base = _RS.get(n, n)
    if _arr(jt):
        return 'Vec<%s>' % base
    return base


def _params(method, render):
    return ', '.join('%s %s' % (render(p.jtype), p.name) for p in getattr(method, 'params', []))


def _rparams(method):
    """Rust parameter order: `name: type`."""
    return ', '.join('%s: %s' % (_snake(p.name), _rstype(p.jtype))
                     for p in getattr(method, 'params', []))


# --- C ---------------------------------------------------------------------
def _emit_c(cls):
    guard = _snake(cls.name).upper() + '_H'
    L = ['/* %s.h -- SKELETON (C) generated by j2ctool. Not a working translation. */' % cls.name,
         '#ifndef %s' % guard, '#define %s' % guard, '',
         'typedef struct %s {' % cls.name]
    inst = [f for f in cls.fields if not getattr(f, 'is_static', False)]
    for f in inst:
        L.append('    %s %s;' % (_ctype(f.jtype), f.name))
    if not inst:
        L.append('    int _placeholder;')
    L += ['} %s;' % cls.name, '', '/* methods (free functions taking the struct as self) */']
    for m in cls.methods:
        if getattr(m, 'is_ctor', False):
            L.append('%s* %s_new(%s);' % (cls.name, cls.name, _params(m, _ctype)))
            continue
        ret = _ctype(m.return_type)
        args = _params(m, _ctype)
        if getattr(m, 'is_static', False):                # static -> no self
            L.append('%s %s_%s(%s);' % (ret, cls.name, m.name, args))
        else:
            sep = ', ' if args else ''
            L.append('%s %s_%s(%s* self%s%s);' % (ret, cls.name, m.name, cls.name, sep, args))
    L += ['', '#endif /* %s */' % guard, '']
    return '%s.h' % cls.name, '\n'.join(L)


# --- C# --------------------------------------------------------------------
def _emit_csharp(cls):
    base = ' : %s' % cls.parent if getattr(cls, 'parent', None) else ''
    L = ['// %s.cs -- SKELETON (C#) generated by j2ctool. Not a working translation.' % cls.name, '',
         'public class %s%s' % (cls.name, base), '{']
    for f in cls.fields:
        st = 'static ' if getattr(f, 'is_static', False) else ''
        L.append('    public %s%s %s;' % (st, _cstype(f.jtype), f.name))
    for m in cls.methods:
        if getattr(m, 'is_ctor', False):
            L.append('    public %s(%s) { throw new System.NotImplementedException(); }'
                     % (cls.name, _params(m, _cstype)))
            continue
        st = 'static ' if getattr(m, 'is_static', False) else ''
        L.append('    public %s%s %s(%s) { throw new System.NotImplementedException(); }'
                 % (st, _cstype(m.return_type), m.name, _params(m, _cstype)))
    L += ['}', '']
    return '%s.cs' % cls.name, '\n'.join(L)


# --- Rust ------------------------------------------------------------------
def _emit_rust(cls):
    L = ['// %s -- SKELETON (Rust) generated by j2ctool. Not a working translation.' % cls.name, '',
         'pub struct %s {' % cls.name]
    inst = [f for f in cls.fields if not getattr(f, 'is_static', False)]
    for f in inst:
        L.append('    pub %s: %s,' % (_snake(f.name), _rstype(f.jtype)))
    if not inst:
        L.append('    _placeholder: (),')
    L += ['}', '', 'impl %s {' % cls.name]
    for m in cls.methods:
        if getattr(m, 'is_ctor', False):
            L.append('    pub fn new(%s) -> Self { unimplemented!() }' % _rparams(m))
            continue
        ret = _rstype(m.return_type)
        arrow = '' if ret == '()' else ' -> %s' % ret
        args = _rparams(m)
        selfarg = 'self' if getattr(m, 'is_static', False) is False else ''
        if selfarg and args:
            args = '&self, ' + args
        elif selfarg:
            args = '&self'
        L.append('    pub fn %s(%s)%s { unimplemented!() }' % (_snake(m.name), args, arrow))
    L += ['}', '']
    return '%s.rs' % cls.name, '\n'.join(L)


_EMIT = {'c': _emit_c, 'csharp': _emit_csharp, 'rust': _emit_rust}
LANG_LABEL = {'c': 'C', 'csharp': 'C#', 'rust': 'Rust'}


def run(java_dir, out_dir, language):
    """Parse the Java tree and emit one skeleton file per class in `language` (c|csharp|rust). Returns
    {'written': [names], 'classes': n, 'language': language}."""
    from . import parse
    emit = _EMIT.get(language)
    if emit is None:
        raise ValueError('no scaffold emitter for language %r' % language)
    if not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    written = []
    for path in _discover(java_dir):
        try:
            cls = parse.parse_file(path)
        except Exception:                                  # skip a file that won't parse
            continue
        if cls is None or not getattr(cls, 'name', None):
            continue
        name, content = emit(cls)
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8') as f:
            f.write(content)
        written.append(name)
    # a short README so the skeleton nature is obvious
    with open(os.path.join(out_dir, 'SKELETON_%s.md' % language.upper()), 'w', encoding='utf-8') as f:
        f.write('# %s skeleton output\n\nGenerated by j2ctool. These are STRUCTURAL skeletons (types, '
                'fields, method signatures as stubs) showing how the port maps into %s -- not a working '
                'translation. C++ is the fully-translated target.\n\n- classes: %d\n'
                % (LANG_LABEL.get(language, language), LANG_LABEL.get(language, language), len(written)))
    return {'written': written, 'classes': len(written), 'language': language}
