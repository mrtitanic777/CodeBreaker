// dotnet/decompiler/documentation/xml_documentation_provider.hpp -- the documentation of a type or member read from an .xml file as the C# compiler
// writes it (`<doc><members><member name="T:Ns.Type">...</member>`): an index of where each member's text starts, then only the requested member
// is read.
//
//     XmlDocumentationProvider provider("System.Runtime.xml");
//     provider.get_documentation("T:System.String");                 // "<summary>...</summary>" (the inner XML of the member), nullopt for none
//     provider.get_documentation(entity);                            // by the entity's ID string (C# and C++/CLI forms)
//
// Ported from ILSpy (ICSharpCode.Decompiler.Documentation: XmlDocumentationProvider and its IndexEntry, XmlDocumentationCache and LinePositionMapper,
// from XmlDocumentationProvider.cs), Copyright AlphaSierraPapa for the ILSpy team, MIT (see NOTICE in dotnet/decompiler). This class first creates an
// in-memory index of the .xml file, and then uses that to read only the requested members. This way, the whole documentation is not kept in
// memory. The .xml file is only opened when necessary, the file handle is not kept open all the time. If the .xml file is changed, the index will
// automatically be recreated.
//
// The text of the file is UTF-8 (or US-ASCII): util/xml_text_reader.hpp reads no other encoding. Not ported: serialization (IDeserializationCallback);
// the cache is made empty by the constructor only. Every lookup may be made from several threads.
//
// A lookup that fails with an I/O error or an XmlError (the file was deleted, changed, or is not valid XML) reloads the index once; if that fails
// too, the index is emptied and nothing is found from then on (upstream's IOException and XmlException).
#pragma once

#include <filesystem>
#include <memory>
#include <mutex>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

#include "dotnet/decompiler/documentation/idocumentation_provider.hpp"

namespace cb::dotnet::decompiler::documentation {

// Provides documentation from an .xml file (as generated by the Microsoft C# compiler).
class XmlDocumentationProvider : public IDocumentationProvider {
public:
    // The provider of the .xml file. IoError (an IOException) when it cannot be read, XmlError when it is not valid XML. A file that says
    // `redirect="..."` names another file, which is read instead (XmlError when that is not found).
    explicit XmlDocumentationProvider(const std::filesystem::path& file_name);
    XmlDocumentationProvider(const XmlDocumentationProvider&) = delete;
    XmlDocumentationProvider& operator=(const XmlDocumentationProvider&) = delete;
    ~XmlDocumentationProvider() override = default;

    // The documentation for the member with the specified documentation key ("T:Ns.Type", "M:Ns.Type.Method(System.Int32)"); nullopt for none.
    virtual std::optional<std::string> get_documentation(std::string_view key) const;
    // The documentation for the specified member: the first of its ID string candidates (id_string_provider.hpp) that has one.
    std::optional<std::string> get_documentation(const typesystem::IEntity* entity) const override;

protected:
    // For subclasses that aggregate multiple XmlDocumentationProvider instances (see the modern .NET ref-pack lookup in xml_doc_loader.hpp). The
    // index stays empty; subclasses must override get_documentation(key) to fan out across their contributors.
    XmlDocumentationProvider();

private:
    // One member of the index: the hash of its documentation tag, and the position in the file where the documentation starts.
    struct IndexEntry {
        int hash_code = 0;
        int position_in_file = 0;
    };
    using Index = std::vector<IndexEntry>;   // sorted by hash code

    // The last 50 lookups, as upstream's XmlDocumentationCache keeps them (results that were nothing too).
    struct CacheEntry {
        bool used = false;
        std::string key;
        std::optional<std::string> value;
    };
    class Cache {
    public:
        explicit Cache(int size = 50);
        bool try_get(const std::string& key, std::optional<std::string>& value) const;
        void add(const std::string& key, const std::optional<std::string>& value);

    private:
        std::vector<CacheEntry> entries_;
        std::size_t pos_ = 0;
    };

    // Reads the index of the file with the reader (which is on the root element).
    void read_xml_doc(const std::filesystem::path& path, util::XmlTextReader& reader) const;
    std::optional<std::string> get_documentation_core(const std::string& key, bool allow_reload) const;
    std::optional<std::string> reload_and_get_documentation(const std::string& key) const;
    std::optional<std::string> load_documentation(const std::string& key, int position_in_file) const;
    static std::filesystem::path get_redirection_target(const std::filesystem::path& xml_file_name, const std::string& target);
    std::shared_ptr<const Index> index() const;
    void set_index(Index index) const;

    std::filesystem::path file_name_;
    std::string encoding_;
    mutable std::mutex index_mutex_;
    mutable std::shared_ptr<const Index> index_ = std::make_shared<const Index>();
    mutable std::recursive_mutex cache_mutex_;
    mutable Cache cache_;
};

}  // namespace cb::dotnet::decompiler::documentation
