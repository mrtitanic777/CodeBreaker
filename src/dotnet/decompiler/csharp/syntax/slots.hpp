// dotnet/decompiler/csharp/syntax/slots.hpp -- the shared slot kinds of the C# syntax tree: one constant per distinct kind of child
// position, across every node class. A node class's own slots point at these (`kind()`), so "is this node an initializer?" is one
// comparison whatever the parent is.
//
//     node->get_child(Slots::identifier)                  // the child of that kind, typed (Identifier*), or nullptr
//     node->get_children(Slots::parameter)                // the collection of that kind (AstNodeCollection<ParameterDeclaration>&)
//     if (node->slot()->kind() == &Slots::body) ...
//     parent->add_child(argument, Slots::argument);
//
// A name is upstream's, in snake_case (`Slots.AddAccessor` is `Slots::add_accessor`); `True` and `False` are `true_` and `false_`.
// Each kind has a single child type, shown in its declaration.
//
// Ported from ILSpy (ICSharpCode.Decompiler.CSharp.Syntax: Slots, generated by ICSharpCode.Decompiler.Generators from the [Slot]
// attributes of the node classes), Copyright AlphaSierraPapa for the ILSpy team, MIT (see NOTICE in dotnet/decompiler).
