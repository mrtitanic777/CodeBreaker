// dotnet/decompiler/csharp/syntax/ast_visitor.hpp -- visitors of the C# syntax tree: one visit_* method per concrete node class (and one
// for an error node and one for a pattern placeholder). IAstVisitor returns nothing; IAstVisitorT<S> returns an S; IAstVisitorTS<T, S>
// also takes a datum of type T.
//
//     struct CountCalls : DepthFirstAstVisitor {             // depth_first_ast_visitor.hpp walks the children for you
//         int calls = 0;
//         void visit_invocation_expression(InvocationExpression& e) override { ++calls; visit_children(e); }
//     };
//     node->accept_visitor(counter);                          // AstNode::accept_visitor (void)
//     std::string text = node->accept_visitor(my_typed_visitor);   // IAstVisitorT<std::string>
//
// The method of a class is named after its upstream Visit method: VisitBinaryOperatorExpression is `visit_binary_operator_expression`,
// and the three classes whose name differs keep upstream's visit name (FunctionPointerAstType: `visit_function_pointer_type`,
// InvocationAstType: `visit_invocation_type`, TupleAstType: `visit_tuple_type`). Upstream's VisitErrorNode (the ErrorExpression's) and
// VisitPatternPlaceholder (the placeholder nodes') have the classes' other parameters.
//
// C# generic virtual methods have no C++ counterpart, and a node class would otherwise need three accept_visitor overrides; here the
// node classes override one virtual (AstNode::dispatch_to(IAstVisitor&)), and the typed visitors run through ResultVisitor /
// ResultDataVisitor, which are IAstVisitors that forward each visit to the typed one and keep what it returned. A visit method sees the
// node as its class; only forward declarations of the classes are needed here. S must be default constructible (it is what
// DepthFirstAstVisitorT returns for a node it does not handle).
//
// Ported from ILSpy (ICSharpCode.Decompiler.CSharp.Syntax: IAstVisitor, IAstVisitor<S>, IAstVisitor<T, S>, generated by
// ICSharpCode.Decompiler.Generators), Copyright AlphaSierraPapa for the ILSpy team, MIT (see NOTICE in dotnet/decompiler).
