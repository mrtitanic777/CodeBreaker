// dotnet/decompiler/csharp/record_decompiler.hpp -- what the decompiler knows about one record type (`record R(int A);`, `record struct`):
// which members the compiler generated (and so must not be written), the order of its fields and properties, which auto-properties
// the primary constructor declares, and which constructor is the primary one.
//
//     RecordDecompiler record(type_system, record_type_def, settings, token);
//     for (const IMember* m : record.fields_and_properties()) ...         // in the order Equals/ToString/GetHashCode agree on
//     if (record.method_is_generated(method)) continue;                    // Equals, GetHashCode, PrintMembers, Clone, == ...
//     const IMethod* ctor = record.primary_constructor();                  // nullptr when none was detected
//
// The generated members are recognized by matching the ILAst of their bodies (the bodies are decompiled with
// CSharpDecompiler::decompile_body_for_analysis) with what the C# compiler writes: the structure of Equals (a chain of
// EqualityComparer<T>.Default.Equals calls), GetHashCode (a multiplication by -1521134295 per member), PrintMembers and ToString
// (StringBuilder appends), the copy constructor, Deconstruct and the EqualityContract property.
//
// Ported from ILSpy (ICSharpCode.Decompiler.CSharp: RecordDecompiler, from RecordDecompiler.cs), Copyright AlphaSierraPapa for the ILSpy
// team, MIT (see NOTICE in dotnet/decompiler). Upstream's Dictionary<IField, IProperty> and the like are MemberMap (below): they keep
// the order of insertion and compare members as C# does (a specialized member equals one of the same definition and substitution).
