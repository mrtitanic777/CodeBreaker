// A dictionary keyed by members that enumerates in insertion order and treats equal members (IMember::equals) as one key.
template <class Key, class Value>
class MemberMap {
public:
    int count() const { return static_cast<int>(items_.size()); }
    bool empty() const { return items_.empty(); }
    // The value of the key, or nullptr (upstream's TryGetValue).
    const Value* find(const Key* key) const {
        auto range = index_.equal_range(key->hash_code());
        for (auto it = range.first; it != range.second; ++it)
            if (typesystem::member_equals(items_[it->second].first, key)) return &items_[it->second].second;
        return nullptr;
    }
    bool contains(const Key* key) const { return find(key) != nullptr; }
    // Dictionary.Add: std::invalid_argument for a key that is in the map.
    void add(const Key* key, Value value);
    void clear() {
        items_.clear();
        index_.clear();
    }
    const std::vector<std::pair<const Key*, Value>>& items() const { return items_; }

private:
    std::vector<std::pair<const Key*, Value>> items_;
    std::unordered_multimap<int, std::size_t> index_;
};

class RecordDecompiler {
public:
    // What GetParameterToBackingStoreMap gives for a parameter of the primary constructor: the auto-property it initializes and that
    // property's backing field.
    struct BackingStore {
        const typesystem::IParameter* parameter;
        const typesystem::IProperty* property;   // nullptr: no property
        const typesystem::IField* field;
    };

    RecordDecompiler(const typesystem::DecompilerTypeSystem& dts, const typesystem::ITypeDefinition* record_type_def, const DecompilerSettings& settings,
                     const util::CancellationToken& cancellation_token);
    RecordDecompiler(const RecordDecompiler&) = delete;
    RecordDecompiler& operator=(const RecordDecompiler&) = delete;

    // The fields and properties of the record type, interleaved as necessary to maintain Equals/ToString/etc. semantics.
    const std::vector<const typesystem::IMember*>& fields_and_properties() const { return ordered_members_; }
    // The detected primary constructor; nullptr when none was detected.
    const typesystem::IMethod* primary_constructor() const { return primary_ctor_; }
    bool is_inherited_record() const { return is_inherited_record_; }

    // Whether the member of the record type will be generated by the compiler.
    bool method_is_generated(const typesystem::IMethod* method) const;
    bool property_is_generated(const typesystem::IProperty* property) const;
    bool is_property_declared_by_primary_constructor(const typesystem::IProperty* property) const;
    // The parameters of the primary constructor with the auto-property and backing field each one stands for, in the order they were found.
    std::vector<BackingStore> get_parameter_to_backing_store_map() const;
    bool is_copy_constructor(const typesystem::IMethod* method) const;

private:
    using ILInstruction = il::ILInstruction;

    void detect_automatic_properties();
    bool is_auto_property(const typesystem::IProperty* p, const typesystem::IField** field) const;
    bool is_auto_getter(const typesystem::IMethod* method, const typesystem::IField** field) const;
    bool is_auto_setter(const typesystem::IMethod* method, const typesystem::IField** field) const;
    const typesystem::IMethod* detect_primary_constructor();
    bool is_primary_constructor(il::Block* body, const typesystem::IMethod* method, const typesystem::IMethod* unspecialized_method,
                                const std::unordered_map<std::string, const typesystem::IMember*>& name_to_member_map);
    bool validate_parameter(il::ILVariable* v, int expected_minimum_index, const typesystem::IMethod* unspecialized_method) const;
    static const typesystem::IMethod* find_chained_ctor(il::Block* body);
    static std::vector<const typesystem::IMember*> detect_member_order(const typesystem::ITypeDefinition* record_type_def,
                                                                        const MemberMap<typesystem::IField, const typesystem::IProperty*>& backing_field_to_auto_property);

    bool is_record_type(const typesystem::IType* type) const;
    static bool is_allowed_attribute(const typesystem::IAttribute* attribute);
    bool is_generated_copy_constructor(const typesystem::IMethod* method) const;
    bool is_generated_equality_contract(const typesystem::IProperty* property) const;
    bool is_generated_print_members(const typesystem::IMethod* method) const;
    bool match_string_builder_append(ILInstruction* inst, const il::ILVariable* sb, ILInstruction** val) const;
    bool is_generated_to_string(const typesystem::IMethod* method) const;
    bool is_generated_equals(const typesystem::IMethod* method) const;
    static std::vector<ILInstruction*> unpack_logic_and_chain(ILInstruction* root_of_chain);
    bool match_get_equality_contract(ILInstruction* inst, ILInstruction** target) const;
    static bool is_equality_comparer_get_default_call(ILInstruction* inst, const typesystem::IType* type);
    bool member_considered_for_equality(const typesystem::IMember* member) const;
    bool is_generated_get_hash_code(const typesystem::IMethod* method) const;
    bool is_generated_deconstruct(const typesystem::IMethod* method) const;
    bool match_member_access(ILInstruction* inst, ILInstruction** target, const typesystem::IMember** member) const;
    il::Block* decompile_body(const typesystem::IMethod* method) const;

    const typesystem::DecompilerTypeSystem& type_system_;
    const typesystem::ITypeDefinition* record_type_def_;
    const DecompilerSettings& settings_;
    util::CancellationToken cancellation_token_;
    std::vector<const typesystem::IMember*> ordered_members_;
    bool is_inherited_record_ = false;
    bool is_struct_ = false;
    bool is_sealed_ = false;
    const typesystem::IMethod* primary_ctor_ = nullptr;
    const typesystem::IType* base_class_ = nullptr;
    MemberMap<typesystem::IField, const typesystem::IProperty*> backing_field_to_auto_property_;
    MemberMap<typesystem::IProperty, const typesystem::IField*> auto_property_to_backing_field_;
    // Keyed by parameter objects (the parameters of the constructor definition), in the order they were found.
    std::vector<std::pair<const typesystem::IParameter*, const typesystem::IProperty*>> primary_ctor_parameter_to_auto_property_;
    MemberMap<typesystem::IProperty, const typesystem::IParameter*> auto_property_to_primary_ctor_parameter_;
};

template <class Key, class Value>
void MemberMap<Key, Value>::add(const Key* key, Value value) {
    if (contains(key)) throw std::invalid_argument("An item with the same key has already been added.");
    index_.emplace(key->hash_code(), items_.size());
    items_.emplace_back(key, std::move(value));
}

