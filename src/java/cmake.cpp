#include "java/cmake.hpp"

#include "core/fs.hpp"
#include "core/text.hpp"

namespace cb::java::cmake {

namespace {

// `{name}` is the executable's name.
constexpr std::string_view kTemplate = R"CMK(# Generated by CodeBreaker (java -> C++, platform pc_opengl). Build:
#   cmake -S . -B build -G Ninja      (or "MinGW Makefiles" / your generator)
#   cmake --build build
cmake_minimum_required(VERSION 3.16)
project({name} CXX)

set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS ON)

file(GLOB J2X_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/*.cpp")
add_executable({name} WIN32 ${J2X_SOURCES})   # (WIN32: a windowed program, no console beside it; main() is still the entry)
# (no include directory: the sources include each other with quotes, found beside them; on the include path a class named
# Locale, Error or Regex would stand in for the system's <locale.h> <error.h> <regex.h>, and <string> stops compiling)
if(CMAKE_CXX_COMPILER_ID MATCHES "GNU|Clang")
  target_compile_options({name} PRIVATE -w -fpermissive)
endif()

find_package(SDL2 CONFIG QUIET)
if(TARGET SDL2::SDL2)
  target_link_libraries({name} PRIVATE SDL2::SDL2)
else()
  target_link_libraries({name} PRIVATE SDL2)
endif()
{graphics}target_link_libraries({name} PRIVATE vorbisfile vorbis ogg)   # the game's .ogg sounds and music
if(WIN32)
  target_link_libraries({name} PRIVATE ws2_32)
  if(MSVC)
    target_link_options({name} PRIVATE /ENTRY:mainCRTStartup)   # (a windowed program whose entry is main, not WinMain)
  endif()
endif()

if(EXISTS "${CMAKE_CURRENT_SOURCE_DIR}/Content")
  add_custom_command(TARGET {name} POST_BUILD
    COMMAND ${CMAKE_COMMAND} -E copy_directory "${CMAKE_CURRENT_SOURCE_DIR}/Content" "$<TARGET_FILE_DIR:{name}>/Content")
endif()
)CMK";

constexpr std::string_view kOpenGl = R"CMK(find_package(OpenGL REQUIRED)
target_link_libraries({name} PRIVATE OpenGL::GL OpenGL::GLU)
)CMK";

constexpr std::string_view kD3d9 = R"CMK(target_link_libraries({name} PRIVATE d3d9)   # Direct3D 9 (the shader compiler is d3dcompiler_47.dll, loaded at run time)
)CMK";

constexpr std::string_view kD3d11 = R"CMK(target_link_libraries({name} PRIVATE d3d11 dxgi)   # Direct3D 11 (the shader compiler is d3dcompiler_47.dll, loaded at run time)
)CMK";

}  // namespace

std::string cmakelists_text(std::string_view name, std::string_view graphics) {
    const std::string_view link = graphics == "d3d9" ? kD3d9 : graphics == "d3d11" ? kD3d11 : kOpenGl;
    const std::string text = text::replace_all(kTemplate, "{graphics}", link);
    return text::replace_all(text, "{name}", name);
}

std::filesystem::path write_cmakelists(const std::filesystem::path& out_dir, std::string_view name, std::string_view graphics) {
    std::filesystem::path path = out_dir / "CMakeLists.txt";
    fs::write_text(path, cmakelists_text(name, graphics));
    return path;
}

}  // namespace cb::java::cmake
