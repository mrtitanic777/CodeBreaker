CB_TEST("java.signatures.no_failures_means_no_failure_section", [] {
    sg::Codebase code = sample();
    code.failures.clear();
    const std::string md = sg::render(code, resolver_for(code), {});
    CB_CHECK(!has(md, "Parse failures"));
    CB_CHECK(has(md, "Subsystem: world (2 classes)."));
    CB_CHECK(md.ends_with("  - (none)\n\n"));
});

CB_TEST("java.signatures.load_takes_the_first_of_a_repeated_file_name", [] {
    cb::fs::ScopedTempDir tmp("cbsig");
    cb::fs::write_text(tmp.path() / "a" / "Thing.java", kThing);
    cb::fs::write_text(tmp.path() / "b" / "Thing.java", "package other;\npublic class Thing { int x; }\n");
    cb::fs::write_text(tmp.path() / "Color.java", kColor);
    cb::fs::write_text(tmp.path() / "Bad.java", "nothing here");
    const sg::Codebase code = sg::load(tmp.path());
    CB_CHECK_EQ(code.classes.size(), std::size_t{2});
    CB_CHECK_EQ(code.classes[0].name, "Color");   // by file name: Bad, Color, Thing
    CB_CHECK_EQ(code.classes[1].package.value_or(""), "game.world");
    CB_CHECK_EQ(code.failures.size(), std::size_t{1});
    CB_CHECK_EQ(code.failures[0].file, "Bad.java");
    CB_CHECK_THROWS_AS(cb::NotFoundError, (void)sg::load(tmp.path() / "nope"));
});

CB_TEST("java.signatures.summary", [] {
    const sg::Codebase code = sample();
    CB_CHECK_EQ(sg::summary(code, "out/signatures.md"),
                "Wrote out/signatures.md\n"
                "Classes mapped: 3 across 2 packages.\n"
                "  - game.world (2 classes)\n"
                "  - (default package) (1 classes)\n"
                "Parse failures: 1\n"
                "  - Broken.java: no type declaration\n");
    sg::Codebase clean = sample();
    clean.failures.clear();
    CB_CHECK(sg::summary(clean, "x.md").ends_with("Parse failures: 0\n"));
});

