#include <string>

#include "core/fs.hpp"
#include "core/testing.hpp"
#include "java/cmake.hpp"

namespace {

using namespace cb;
using namespace cb::java;
namespace stdfs = std::filesystem;
CB_TEST("java.cmake.template", [] {
    const std::string t = java::cmake::cmakelists_text("MinecraftBeta");
    CB_CHECK(t.starts_with("# Generated by CodeBreaker (java -> C++, platform pc_opengl). Build:"));
    CB_CHECK(t.find("project(MinecraftBeta CXX)") != std::string::npos);
    CB_CHECK(t.find("add_executable(MinecraftBeta WIN32 ${J2X_SOURCES})") != std::string::npos);   // (a windowed program: no console)
    CB_CHECK(t.find("/ENTRY:mainCRTStartup") != std::string::npos);
    CB_CHECK(t.find("{name}") == std::string::npos);                       // every placeholder filled
    CB_CHECK(t.find("${CMAKE_CURRENT_SOURCE_DIR}/*.cpp") != std::string::npos);   // CMake's own variables untouched
    CB_CHECK(t.find("$<TARGET_FILE_DIR:MinecraftBeta>/Content") != std::string::npos);

    // the golden text for the same name (reviewed line by line)
    CB_CHECK_EQ(java::cmake::cmakelists_text("Game"), fs::read_text(testing::data_path("java/testdata/cmake_Game.golden.txt")));

    fs::ScopedTempDir tmp("cbjava");
    const stdfs::path written = java::cmake::write_cmakelists(tmp.path(), "Game");
    CB_CHECK_EQ(written.filename().string(), "CMakeLists.txt");
    CB_CHECK_EQ(fs::read_text(written), java::cmake::cmakelists_text("Game"));

    // Direct3D 9: d3d9 in place of OpenGL and GLU, everything else the same
    const std::string d = java::cmake::cmakelists_text("Game", "d3d9");
    CB_CHECK(d.find("target_link_libraries(Game PRIVATE d3d9)") != std::string::npos);
    CB_CHECK(d.find("OpenGL") == std::string::npos && d.find("{graphics}") == std::string::npos && d.find("{name}") == std::string::npos);
    CB_CHECK(d.find("SDL2::SDL2") != std::string::npos && d.find("vorbisfile") != std::string::npos);
    CB_CHECK_EQ(java::cmake::cmakelists_text("Game", "opengl"), java::cmake::cmakelists_text("Game"));
    java::cmake::write_cmakelists(tmp.path(), "Game", "d3d9");
    CB_CHECK_EQ(fs::read_text(written), d);

    // Direct3D 11: d3d11 and dxgi
    const std::string e = java::cmake::cmakelists_text("Game", "d3d11");
    CB_CHECK(e.find("target_link_libraries(Game PRIVATE d3d11 dxgi)") != std::string::npos);
    CB_CHECK(e.find("OpenGL") == std::string::npos && e.find("PRIVATE d3d9)") == std::string::npos);
});

}  // namespace

