#!/usr/bin/env python3
r"""cdimage.py -- assemble a CLEAN-ROOM Win95 CD from ONLY our own reconstructed+built artifacts.

Logan's rule: put on the CD only files we have genuine SOURCE for AND have BUILT from that source
with our own toolchain -- never a real binary copied from the corpus. That keeps a hard provenance
boundary: everything on this CD was regenerated by us, so nothing is confused with an original.

This tool is the build-driver + provenance ledger + CD stager in one:

  * BUILD each buildable layer to a final image and persist it under a staging tree:
      - the volume boot record  (nasm on design/recon/bootdisk/msboot.asm)      -> BUILT
      - the NE core             (nerecon --ow --link -> krnl386/gdi/user _ow.exe) -> BUILT
      - the Setup chain         (nerecon --setup --link -> setupx/suwin _ow.exe)
      - the DOS 7.10 layer      (dosrecon --exact byte-identical images)
  * LEDGER every intended CD component with its provenance: BUILT (ours, with the toolchain and
    whether it is byte-identical to the original), SOURCE-ONLY (reconstructed, not yet built), or
    PENDING (still in the reconstruction backlog -- e.g. the CAB payload).
  * STAGE a \WIN95 CD tree containing only BUILT files, and write MANIFEST.csv + README.md.

    wt --target win95 cdimage [--out DIR] [--build]

--build re-runs the layer builds; without it, only already-built images are collected. Nothing here
copies a corpus binary into the CD tree.
"""
import os
import sys
import shutil
import hashlib
import subprocess

from src.core import paths


def _design_root():
    dr = paths.design_root()
    if os.path.isdir(os.path.join(dr, "corpus")):
        return dr
    sib = os.path.join(os.path.dirname(paths.repo_root()), "Windows95", "design")
    return sib if os.path.isdir(os.path.join(sib, "corpus")) else dr


def _md5(p):
    with open(p, "rb") as f:
        return hashlib.md5(f.read()).hexdigest()


def _corpus_find(name):
    root = os.path.join(_design_root(), "corpus")
    for dp, _dn, fn in os.walk(root):
        for f in fn:
            if f.lower() == name.lower():
                return os.path.join(dp, f)
    return None


def _nasm():
    for c in ("nasm", r"C:\Program Files\NASM\nasm.exe"):
        try:
            subprocess.run([c, "-v"], capture_output=True)
            return c
        except OSError:
            continue
    return None


# The intended CD component set, grouped by layer. Each entry:
#   (cd_path, built_image_relpath_under_recon | None, corpus_original_name | None, note)
# built_image is where our build persists the final image; corpus_original lets us report
# byte-identity (a strong provenance signal) without ever copying the original onto the CD.
def _components(recon):
    C = []
    # boot record
    C.append(("[boot]/MSBOOT.BIN", os.path.join(recon, "bootdisk", "_cd_msboot.bin"),
              None, "volume boot record (nasm msboot.asm)"))
    # NE 16-bit core
    for m, orig in (("krnl386", "krnl386.exe"), ("gdi", "gdi.exe"), ("user", "user.exe")):
        C.append(("WINDOWS/SYSTEM/%s" % orig.upper(),
                  os.path.join(recon, "ne", m, m + "_ow.exe"), orig, "NE core (OpenWatcom)"))
    # Setup chain
    C.append(("WIN95/SETUPX.DLL", os.path.join(recon, "ne", "setupx", "setupx_ow.exe"),
              "setupx.dll", "Setup INF+registry engine (NE, OpenWatcom)"))
    C.append(("WIN95/SUWIN.EXE", os.path.join(recon, "ne", "suwin", "suwin_ow.exe"),
              "suwin.exe", "Setup wizard (NE, OpenWatcom)"))
    C.append(("WIN95/OEMSETUP.EXE", os.path.join(recon, "oemsetup", "_built", "oemsetup.exe"),
              "oemsetup.exe", "real-mode Setup launcher (DOS/MZ)"))
    # DOS 7.10 layer (byte-identical images from dosrecon --exact)
    for m, orig in (("iosys", "IO.SYS"), ("command", "COMMAND.COM"), ("himem", "HIMEM.SYS"),
                    ("drvspace", "DRVSPACE.SYS"), ("ifshlp", "IFSHLP.SYS"),
                    ("setver", "SETVER.EXE"), ("ramdrive", "RAMDRIVE.SYS")):
        C.append(("WIN95/%s" % orig, os.path.join(recon, m, "_built", orig.lower().replace(".", "_") + ".bin"),
                  {"IO.SYS": "winboot.sys"}.get(orig, orig.lower()), "MS-DOS 7.10 (byte-identical)"))
    return C


def _build_vbr(recon):
    nasm = _nasm()
    asm = os.path.join(recon, "bootdisk", "msboot.asm")
    out = os.path.join(recon, "bootdisk", "_cd_msboot.bin")
    if not nasm or not os.path.isfile(asm):
        return
    subprocess.run([nasm, "-f", "bin", asm, "-o", out], capture_output=True)


def main(argv):
    recon = os.path.join(_design_root(), "recon")
    outdir = os.path.join(recon, "cd")
    do_build = False
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--out" and i + 1 < len(argv):
            outdir = argv[i + 1]; i += 1
        elif a == "--build":
            do_build = True
        elif a in ("-h", "--help"):
            print(__doc__); return 0
        i += 1

    if do_build:
        print("== building layers ==")
        _build_vbr(recon)
        # NE core + setup chain: drive nerecon (assemble+link). DOS --exact left to dosrecon.
        from src.targets.win95 import nerecon as NR
        for args in (["--krnl386", "--gdi", "--user", "--ow", "--link"], ["--setup", "--ow", "--link"]):
            try:
                NR.main(args)
            except Exception as e:                     # noqa: BLE001 -- report, keep going
                print("  nerecon %s: %s" % (args, e))

    comps = _components(recon)
    win95 = os.path.join(outdir, "WIN95")
    sysdir = os.path.join(outdir, "WINDOWS", "SYSTEM")
    for d in (win95, sysdir, os.path.join(outdir, "_boot")):
        os.makedirs(d, exist_ok=True)

    rows = []
    for cd_path, built, orig, note in comps:
        status, detail, dest = "PENDING", note, None
        if built and os.path.isfile(built):
            status = "BUILT"
            m = _md5(built)
            detail = note
            if orig:
                op = _corpus_find(orig)
                if op:
                    detail = note + (" -- BYTE-IDENTICAL to %s" % orig if _md5(op) == m
                                     else " -- differs from %s (readable build)" % orig)
            # stage into the CD tree (only BUILT files ever land here)
            dest = os.path.join(outdir, cd_path.replace("[boot]/", "_boot/"))
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copy2(built, dest)
        rows.append((cd_path, status, os.path.basename(built) if built else "", detail))

    built_n = sum(1 for r in rows if r[1] == "BUILT")
    # manifest
    import csv
    with open(os.path.join(outdir, "MANIFEST.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["cd_path", "provenance", "our_image", "detail"])
        for r in rows:
            w.writerow(r)
    with open(os.path.join(outdir, "README.md"), "w") as f:
        f.write("# Clean-room Win95 CD -- our-built artifacts only\n\n")
        f.write("Every file here was regenerated by CodeBreaker from reconstructed source with our\n")
        f.write("own toolchain. No original corpus binary is copied in. Byte-identity to the\n")
        f.write("original (where noted) is a provenance check, not a copy.\n\n")
        f.write("Coverage: **%d / %d** intended components built.\n\n" % (built_n, len(rows)))
        f.write("| CD path | provenance | our image | detail |\n|---|---|---|---|\n")
        for cd_path, status, img, detail in rows:
            f.write("| `%s` | %s | %s | %s |\n" % (cd_path, status, img or "-", detail))
        f.write("\nBoot-test our Setup from this tree (no ISO needed):\n\n")
        f.write("    qemu-system-i386 -fda <our-dos-floppy> "
                "-drive file=fat:rw:%s,media=cdrom\n" % outdir)

    print("cdimage: %d / %d components built and staged into %s" % (built_n, len(rows), outdir))
    for cd_path, status, img, detail in rows:
        print("  %-9s %-26s %s" % (status, cd_path, detail))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
