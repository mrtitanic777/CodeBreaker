constexpr std::uint32_t kImageVa = 0x82100000;   // where the made program of config_code.bin loads

// The made program of config_code.bin as the recompiler reads an image (the same code the powerpc tests recompile).
cb::recompile::powerpc::LoadedImage sample_image() {
    cb::recompile::powerpc::LoadedImage loaded;
    const cb::Bytes code = cb::fs::read_file(cb::testing::data_path("recompile/testdata/config_code.bin"));
    const std::uint32_t end = kImageVa + static_cast<std::uint32_t>(code.size());
    auto& image = loaded.image;
    image.code = code;
    image.code_begin = kImageVa;
    image.code_end = end;
    image.entry = kImageVa;
    image.extents = {{kImageVa, 0x40}, {kImageVa + 0x40, 0x20}, {kImageVa + 0x430, 0x40}, {kImageVa + 0x4C0, 0x20}, {kImageVa + 0x600, 0x20}};
    image.imports = {kImageVa + 0x700};
    image.sections.push_back({".text", kImageVa, 0x60000020, code});
    auto& facts = loaded.facts;
    facts.data = code;
    facts.base = kImageVa;
    facts.entry = kImageVa;
    facts.code_begin = kImageVa;
    facts.code_end = end;
    facts.chunks.push_back({kImageVa, 0, static_cast<std::uint32_t>(code.size())});
    facts.sections.push_back({".text", kImageVa, static_cast<std::uint32_t>(code.size()), 0x60000020});
    return loaded;
}

pj::Environment sample_environment(const stdfs::path& rexglue) {
    pj::Environment env;
    env.read_title = [](const stdfs::path&) {
        pj::TitleImage t;
        t.is_xex = false;
        t.image_name = "Sample_XENON.exe";
        t.loaded = sample_image();
        t.imports = {{kImageVa + 0x700, 0, 2}};   // the import stub the image marks, library 0 (no header: xboxkrnl.exe), ordinal 2
        return t;
    };
    env.import_names = [](std::string_view library, std::uint32_t ordinal) { return library == "xboxkrnl.exe" && ordinal == 2 ? "VdSwap" : ""; };
    env.rexglue = rexglue;
    return env;
}

