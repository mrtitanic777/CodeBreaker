"""The console's export names by ordinal, as C++ for the runtime (kernel::OrdinalName).

Usage: gen_ordinal_names.py <ordinals.json> <output .cpp>
The JSON is the knowledge base's description of the console's ordinals (config/knowledge/xbox360/ordinals.json: entries of kind
export with module, ordinal and name); only xam.xex and xboxkrnl.exe are written. A title
that looks an export up by ordinal at run time (XexGetProcedureAddress) and that the runtime implements as an import of that
name is answered through this table (kernel/xboxkrnl_modules.cpp).
"""
import json
import os
import sys


def main():
    source, out = sys.argv[1:3]
    with open(source, encoding='utf-8') as f:
        description = json.load(f)
    names = {}
    for entry in description['entries']:
        if entry.get('kind') == 'export':
            names.setdefault(entry['module'], {})[str(entry['ordinal'])] = entry['name']
    lines = ['// Generated by native/x360/tools/gen_ordinal_names.py from config/knowledge/xbox360/ordinals.json. Do not edit.',
             '#include <cstdint>', '#include <cstring>', '#include <string>', '',
             'namespace kernel', '{', 'namespace', '{',
             'struct OrdinalEntry { uint16_t ordinal; const char* name; };']
    arrays = []
    for library, ident in (('xam.xex', 'kXam'), ('xboxkrnl.exe', 'kKernel')):
        entries = sorted((int(k), v) for k, v in names.get(library, {}).items() if k.isdigit() and int(k) < 65536)
        lines.append(f'const OrdinalEntry {ident}Names[] = {{')
        lines.extend(f'    {{ {o}, "{n}" }},' for o, n in entries)
        lines.append('};')
        arrays.append((library, ident))
    lines += ['', 'const char* Find(const OrdinalEntry* begin, const OrdinalEntry* end, uint16_t ordinal)', '{',
              '    while (begin < end)', '    {', '        const OrdinalEntry* middle = begin + (end - begin) / 2;',
              '        if (middle->ordinal == ordinal)', '            return middle->name;',
              '        if (middle->ordinal < ordinal)', '            begin = middle + 1;', '        else',
              '            end = middle;', '    }', '    return "";', '}', '}', '',
              '// The name of export `ordinal` of "xam.xex" or "xboxkrnl.exe", empty when the console table has none.',
              'const char* OrdinalName(const std::string& library, uint16_t ordinal)', '{']
    for library, ident in arrays:
        lines.append(f'    if (library == "{library}")')
        lines.append(f'        return Find({ident}Names, {ident}Names + sizeof({ident}Names) / sizeof({ident}Names[0]), ordinal);')
    lines += ['    return "";', '}', '}', '']
    text = '\n'.join(lines)
    if not os.path.exists(out) or open(out, encoding='utf-8').read() != text:
        with open(out, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)


if __name__ == '__main__':
    main()
