namespace {

bool has_flag(std::span<const std::string> args, std::string_view flag) { return std::find(args.begin(), args.end(), flag) != args.end(); }

// The argument after `flag`; none when the flag is absent. UsageError when it is the last argument.
std::optional<std::string> flag_value(std::span<const std::string> args, std::string_view flag) {
    const auto it = std::find(args.begin(), args.end(), flag);
    if (it == args.end()) return std::nullopt;
    if (it + 1 == args.end()) throw UsageError(std::format("{} needs a value", flag));
    return *(it + 1);
}

bool starts_with_xex_magic(const stdfs::path& file) {
    if (!stdfs::is_regular_file(file)) return false;
    const Bytes head = fs::read_file(file);
    return head.size() >= 4 && std::equal(head.begin(), head.begin() + 4, "XEX2");
}

}  // namespace

int run_command(const CommandHooks& hooks, std::span<const std::string> args, const std::function<void(std::string_view)>& say) {
    if (args.empty() || args[0].starts_with("-")) {
        say(kUsage);
        return 2;
    }
    const std::optional<std::string> out = flag_value(args, "-o");
    const std::string runtime = flag_value(args, "--runtime").value_or("x360");

    if (runtime == "x360") {
        const std::optional<std::string> files = flag_value(args, "--title-files");
        std::optional<std::string> name = flag_value(args, "--name");
        stdfs::path xex_path = fs::from_text(args[0]);
        std::optional<TitleFiles> found;
        if (!starts_with_xex_magic(xex_path)) {
            // a package, disc image, Games-on-Demand folder or folder of files: its default.xex, and its files unpacked into
            // the project's assets/ (once)
            found = hooks.locate_title(xex_path);
            if (!found) {
                say(std::format("{}: no Xbox 360 title found (a default.xex in a package, disc image or folder)", args[0]));
                return 1;
            }
            if (!name || name->empty()) name = found->name;
            const stdfs::path staging = hooks.store.root() / "_unpacking";
            fs::make_dirs(staging);
            xex_path = staging / "default.xex";
            fs::write_file(xex_path, found->xex);
        }
        std::optional<store::converted::Project> proj;
        if (!out) {
            std::optional<std::string> given;
            if (name && !name->empty()) given = name;
            proj = hooks.store.project(xex_path, given);
        }
        const stdfs::path folder = proj ? proj->root() : fs::from_text(*out);
        if (found) {
            const std::size_t n = found->unpack(folder / "assets");
            say(std::format("{}: {}", found->name, n ? std::format("{} files unpacked from {}", n, found->source) : "files unpacked before"));
        }
        const std::string scaffold_name = name && !name->empty() ? *name : proj ? proj->name() : std::string();
        const std::string translator = flag_value(args, "--translator").value_or("xenonrecomp");
        if (translator != "xenonrecomp" && translator != "pcode") {
            say("--translator: xenonrecomp or pcode");
            return 2;
        }
        x360project::Recompiler recompiler = hooks.recompiler;
        const auto counted = std::make_shared<xenon::Translation>();
        if (translator == "pcode") recompiler.recomp = xenon::with_pcode(recompiler.recomp, hooks.pcode_sla, counted);
        const x360project::ScaffoldInfo info = x360project::scaffold(
            recompiler, xex_path, folder, scaffold_name, files ? std::optional<stdfs::path>(fs::from_text(*files)) : std::nullopt);
        if (proj) {
            proj->record("recompile-project", {proj->root() / "CMakeLists.txt", proj->src(), proj->assets(), proj->reports() / "recompile.log"},
                         std::format("{} functions recompiled to C++ (XenonRecomp) for CodeBreaker's Xbox 360 runtime.\n"
                                     "Build: Build-{}.bat   Play: Play-{}.bat (keyboard or controller)",
                                     info.functions, info.name, info.name));
        }
        say(std::format("{}: {} functions, {} switch tables, {} unimplemented instructions", info.name, info.functions, info.switches, info.unimplemented));
        if (translator == "pcode") {
            say(std::format("  p-code wrote {} instructions, XenonRecomp {}", counted->translated, counted->declined));
            std::vector<std::pair<std::size_t, std::string>> why;
            for (const auto& [reason, n] : counted->why) why.emplace_back(n, reason);
            std::sort(why.rbegin(), why.rend());
            for (std::size_t k = 0; k < why.size() && k < 12; ++k) say(std::format("    declined {}: {}", why[k].first, why[k].second));
            std::string written;
            for (const auto& [m, n] : counted->written) written += std::format("{} {}\n", m, n);
            fs::write_text(info.dir / "reports" / "pcode_written.txt", written);   // (every mnemonic it wrote, counted)
            std::string declined;
            for (const auto& [reason, n] : counted->declined_by) declined += std::format("{} {}\n", n, reason);
            fs::write_text(info.dir / "reports" / "pcode_declined.txt", declined);   // (every reason it declined, counted)
        }
        if (info.modules != 0) say(std::format("  {} other modules translated and linked (reports/modules.txt)", info.modules));
        say("  -> " + native_text(info.dir));
        say("  build: " + native_text(info.dir / ("Build-" + info.name + ".bat")));
        say("  play:  " + native_text(info.dir / ("Play-" + info.name + ".bat")));
        if (has_flag(args, "--build") || has_flag(args, "--check")) {
            const x360project::BuildResult built = x360project::build(info.dir, info.name);
            say(std::string("build: ") + (built.ok ? "ok" : "FAILED"));
            if (!built.ok) {
                for (const std::string& line : built.tail) say("  " + std::string(clip(line, 300)));
                return 1;
            }
        }
        if (has_flag(args, "--check")) {
            const auto at = std::find(args.begin(), args.end(), "--check");
            unsigned seconds = 60;
            if (at + 1 != args.end()) {
                if (const auto n = text::parse_int<unsigned>(*(at + 1))) seconds = *n;
            }
            const x360project::CheckResult r = x360project::check(info.dir, info.name, seconds);
            say(std::format("check ({} s headless): {} frames presented", seconds, r.frames));
            std::vector<std::pair<std::string, std::size_t>> unimplemented(r.unimplemented.begin(), r.unimplemented.end());
            std::stable_sort(unimplemented.begin(), unimplemented.end(), [](const auto& a, const auto& b) { return a.second > b.second; });
            for (const auto& [import, calls] : unimplemented) say(std::format("  unimplemented import {} ({} calls)", import, calls));
            if (!r.fatal.empty()) say("  stopped: " + std::string(clip(r.fatal, 400)));
            say("  log: " + native_text(r.log));
        }
        return 0;
    }

    if (!out) {
        say(kUsage);
        return 2;
    }
    std::optional<unsigned> jobs;
    if (const std::optional<std::string> j = flag_value(args, "-j")) {
        jobs = text::parse_int<unsigned>(*j);
        if (!jobs) throw UsageError("-j needs a number");
    }
    const Scaffolded made = scaffold(hooks.env, fs::from_text(args[0]), fs::from_text(*out), jobs);
    const double pct = 100.0 * static_cast<double>(made.agg.translated) / static_cast<double>(std::max<std::size_t>(1, made.agg.total));
    say(std::format("{}: {} functions in {} source files, {:.1f}% of {} instructions translated, {} imports", made.name, made.agg.funcs, made.shards,
                    pct, made.agg.total, made.imports));
    say("  -> " + native_text(made.dir));
    const std::string dir = native_text(made.dir);
    say(std::format("  build: cmake -S \"{0}\" -B \"{0}/build\" && cmake --build \"{0}/build\"", dir));
    return 0;
}

