bool write_if_changed(const stdfs::path& path, ByteView data) {
    try {
        const Bytes have = fs::read_file(path);
        if (std::equal(have.begin(), have.end(), data.begin(), data.end())) return false;
    } catch (const IoError&) {
        // not there yet (or unreadable): write it
    }
    fs::make_dirs(path.parent_path());
    fs::write_file(path, data);
    return true;
}

namespace {

bool write_text_if_changed(const stdfs::path& path, std::string_view text) {
    return write_if_changed(path, ByteView(reinterpret_cast<const std::uint8_t*>(text.data()), text.size()));
}

}  // namespace

void sync_tree(const stdfs::path& src, const stdfs::path& dst, const std::function<bool(const std::string&)>& drop) {
    std::set<stdfs::path> keep;
    std::vector<stdfs::path> stack{src};
    while (!stack.empty()) {
        const stdfs::path dir = stack.back();
        stack.pop_back();
        const stdfs::path rel = stdfs::relative(dir, src);
        fs::make_dirs((dst / rel).lexically_normal());
        for (const stdfs::directory_entry& e : stdfs::directory_iterator(dir)) {
            if (drop(fs::to_text(e.path().filename()))) continue;
            if (e.is_directory()) {
                stack.push_back(e.path());
            } else if (e.is_regular_file()) {
                const stdfs::path target = (dst / rel / e.path().filename()).lexically_normal();
                keep.insert(target);
                write_if_changed(target, fs::read_file(e.path()));
            }
        }
    }
    if (!stdfs::is_directory(dst)) return;
    std::vector<stdfs::path> stale;
    for (const stdfs::directory_entry& e : stdfs::recursive_directory_iterator(dst)) {
        if (e.is_regular_file() && !keep.contains(e.path().lexically_normal())) stale.push_back(e.path());
    }
    for (const stdfs::path& p : stale) stdfs::remove(p);
}

bool copy_rex_dxbc(const stdfs::path& rexglue, const stdfs::path& dst) {
    const stdfs::path src = rexglue / "dxbc";
    if (!stdfs::is_directory(src) || !stdfs::exists(src / "CMakeLists.txt")) return false;
    static const std::set<std::string, std::less<>> skip = {"obj", "build_dxbc.sh", "linktest.cpp", "translate_probe.cpp",
                                                            "client_test.cpp", "wired_main.cpp", "librex_dxbc.a"};
    sync_tree(src, dst, [&](const std::string& n) { return skip.contains(n) || is_build_product(n); });
    return true;
}

bool copy_rex_kernel(const stdfs::path& rexglue, const stdfs::path& dst) {
    const stdfs::path src = rexglue / "kernel";
    if (!stdfs::is_directory(src) || !stdfs::exists(src / "CMakeLists.txt")) return false;
    static const std::set<std::string, std::less<>> skip = {"obj", "build_kernel.sh", "sweep.sh", "librex_kernel.a"};
    sync_tree(src, dst, [&](const std::string& n) { return skip.contains(n) || is_build_product(n); });
    return true;
}

Scaffolded scaffold(const Environment& env, const stdfs::path& xex_path, const stdfs::path& out_dir, std::optional<unsigned> jobs) {
    const TitleImage title = env.read_title(xex_path);
    const disassemble::FlatImage flat = disassemble::flatten(title.loaded.facts);
    const std::string name = clean_name(title.image_name && !title.image_name->empty() ? *title.image_name : fs::to_text(xex_path.filename()));

    // the import stubs get host functions, not recompiled bodies (the loader replaces their bytes)
    const std::vector<std::string> libraries =
        !title.libraries.empty() ? title.libraries : std::vector<std::string>{"xboxkrnl.exe", "xam.xex"};
    Thunks thunks;
    powerpc::ImageOptions options;
    options.jobs = jobs;
    for (const TitleImage::Stub& stub : title.imports) {
        thunks[stub.address] = {stub.library < libraries.size() ? libraries[stub.library] : std::format("library{}", stub.library), stub.ordinal};
        options.skip.insert(stub.address);
    }
    const powerpc::ImageResult recompiled = powerpc::recompile_image(powerpc::Program{title.loaded.image, flat}, env.vector, options);
    const powerpc::Aggregate& agg = recompiled.agg;

    const stdfs::path inc = out_dir / "include", src = out_dir / "src", assets = out_dir / "assets";
    for (const stdfs::path& d : {inc, src, assets}) fs::make_dirs(d);

    // --- include/: the runtime header, the shared declarations, the config
    write_text_if_changed(inc / "rex_ppc_min.h", powerpc::runtime_header());
    write_text_if_changed(inc / (name + "_config.h"), config_h(name, flat.base, flat.entry, flat.bytes.size()));
    write_text_if_changed(inc / (name + ".h"), recomp_header(name, agg.decls));
    write_text_if_changed(inc / "rex_host.h", host_h(name));   // guest heap + host helpers

    // --- src/: the recompiled functions, split into many translation units
    const auto ranges = shard_ranges(agg.parts);
    for (std::size_t i = 0; i < ranges.size(); ++i) {
        const std::span<const std::string> group = std::span(agg.parts).subspan(ranges[i].first, ranges[i].second - ranges[i].first);
        write_text_if_changed(src / std::format("{}_{:04}.cpp", name, i), std::format("#include \"{}.h\"\n\n", name) + text::join(group, "\n"));
    }
    // the import shims go in the table too: the CRT calls some imports through pointers (TlsGetValue handing back
    // KeTlsGetValue's thunk, then bctrl to it)
    {
        std::set<std::uint32_t> mapped(agg.chosen.begin(), agg.chosen.end());
        const std::set<std::uint32_t> declared(agg.decls.begin(), agg.decls.end());
        std::vector<std::uint32_t> undeclared;
        for (const auto& [address, thunk] : thunks) {
            mapped.insert(address);
            if (!declared.contains(address)) undeclared.push_back(address);
        }
        const std::vector<std::uint32_t> mapped_sorted(mapped.begin(), mapped.end());
        write_text_if_changed(src / (name + "_init.cpp"), init_cpp(name, mapped_sorted, undeclared));   // (`thunks` iterates by address: sorted)
    }
    write_text_if_changed(src / "rex_runtime.cpp", runtime_cpp(name));
    // the host-shim layer: one typed stub per imported kernel/XAM function
    write_text_if_changed(src / (name + "_imports.cpp"), imports_cpp(name, thunks, env.import_names, read_rex_exports(env.rexglue)));

    // --- graphics/: the native D3D12 GPU subsystem
    fs::make_dirs(out_dir / "graphics");
    for (const gpu::GeneratedFile& f : gpu::graphics_files()) write_text_if_changed(out_dir / fs::from_text(f.path), f.text);
    write_text_if_changed(out_dir / "GPU_DESIGN.md", gpu::design_md(name));

    Scaffolded made;
    // the DXBC shader translator (graphics/rex_dxbc/): with it there, the ShaderTranslator's __has_include finds it and
    // shaders are translated to DXBC; the kernel core (kernel/rex_kernel/): the recompiled code bridges onto its PPCContext
    // and kernel (rex_ppc_min.h finds it by itself)
    made.dxbc_copied = copy_rex_dxbc(env.rexglue, out_dir / "graphics" / "rex_dxbc");
    made.kernel_copied = copy_rex_kernel(env.rexglue, out_dir / "kernel" / "rex_kernel");

    // --- assets/: the image (for a standalone boot) and the .xex (the kernel core decrypts, decompresses and loads it itself
    // at boot)
    fs::write_file(assets / (name + ".bin"), flat.bytes);
    if (title.is_xex) {
        std::error_code ec;   // best effort: a project without the copy still builds; the caller sees xex_copied
        stdfs::copy_file(xex_path, assets / (name + ".xex"), stdfs::copy_options::overwrite_existing, ec);
        made.xex_copied = !ec;
    }

    // --- build glue, launcher, docs
    write_text_if_changed(out_dir / "CMakeLists.txt", cmakelists(name));
    write_text_if_changed(out_dir / ("Play-" + name + ".bat"), launcher_bat(name));
    write_text_if_changed(out_dir / "README.md", readme(name, agg, flat.base, flat.entry, ranges.size()));

    made.name = name;
    made.dir = out_dir;
    made.agg = agg;
    made.shards = ranges.size();
    made.imports = thunks.size();
    return made;
}

