RexExports read_rex_exports(const stdfs::path& rexglue) {
    RexExports out;
    const stdfs::path root = rexglue / "kernel";
    if (!stdfs::is_directory(root)) return out;
    static const Regex export_line(R"(\s*XE_EXPORT\(\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(\w+))");
    static const Regex imp_export(R"(EXPORT\(__imp__(\w+))");
    // the files the kernel core's CMakeLists leaves out
    static const Regex left_out(R"(graphics[/\\](command_processor|graphics_system|trace_writer)|)"
                                R"(xboxkrnl[/\\](cert_monitor|debug_monitor|xboxkrnl_video|xboxkrnl_audio)|)"
                                R"(xam[/\\](xam_input|xam_ui|xam_nui))");

    std::vector<stdfs::path> tables, sources;
    const stdfs::path kernel_src = root / "src" / "kernel";
    if (stdfs::is_directory(kernel_src)) {
        for (const stdfs::directory_entry& e : stdfs::directory_iterator(kernel_src)) {
            if (e.is_directory() && stdfs::is_regular_file(e.path() / "export_table.inc")) tables.push_back(e.path() / "export_table.inc");
        }
        for (const stdfs::directory_entry& e : stdfs::recursive_directory_iterator(kernel_src)) {
            if (e.is_regular_file() && e.path().extension() == ".cpp") sources.push_back(e.path());
        }
    }
    std::sort(tables.begin(), tables.end());
    std::sort(sources.begin(), sources.end());
    for (const stdfs::path& table : tables) {
        const std::string table_text = text::sanitize_utf8(fs::read_text(table));
        for (const std::string_view line : text::lines(table_text)) {
            const std::optional<RegexMatch> m = export_line.match(line);
            if (!m) continue;
            const std::optional<std::uint32_t> ordinal = text::parse_int<std::uint32_t>(m->group(2).substr(2), 16);
            if (ordinal) out.names[{text::lower(m->group(1)), *ordinal}] = std::string(m->group(3));
        }
    }
    for (const stdfs::path& cpp : sources) {
        if (left_out.test(fs::to_text(cpp))) continue;
        std::string body;
        try {   // a file that cannot be read has no exports to find; the rest still count
            body = text::sanitize_utf8(fs::read_text(cpp));
        } catch (const IoError&) {
            continue;
        }
        imp_export.for_each_match(body, [&](const RegexMatch& m) {
            out.implemented.emplace(m.group(1));
            return true;
        });
    }
    return out;
}

std::string imports_cpp(std::string_view name, const Thunks& thunks, const ImportNames& names, const RexExports& rex) {
    struct Record {
        std::uint32_t address, ordinal;
        std::string api;
    };
    std::map<std::string, std::vector<Record>> by_library;   // sorted by library name
    for (const auto& [address, thunk] : thunks) {
        by_library[thunk.library].push_back({address, thunk.ordinal, names ? names(text::lower(thunk.library), thunk.ordinal) : std::string()});
    }

    // a few Vd* imports are the guest<->GPU seam: they go to the native GPU subsystem (graphics/) instead of a generic stub
    static const std::map<std::string, std::string, std::less<>> vd_routes = {
        {"VdInitializeRingBuffer", "xe_gpu::gpu().InitializeRingBuffer(ctx.r3.u32, ctx.r4.u32);"},
        {"VdEnableRingBufferRPtrWriteBack", "xe_gpu::gpu().EnableReadPointerWriteBack(ctx.r3.u32, ctx.r4.u32);"},
        {"VdSwap", "xe_gpu::gpu().Swap(ctx.r3.u32, 1280, 720); ctx.r3.s64 = 0;"},
        {"VdQueryVideoFlags", "ctx.r3.u64 = 0x00000007;   // widescreen + progressive (bootstrap)"},
    };

    std::set<std::string> imp_externs;   // the __imp__<name> exports called directly
    std::vector<std::string> body;
    std::size_t n_rex = 0, n_host = 0, n_vd = 0, n_stub = 0;
    for (auto& [library, records] : by_library) {
        std::sort(records.begin(), records.end(), [](const Record& a, const Record& b) {
            return std::tie(a.address, a.ordinal, a.api) < std::tie(b.address, b.ordinal, b.api);
        });
        body.push_back(std::format("// ---- {}  ({} functions) ----", library, records.size()));
        const std::string lowered = text::lower(library);
        const std::string module(text::split(lowered, '.')[0]);   // "xboxkrnl.exe" -> "xboxkrnl"
        for (const Record& rec : records) {
            const auto found = rex.names.find({module, rec.ordinal});
            const std::string rexname = found == rex.names.end() ? std::string() : found->second;
            const std::string label = !rec.api.empty() ? rec.api : !rexname.empty() ? rexname : std::format("ordinal {}", rec.ordinal);
            const std::string addr = hex8(rec.address);
            body.push_back(std::format("PPC_FUNC(sub_{}) {{   // {}: {}", addr, library, label));
            body.push_back(std::format("    REX_TRACE_IN(\"{}\");", label));
            if (const auto vd = vd_routes.find(rec.api); vd != vd_routes.end()) {   // (1) the GPU seam
                body.push_back("    " + vd->second);
                body.push_back("    (void)ctx; (void)base;");
                ++n_vd;
            } else if (!rexname.empty() && rex.implemented.contains(rexname)) {   // (2) a real RexGlue kernel export
                imp_externs.insert(rexname);
                body.push_back(std::format("    __imp__{}(ctx, base);", rexname));
                ++n_rex;
            } else if (const auto host = host_impl().find(rec.api); host != host_impl().end()) {   // (3) our own host implementation
                for (const std::string& stmt : host->second) body.push_back("    " + stmt);
                body.push_back("    (void)ctx; (void)base;");
                ++n_host;
            } else {   // (4) a stub that logs once
                body.push_back("    static bool once = false;");
                body.push_back(std::format("    if (!once) {{ once = true; std::fprintf(stderr, \"[import] TODO {}: {}  (sub_{})\\n\"); }}", library,
                                           label, addr));
                body.push_back("    (void)ctx; (void)base;");
                ++n_stub;
            }
            body.push_back(std::format("    REX_TRACE_OUT(\"{}\");", label));
            body.push_back("}");
        }
        body.push_back("");
    }

    std::vector<std::string> lines = {fill(IMPORTS_PRELUDE_T, {{"@name@", std::string(name)},
                                                               {"@N@", std::to_string(thunks.size())},
                                                               {"@REX@", std::to_string(n_rex)},
                                                               {"@VD@", std::to_string(n_vd)},
                                                               {"@HOST@", std::to_string(n_host)},
                                                               {"@STUB@", std::to_string(n_stub)}}),
                                      ""};
    if (!imp_externs.empty()) {
        lines.push_back("// Real RexGlue kernel exports (linked from kernel/rex_kernel). Calling");
        lines.push_back("// __imp__<name> runs the vendored kernel's actual implementation.");
        for (const std::string& nm : imp_externs) lines.push_back(std::format("extern \"C\" PPC_FUNC(__imp__{});", nm));
        lines.push_back("");
    }
    lines.insert(lines.end(), body.begin(), body.end());
    return text::join(lines, "\n");
}

