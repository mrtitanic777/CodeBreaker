// A template with its @markers@ filled in.
std::string fill(std::string_view tpl, std::initializer_list<std::pair<std::string_view, std::string>> values) {
    std::string out(tpl);
    for (const auto& [marker, value] : values) out = text::replace_all(out, marker, value);
    return out;
}

std::string hex8(std::uint32_t v) { return std::format("{:08X}", v); }

// 1234567 -> "1,234,567"
std::string with_commas(std::uint64_t n) {
    const std::string digits = std::to_string(n);
    std::string out;
    for (std::size_t i = 0; i < digits.size(); ++i) {
        if (i > 0 && (digits.size() - i) % 3 == 0) out += ',';
        out += digits[i];
    }
    return out;
}

std::string upper_name(std::string_view name) { return text::upper(name); }

// The longest prefix of `s` of at most `limit` bytes that does not cut a UTF-8 character.
std::string_view clip(std::string_view s, std::size_t limit) {
    if (s.size() <= limit) return s;
    std::size_t cut = limit;
    while (cut > 0 && (static_cast<unsigned char>(s[cut]) & 0xC0) == 0x80) --cut;
    return s.substr(0, cut);
}

std::string native_text(stdfs::path p) { return p.make_preferred().string(); }

bool is_build_product(const std::string& name) { return name.ends_with(".a") || name.ends_with(".o") || name.ends_with(".exe"); }

