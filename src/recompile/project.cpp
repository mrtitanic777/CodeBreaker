std::string clean_name(std::string_view module) {
    std::string base(module);
    if (const std::size_t dot = base.rfind('.'); dot != std::string::npos && dot > 0 && base.find_first_of("/\\", dot) == std::string::npos) {
        base.erase(dot);   // splitext: a leading dot (".hidden") is no extension
    }
    for (const std::string_view mark : {"XENON", "_xenon", "Xenon"}) base = text::replace_all(base, mark, "");
    std::string kept;
    for (const char c : base) {
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_') kept += c;
    }
    const std::string_view name = text::trim(kept, "_");
    return name.empty() ? "title" : std::string(name);
}

std::vector<std::pair<std::size_t, std::size_t>> shard_ranges(std::span<const std::string> parts, std::size_t target) {
    std::vector<std::pair<std::size_t, std::size_t>> out;
    std::size_t begin = 0, size = 0;
    for (std::size_t i = 0; i < parts.size(); ++i) {
        size += parts[i].size();
        if (size >= target) {
            out.emplace_back(begin, i + 1);
            begin = i + 1;
            size = 0;
        }
    }
    if (begin < parts.size()) out.emplace_back(begin, parts.size());
    return out;
}

std::string config_h(std::string_view name, std::uint32_t image_base, std::uint32_t entry, std::uint64_t image_size) {
    return std::format(
        "// {0}_config.h - generated by CodeBreaker\n"
        "#pragma once\n"
        "#include <cstdint>\n"
        "#define PPC_IMAGE_BASE  0x{1:08X}ull\n"
        "#define PPC_ENTRY_POINT 0x{2:08X}u\n"
        "#define PPC_IMAGE_SIZE  0x{3:X}ull\n"
        "#define PPC_IMAGE_ASSET \"{0}.bin\"\n"
        "#define PPC_XEX_ASSET   \"{0}.xex\"   // raw XEX (RexGlue runtime loads it at boot)\n",
        name, image_base, entry, image_size);
}

std::string recomp_header(std::string_view name, std::span<const std::uint32_t> declared) {
    std::vector<std::string> lines = {std::format("// {}.h - generated by CodeBreaker.", name),
                                      "// Shared declarations for the recompiled title: the runtime, the",
                                      "// config, and a forward declaration of every recompiled function so",
                                      "// the src/*.cpp translation units can call across each other.",
                                      "#pragma once",
                                      std::format("#include \"{}_config.h\"", name),   // config first: the bridge's context.h may want it
                                      "#include \"rex_ppc_min.h\"",
                                      "",
                                      "// --- every recompiled guest function (defined across src/*.cpp) ---"};
    for (const std::uint32_t a : declared) lines.push_back(std::format("PPC_FUNC(sub_{});", hex8(a)));
    for (const char* l : {"",
                          "// guest address -> recompiled function, for indirect (bctr) calls.",
                          "// In bridge mode the vendored RexGlue context.h already provides this",
                          "// (with the same {guest, host} field layout), so we only define it",
                          "// ourselves for the standalone build.",
                          "#ifndef REX_PPC_BRIDGE",
                          "struct PPCFuncMapping { size_t guest; PPCFunc* host; };",
                          "extern PPCFuncMapping PPCFuncMappings[];",
                          "#endif",
                          ""}) {
        lines.push_back(l);
    }
    return text::join(lines, "\n");
}

std::string init_cpp(std::string_view name, std::span<const std::uint32_t> mapped, std::span<const std::uint32_t> undeclared) {
    std::vector<std::string> lines = {std::format("#include \"{}.h\"", name), ""};
    if (!undeclared.empty()) {   // import shims no recompiled code calls directly
        for (const std::uint32_t va : undeclared) lines.push_back(std::format("PPC_FUNC(sub_{});", hex8(va)));
        lines.push_back("");
    }
    lines.push_back("// The function-pointer table: guest address -> recompiled function.");
    lines.push_back("PPCFuncMapping PPCFuncMappings[] = {");
    for (const std::uint32_t va : mapped) lines.push_back(std::format("\t{{ 0x{}, sub_{} }},", hex8(va), hex8(va)));
    lines.push_back("\t{ 0, nullptr },");
    lines.push_back("};");
    lines.push_back("");
    return text::join(lines, "\n");
}

std::string host_h(std::string_view name) { return fill(HOST_H_T, {{"@name@", std::string(name)}}); }

std::string runtime_cpp(std::string_view name) { return fill(RUNTIME_CPP_T, {{"@name@", std::string(name)}}); }

std::string cmakelists(std::string_view name) {
    return fill(CMAKELISTS_T, {{"@NAME@", upper_name(name)}, {"@name@", std::string(name)}});
}

std::string launcher_bat(std::string_view name) { return fill(LAUNCHER_BAT_T, {{"@name@", std::string(name)}}); }

std::string readme(std::string_view name, const powerpc::Aggregate& agg, std::uint32_t image_base, std::uint32_t entry, std::size_t shards) {
    const double pct = 100.0 * static_cast<double>(agg.translated) / static_cast<double>(std::max<std::size_t>(1, agg.total));
    return fill(README_T, {{"@name@", std::string(name)},
                           {"@IB@", hex8(image_base)},
                           {"@ENTRY@", hex8(entry)},
                           {"@FUNCS@", with_commas(agg.funcs)},
                           {"@TRANS@", with_commas(agg.translated)},
                           {"@TOTAL@", with_commas(agg.total)},
                           {"@PCT@", std::format("{:.1f}", pct)},
                           {"@SHARDS@", std::to_string(shards)}});
}

