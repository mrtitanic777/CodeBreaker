def _norm(module):
    return (module or "").strip().lower()

def lookup(module, ordinal):
    """(name, notes) for module+ordinal, or None. `module` may be a bare name
    ("xboxkrnl") or an import-table name ("xboxkrnl.exe", "xam.xex")."""
    tbl = _MODULES.get(_norm(module))
    if tbl is None:
        return None
    return tbl.get(ordinal)

def lookup_kernel(ordinal):
    return XBOXKRNL_ORDINALS.get(ordinal)

def lookup_xam(ordinal):
    return XAM_ORDINALS.get(ordinal)

def resolve(module, ordinal):
    """Convenience: just the name (str) or None."""
    r = lookup(module, ordinal)
    return r[0] if r else None

def search_by_name(name):
    """[(module, ordinal, name, notes), ...] where `name` is a substring."""
    q = name.lower()
    out = []
    for blk, tbl in _ALL.items():
        for num, (fn, notes) in tbl.items():
            if q in fn.lower():
                out.append((blk, num, fn, notes))
    return out

def get_all_kernel():
    return XBOXKRNL_ORDINALS

def get_all_xam():
    return XAM_ORDINALS

def get_all(module):
    return _MODULES.get(_norm(module), {})

def stats():
    s = dict((blk, len(tbl)) for blk, tbl in _ALL.items())
    s["total"] = sum(len(tbl) for tbl in _ALL.values())
    # legacy keys
    s["kernel_count"] = len(XBOXKRNL_ORDINALS)
    s["xam_count"] = len(XAM_ORDINALS)
    return s
