#!/usr/bin/env python3
"""
ppcproject.py — scaffold a complete, buildable PC project from a .xex.

Takes a recompiled title and lays out the working folder needed to build (and,
once the runtime is filled in, run) it on PC — the structure a RexGlue/
XenonRecomp project produces, generated by us:

    <project>/
      CMakeLists.txt                 build glue (C++20)
      README.md                      what it is + how to build
      generated/
        <name>_recomp.cpp            every recompiled PowerPC function
        <name>_init.cpp              PPCFuncMappings (guest addr -> fn) table
        <name>_config.h              image base / entry / size
        rex_ppc_min.h                our PowerPC runtime header
      runtime/
        rex_runtime.cpp              indirect-call table, host-shim registry,
                                     setjmp/longjmp, guest memory, boot main()
      assets/
        <name>.bin                   the decoded guest image (loaded at base)

HONEST STATUS: the project BUILDS and LINKS as scaffolded. To actually RUN a
whole game the host-shim registry (xboxkrnl/XAM/CRT) and the GPU bridge must be
filled in — those stubs currently warn. The scaffold gives the exact structure
and wiring to fill. Run with the UI:

    XboxTranspiler --ui project default.xex -o C:\\path\\TetrisPC
"""
import argparse
import os
import struct
import sys

import ppcrecomp


def _clean_name(module):
    base = os.path.splitext(module)[0]
    for suf in ("XENON", "_xenon", "Xenon"):
        base = base.replace(suf, "")
    return "".join(c for c in base if c.isalnum() or c == "_").strip("_") or "title"


SHARD_BYTES = 1_500_000        # target size of each src/*.cpp translation unit


def _shards(parts, target=SHARD_BYTES):
    """Group per-function C++ into balanced translation units (~target bytes)."""
    out, cur, sz = [], [], 0
    for p in parts:
        cur.append(p)
        sz += len(p)
        if sz >= target:
            out.append(cur); cur, sz = [], 0
    if cur:
        out.append(cur)
    return out


def _copy_rex_dxbc(dst):
    """Copy the vendored DXBC shader translator into a generated project, minus
    build artifacts and standalone tests. Returns True if it was vendored."""
    import shutil
    src = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "vendor", "rex_dxbc")
    if not os.path.isdir(src) or not os.path.exists(os.path.join(src, "CMakeLists.txt")):
        return False
    _SKIP_DIRS = {"obj"}
    _SKIP_FILES = {"build_dxbc.sh", "linktest.cpp", "translate_probe.cpp",
                   "client_test.cpp", "wired_main.cpp", "librex_dxbc.a"}

    def _ignore(dir_path, names):
        drop = set()
        for n in names:
            if n in _SKIP_DIRS or n in _SKIP_FILES:
                drop.add(n)
            elif n.endswith((".a", ".o", ".exe")):
                drop.add(n)
        return drop

    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=_ignore)
    return True


def _copy_rex_kernel(dst):
    """Copy the vendored RexGlue kernel core into a generated project (minus build
    artifacts + obj). Returns True if it was vendored. Its CMake target propagates
    c++23 + header-only fmt + the include roots to whatever links it, so the
    recompiled code compiles against RexGlue's PPCContext (the bridge)."""
    import shutil
    src = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "vendor", "rex_kernel")
    if not os.path.isdir(src) or not os.path.exists(os.path.join(src, "CMakeLists.txt")):
        return False
    _SKIP = {"obj", "build_kernel.sh", "sweep.sh", "librex_kernel.a"}

    def _ignore(dir_path, names):
        return {n for n in names
                if n in _SKIP or n.endswith((".a", ".o", ".exe"))}

    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=_ignore)
    return True


def scaffold(xex_path, out_dir, jobs=None):
    """Generate a real multi-file source tree + a double-click launcher."""
    import xex
    x = xex.open_xex(xex_path)
    img = x.basefile()
    image_base = x.image_base or 0
    entry = x.entry_point or image_base
    name = _clean_name(x.module_name())

    # which functions are imports (xboxkrnl/xam thunks)? those get host shims,
    # not recompiled bodies (their bodies are patched at load and are meaningless).
    thunks = {}                                # {guest_addr: (library, ordinal)}
    for lib, recs in x.imports().items():
        for addr, ordv, kind in recs:
            if kind == "thunk":
                thunks[addr] = (lib, ordv)

    # recompile the whole image (this drives the progress UI via tmap), skipping
    # the import thunks — the host-shim layer provides those instead.
    _body, mapping, agg = ppcrecomp.recompile_image(xex_path, jobs=jobs, skip=set(thunks))
    parts, decls, chosen = agg["parts"], agg["decls"], agg["chosen"]

    inc = os.path.join(out_dir, "include")
    src = os.path.join(out_dir, "src")
    assets = os.path.join(out_dir, "assets")
    for d in (inc, src, assets):
        os.makedirs(d, exist_ok=True)

    # all text files are written UTF-8 (Windows' default cp encoding can't encode
    # some characters and would raise mid-write, leaving a truncated file).
    def _w(path, text):
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    # --- include/ : the runtime header, the shared declarations, the config ---
    _w(os.path.join(inc, "rex_ppc_min.h"), ppcrecomp.runtime_header())
    _w(os.path.join(inc, name + "_config.h"), _config_h(name, image_base, entry, len(img)))
    _w(os.path.join(inc, name + ".h"), _recomp_header(name, decls))
    _w(os.path.join(inc, "rex_host.h"), _host_h(name))   # guest heap + host helpers

    # --- src/ : the recompiled functions, split into many translation units ---
    shards = _shards(parts)
    for i, group in enumerate(shards):
        text = f'#include "{name}.h"\n\n' + "\n".join(group)
        _w(os.path.join(src, f"{name}_{i:04d}.cpp"), text)
    _w(os.path.join(src, name + "_init.cpp"), _init_cpp(name, chosen))
    _w(os.path.join(src, "rex_runtime.cpp"), _runtime_cpp(name, entry))
    # the host-shim layer: one typed stub per imported kernel/XAM function
    _w(os.path.join(src, name + "_imports.cpp"), _imports_cpp(name, thunks))

    # --- graphics/ : the native-D3D12 GPU subsystem (Xenia-shaped) ---
    import ppc_gpu_scaffold as gpu
    os.makedirs(os.path.join(out_dir, "graphics"), exist_ok=True)
    for rel, text in gpu.gpu_files(name).items():
        _w(os.path.join(out_dir, rel), text)
    _w(os.path.join(out_dir, "GPU_DESIGN.md"), gpu.design_md(name))
    # vendor the ReXGlue/Xenia DXBC shader translator (graphics/rex_dxbc/) so the
    # ShaderTranslator seam's __has_include lights up and shaders -> DXBC for real.
    have_dxbc = _copy_rex_dxbc(os.path.join(out_dir, "graphics", "rex_dxbc"))
    # vendor the RexGlue kernel core (kernel/rex_kernel/) so the recompiled code
    # bridges onto RexGlue's PPCContext + kernel (rex_ppc_min.h auto-detects it).
    have_kernel = _copy_rex_kernel(os.path.join(out_dir, "kernel", "rex_kernel"))

    # --- assets/ : the decoded basefile (standalone boot) + the raw .xex (the
    # RexGlue runtime decrypts/decompresses/loads it itself at boot) ---
    with open(os.path.join(assets, name + ".bin"), "wb") as f:
        f.write(img)
    try:
        import shutil as _sh
        _sh.copy2(xex_path, os.path.join(assets, name + ".xex"))
    except Exception:
        pass

    # --- build glue, launcher, docs ---
    _w(os.path.join(out_dir, "CMakeLists.txt"), _cmakelists(name))
    _w(os.path.join(out_dir, f"Play-{name}.bat"), _launcher_bat(name))
    _w(os.path.join(out_dir, "README.md"), _readme(name, agg, image_base, entry, len(shards)))

    agg["name"] = name
    agg["dir"] = out_dir
    agg["shards"] = len(shards)
    agg["imports"] = len(thunks)
    return agg


def _config_h(name, image_base, entry, image_size):
    return f"""// {name}_config.h - generated by XboxTranspiler
#pragma once
#include <cstdint>
#define PPC_IMAGE_BASE  0x{image_base:08X}ull
#define PPC_ENTRY_POINT 0x{entry:08X}u
#define PPC_IMAGE_SIZE  0x{image_size:X}ull
#define PPC_IMAGE_ASSET "{name}.bin"
#define PPC_XEX_ASSET   "{name}.xex"   // raw XEX (RexGlue runtime loads it at boot)
"""


def _recomp_header(name, decls):
    """The one shared header every src/*.cpp includes: runtime + all the function
    declarations + the mapping-table type. This is what lets the recompiled code
    be split across many translation units yet still call across them."""
    lines = [f"// {name}.h - generated by XboxTranspiler.",
             "// Shared declarations for the recompiled title: the runtime, the",
             "// config, and a forward declaration of every recompiled function so",
             "// the src/*.cpp translation units can call across each other.",
             "#pragma once",
             f'#include "{name}_config.h"',   # config first: the bridge's context.h may want it
             '#include "rex_ppc_min.h"',
             "",
             "// --- every recompiled guest function (defined across src/*.cpp) ---"]
    lines += [f"PPC_FUNC(sub_{a:08X});" for a in decls]
    lines += ["",
              "// guest address -> recompiled function, for indirect (bctr) calls.",
              "// In bridge mode the vendored RexGlue context.h already provides this",
              "// (with the same {guest, host} field layout), so we only define it",
              "// ourselves for the standalone build.",
              "#ifndef REX_PPC_BRIDGE",
              "struct PPCFuncMapping { size_t guest; PPCFunc* host; };",
              "extern PPCFuncMapping PPCFuncMappings[];",
              "#endif",
              ""]
    return "\n".join(lines)


def _init_cpp(name, chosen):
    lines = [f'#include "{name}.h"', "",
             "// The function-pointer table: guest address -> recompiled function.",
             "PPCFuncMapping PPCFuncMappings[] = {"]
    for va in chosen:
        lines.append(f"\t{{ 0x{va:08X}, sub_{va:08X} }},")
    lines += ["\t{ 0, nullptr },", "};", ""]
    return "\n".join(lines)


