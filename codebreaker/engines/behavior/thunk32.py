#!/usr/bin/env python3
r"""thunk32.py -- identify 32<->16 thunk layers (thunk-compiler / flat / generic thunks).

Win95 bridges 32-bit and 16-bit code through thunks generated by the thunk compiler and the
KERNEL32 thunk runtime. A module that is a thunk layer imports the thunk-runtime entry points
(ThunkConnect32/16, C16ThkSL01, QT_Thunk, FT_Thunk/FT_Prolog, ...) and carries a thunk data block.
Recognizing those tells you the module's role -- it marshals calls across the 16/32 boundary -- and
names the thunk-runtime calls instead of leaving them anonymous. Niche but real: it explains a whole
class of otherwise-opaque glue modules.
"""
_THUNK_APIS = {
    "THUNKCONNECT32": "flat-thunk connect (32)", "THUNKCONNECT16": "flat-thunk connect (16)",
    "C16THKSL01": "C 16->32 thunklet", "C32THKSL01": "C 32->16 thunklet", "THUNKINITLS": "thunk init",
    "QT_THUNK": "quick thunk (32->16)", "FT_THUNK": "flat thunk (16->32)", "FT_PROLOG": "flat-thunk prolog",
    "FT_EXIT": "flat-thunk exit", "SSONBIGSTACK": "switch to 32-bit stack", "SSCALL": "system stack call",
    "MAPLS": "map 16:16 -> flat", "UNMAPLS": "unmap flat ptr", "MAPSL": "map flat -> 16:16",
    "GETVDMPOINTER32W": "16:16 -> flat (VDM)", "ALLOCSLCALLBACK": "alloc 16->32 callback",
    "GETPROCADDRESS32W": "32-bit GetProcAddress (thunk)",
}


def _pe_imports(module):
    from codebreaker.core import cores
    from codebreaker.formats.pe import PEFile
    pe = PEFile(cores.get("target").resolve(module))
    return {nm.upper() for _va, (_dll, nm) in pe.imports().items()}


def _ne_imports(path):
    from codebreaker.formats.ne import NEFile
    ne = NEFile(path)
    out = set()
    for s in ne.segments():
        for r in ne.relocations(s):
            if r.get("kind") == "IMPORTNAME":
                out.add(ne.imported_name(r["name_off"]).upper())
    return out


def detect(module, path=None):
    """{'is_thunk','mechanism','thunk_apis'} -- whether the module is a 32<->16 thunk layer."""
    names = set()
    for getter in (lambda: _pe_imports(module), lambda: _ne_imports(path or module)):
        try:
            names |= getter()
        except Exception:
            pass
    hits = {n: _THUNK_APIS[n] for n in names if n in _THUNK_APIS}
    if not hits:
        return {"is_thunk": False, "thunk_apis": {}}
    if any(k in hits for k in ("QT_THUNK", "MAPLS", "GETVDMPOINTER32W")):
        mech = "flat thunk (KERNEL32 thunk runtime)"
    elif any(k in hits for k in ("THUNKCONNECT32", "THUNKCONNECT16", "C16THKSL01")):
        mech = "thunk-compiler flat thunk"
    else:
        mech = "generic/other thunk"
    return {"is_thunk": True, "mechanism": mech, "thunk_apis": hits}


def reconstruct(module, path=None):
    d = detect(module, path)
    if not d["is_thunk"]:
        return {"ok": False, "reason": "not a 32<->16 thunk layer"}
    return {"ok": True, "mechanism": d["mechanism"], "thunk_apis": sorted(d["thunk_apis"])}
