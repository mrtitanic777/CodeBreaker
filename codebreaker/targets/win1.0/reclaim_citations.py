#!/usr/bin/env python3
"""
reclaim_citations.py — credit reconstruction work that was already done.

The coverage ledger only counts a function as read once a reconstruction *cites
its address* (`MOD.ord` or `segN:0xHHHH`). `nametodo` found 114 system-module
functions that ARE already reconstructed by their export name (SelectObject,
CreateWindow, ButtonWndProc, …) but never got that token — so the ledger
under-counts genuine work.

This tool recovers exactly those, and ONLY those, with a verified binding:

    a reconstruction DEFINES a function called <Name>
      AND ORDINALS.md binds <Name> to exactly one ordinal MOD.ord   (no ambiguity)
      AND the module entry table binds MOD.ord to (seg,off)          (Microsoft's own export)
      AND (seg,off) is not already cited

For each, it writes one line into reconstructed/system/_recovered_citations.c —
a verified INDEX, not a reconstruction: every line is a comment carrying the
module-qualified `MOD.ord` token (which is what the ledger credits, unambiguously)
plus the address and the file where the real body lives. No function bodies, so
the transcribed-body count is untouched; this moves only the "addressed" figure,
and only for work that provably exists.

    wt --target win1.0 reclaim_citations            # preview (default, no writes)
    wt --target win1.0 reclaim_citations --apply     # write the index file
"""
import os
import re
import sys
import glob
import collections

import _wtroot
import ledger
import trace
from codebreaker.foundation import layout

ROOT = _wtroot.data_root(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(layout.recon_sub("system", ROOT), "_recovered_citations.c")
MODRX = r"(KERNEL|GDI|USER|SYSTEM|KEYBOARD|MOUSE|DISPLAY|SOUND|COMM)"


def verified():
    os.chdir(ROOT)
    names = trace.load_ordinals("ORDINALS.md")          # 'GDI.45' -> 'SelectObject'
    tot = ledger.module_totals()
    cites = ledger.cited_addresses(tot)

    name2ord = collections.defaultdict(set)
    ord2addr = {}
    for key, nm in names.items():
        m = re.match(r"^%s\.(\d+)$" % MODRX, key)
        if not m:
            continue
        mod, ordn = m.group(1), int(m.group(2))
        if mod not in tot:
            continue
        seg, off = trace.find_seg_of_entry(tot[mod]["ne"], ordn)
        if seg is None:
            continue
        name2ord[nm.lower()].add(key)
        ord2addr[key] = (seg, off)

    # where each name is DEFINED (a real function body), across reconstructions
    def_locs = collections.defaultdict(list)
    fndef = re.compile(r"^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\([^;{]*\)\s*\{?\s*$")
    for f in glob.glob(os.path.join(layout.recon_dir(), "*.c")) + glob.glob(os.path.join(layout.recon_sub("system"), "*.c")):
        base = os.path.basename(f)
        if base == os.path.basename(OUT):
            continue
        for ln in open(f, encoding="utf-8", errors="replace"):
            m = fndef.match(ln)
            if m:
                def_locs[m.group(1).lower()].append(base)

    out, ambiguous = [], []
    for nml, ords in name2ord.items():
        if nml not in def_locs:
            continue                                    # not reconstructed
        if len(ords) != 1:
            ambiguous.append(nml)                       # name -> many ordinals: unsafe
            continue
        key = next(iter(ords))
        seg, off = ord2addr[key]
        mod = key.split(".")[0]
        if (seg, off) in cites.get(mod, set()):
            continue                                    # already credited
        out.append(dict(ord=key, name=names[key], seg=seg, off=off,
                        where=sorted(set(def_locs[nml]))))
    out.sort(key=lambda r: (r["ord"].split(".")[0], int(r["ord"].split(".")[1])))
    return out, ambiguous


def main():
    rows, ambiguous = verified()
    bymod = collections.Counter(r["ord"].split(".")[0] for r in rows)
    print("verified reclaimable citations: %d   (skipped %d ambiguous name->ordinal)"
          % (len(rows), len(ambiguous)))
    print("by module: " + "  ".join("%s=%d" % (m, n) for m, n in sorted(bymod.items())))
    for r in rows[:12]:
        print("  %-12s %-24s seg%d:0x%04x   body in %s"
              % (r["ord"], r["name"], r["seg"], r["off"], ", ".join(r["where"])))
    if len(rows) > 12:
        print("  … %d more" % (len(rows) - 12))

    if "--apply" not in sys.argv:
        print("\n(preview only — re-run with --apply to write %s)"
              % os.path.relpath(OUT, ROOT))
        return

    lines = [
        "/* _recovered_citations.c — VERIFIED INDEX, not a reconstruction.",
        " *",
        " * Generated by `wt --target win1.0 reclaim_citations --apply`.",
        " * Each line below is a function that is ALREADY reconstructed (its body",
        " * lives in the cited file) but whose address the ledger had not yet been",
        " * told. The `MOD.ord` token credits the work that exists; the binding is",
        " * Microsoft's own export table (ordinal -> address) cross-checked against",
        " * the recovered .SYM name in ORDINALS.md. No bodies here — this moves the",
        " * addressed figure only, and only for work that provably exists.",
        " */",
        "",
    ]
    for r in rows:
        lines.append("/* %-12s seg%d:0x%04x  %-24s  body: %s */"
                     % (r["ord"], r["seg"], r["off"], r["name"], ", ".join(r["where"])))
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\nwrote %s  (%d verified citations)" % (os.path.relpath(OUT, ROOT), len(rows)))
    print("re-run `wt --target win1.0 nametodo` and `ledger.py` to see the credit.")


if __name__ == "__main__":
    main()
