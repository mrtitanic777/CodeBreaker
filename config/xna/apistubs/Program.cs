// apistubs -- C# stubs of a .NET assembly's public API, read from its metadata (System.Reflection.Metadata, part of
// .NET): every public type of the namespaces asked for, with its members, their bodies doing nothing (a value
// type's or null result; an IAsyncResult already completed, its callback called). The `xna` lane's port step
// stubs the XNA 4.0 assemblies MonoGame lacks (GamerServices, Net, Storage, Avatar) so a game's calls compile;
// what a game needs to do something real is written by hand (codebreaker/xna/runtime) and left out here.
//
//   apistubs <assembly.dll> <out.cs> <namespace prefix> [skip type ...]
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;

static class Program
{
    static MetadataReader md;
    static readonly HashSet<string> skip = new HashSet<string>();
    static readonly HashSet<string> keywords = new HashSet<string> { "object", "string", "event", "base", "params", "operator",
        "checked", "fixed", "lock", "ref", "out", "in", "is", "as", "new", "this", "default", "class", "struct" };

    static int Main(string[] args)
    {
        if (args.Length < 3) { Console.Error.WriteLine("apistubs <assembly.dll> <out.cs> <namespace prefix> [skip type ...]"); return 2; }
        foreach (var s in args.Skip(3)) skip.Add(s);
        using var pe = new PEReader(File.OpenRead(args[0]));
        md = pe.GetMetadataReader();
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by codebreaker/xna/apistubs from " + Path.GetFileName(args[0]) + "'s public API: the members");
        sb.AppendLine("// do nothing. #pragma: the stubs leave events unraised and parameters unused.");
        sb.AppendLine("#pragma warning disable 67, 108, 109, 114, 169, 414, 649, 693, 1066, 3021");
        sb.AppendLine("using System;");
        var byNs = new SortedDictionary<string, List<TypeDefinition>>();
        foreach (var h in md.TypeDefinitions)
        {
            var t = md.GetTypeDefinition(h);
            if (!t.GetDeclaringType().IsNil) continue;
            if ((t.Attributes & TypeAttributes.VisibilityMask) != TypeAttributes.Public) continue;
            string ns = md.GetString(t.Namespace);
            if (!ns.StartsWith(args[2])) continue;
            if (skip.Contains(md.GetString(t.Name).Split('`')[0])) continue;
            if (!byNs.TryGetValue(ns, out var list)) byNs[ns] = list = new List<TypeDefinition>();
            list.Add(t);
        }
        foreach (var (ns, types) in byNs)
        {
            sb.AppendLine("namespace " + ns + " {");
            foreach (var t in types) EmitType(sb, t, "    ");
            sb.AppendLine("}");
        }
        File.WriteAllText(args[1], sb.ToString());
        Console.WriteLine("stubbed " + byNs.Values.Sum(l => l.Count) + " types");
        return 0;
    }

    static string Name(string n) { n = n.Split('`')[0]; return keywords.Contains(n) ? "@" + n : n; }

    static string GenericParams(GenericParameterHandleCollection gps, int skipOuter = 0)
    {
        var names = gps.Skip(skipOuter).Select(g => md.GetString(md.GetGenericParameter(g).Name)).ToList();
        return names.Count == 0 ? "" : "<" + string.Join(", ", names) + ">";
    }

    static bool IsPublic(MethodAttributes a) => (a & MethodAttributes.MemberAccessMask) == MethodAttributes.Public ||
                                                (a & MethodAttributes.MemberAccessMask) == MethodAttributes.Family ||
                                                (a & MethodAttributes.MemberAccessMask) == MethodAttributes.FamORAssem;

    static string Access(MethodAttributes a) => (a & MethodAttributes.MemberAccessMask) == MethodAttributes.Public ? "public" : "protected";

    static string BaseName(EntityHandle h, TypeProvider p)
    {
        if (h.IsNil) return null;
        string n = h.Kind == HandleKind.TypeSpecification ? md.GetTypeSpecification((TypeSpecificationHandle)h).DecodeSignature(p, null)
                 : p.Named(h);
        return n;
    }

    static void EmitType(StringBuilder sb, TypeDefinition t, string ind)
    {
        var p = new TypeProvider();
        string name = Name(md.GetString(t.Name));
        string baseName = BaseName(t.BaseType, p);
        bool isEnum = baseName == "System.Enum", isStruct = baseName == "System.ValueType";
        bool isInterface = (t.Attributes & TypeAttributes.Interface) != 0;
        bool isDelegate = baseName == "System.MulticastDelegate";
        bool isStatic = (t.Attributes & TypeAttributes.Abstract) != 0 && (t.Attributes & TypeAttributes.Sealed) != 0;
        string gp = GenericParams(t.GetGenericParameters(), CountOuterGenerics(t));
        if (isEnum)
        {
            string under = "int";
            var vals = new List<string>();
            foreach (var fh in t.GetFields())
            {
                var f = md.GetFieldDefinition(fh);
                string fn = md.GetString(f.Name);
                if (fn == "value__") { under = f.DecodeSignature(p, null); continue; }
                var c = f.GetDefaultValue();
                vals.Add(Name(fn) + (c.IsNil ? "" : " = " + Constant(md.GetConstant(c))));
            }
            bool flags = HasAttribute(t.GetCustomAttributes(), "FlagsAttribute");
            sb.AppendLine(ind + (flags ? "[Flags] " : "") + "public enum " + name + " : " + under + " { " + string.Join(", ", vals) + " }");
            return;
        }
        if (isDelegate)
        {
            foreach (var mh in t.GetMethods())
            {
                var m = md.GetMethodDefinition(mh);
                if (md.GetString(m.Name) != "Invoke") continue;
                var sig = m.DecodeSignature(p, null);
                sb.AppendLine(ind + "public delegate " + sig.ReturnType + " " + name + gp + "(" + Params(m, sig) + ");");
            }
            return;
        }
        string kind = isInterface ? "interface" : isStruct ? "struct" : (isStatic ? "static class" : ((t.Attributes & TypeAttributes.Abstract) != 0 ? "abstract class" : "class"));
        var bases = new List<string>();
        if (!isInterface && !isStruct && baseName != null && baseName != "System.Object") bases.Add(baseName);
        foreach (var ih in t.GetInterfaceImplementations())
        {
            var ii = md.GetInterfaceImplementation(ih);
            string iname = BaseName(ii.Interface, p);
            if (iname != null && !iname.Contains("Microsoft.Xna.Framework.GamerServices.") || iname != null && Public(ii.Interface)) bases.Add(iname);
        }
        sb.AppendLine(ind + "public " + (kind == "class" ? "partial class" : kind == "abstract class" ? "abstract partial class" : kind) + " " + name + gp +
                      (bases.Count > 0 ? " : " + string.Join(", ", bases.Distinct()) : "") + " {");
        string inner = ind + "    ";
        string baseInit = BaseInit(baseName);
        // a parameterless constructor for subclasses and the stubs' own use
        bool publicDefault = false;
        foreach (var mh0 in t.GetMethods())
        {
            var m0 = md.GetMethodDefinition(mh0);
            if (md.GetString(m0.Name) == ".ctor" && m0.DecodeSignature(p, null).ParameterTypes.Length == 0 &&
                (m0.Attributes & MethodAttributes.MemberAccessMask) == MethodAttributes.Public) publicDefault = true;
        }
        if (!isInterface && !isStatic && !isStruct)
            sb.AppendLine(inner + (publicDefault ? "public " : "protected ") + name + "()" + baseInit + " { }");
        var accessors = new HashSet<MethodDefinitionHandle>();
        foreach (var ph in t.GetProperties())
        {
            var prop = md.GetPropertyDefinition(ph);
            var acc = prop.GetAccessors();
            if (!acc.Getter.IsNil) accessors.Add(acc.Getter);
            if (!acc.Setter.IsNil) accessors.Add(acc.Setter);
            var any = !acc.Getter.IsNil ? md.GetMethodDefinition(acc.Getter) : md.GetMethodDefinition(acc.Setter);
            string propName = md.GetString(prop.Name);
            bool explicitImpl = propName.Contains(".");
            if (!IsPublic(any.Attributes) && !explicitImpl) continue;
            var sig = prop.DecodeSignature(p, null);
            bool st = (any.Attributes & MethodAttributes.Static) != 0;
            string pn = md.GetString(prop.Name);
            string head = isInterface || explicitImpl ? "" : Access(any.Attributes) + " " + (st ? "static " : "") + Virtual(any.Attributes, isStruct);
            bool showGet = !acc.Getter.IsNil && (explicitImpl || IsPublic(md.GetMethodDefinition(acc.Getter).Attributes));
            bool showSet = !acc.Setter.IsNil && (explicitImpl || IsPublic(md.GetMethodDefinition(acc.Setter).Attributes));
            string get = showGet ? (isInterface ? "get; " : "get { return default(" + sig.ReturnType + "); } ") : "";
            string set = showSet ? (isInterface ? "set; " : "set { } ") : "";
            if (explicitImpl) pn = propName;
            if (get == "" && set == "") continue;
            if (sig.ParameterTypes.Length > 0)
            {
                var ps = string.Join(", ", sig.ParameterTypes.Select((ty, i) => ty + " i" + i));
                string idx = explicitImpl ? Explicit(pn.Substring(0, pn.LastIndexOf('.'))) + ".this" : "this";
                sb.AppendLine(inner + head + sig.ReturnType + " " + idx + "[" + ps + "] { " + get + set + "}");
            }
            else sb.AppendLine(inner + head + sig.ReturnType + " " + (explicitImpl ? Explicit(pn) : Name(pn)) + " { " + get + set + "}");
        }
        foreach (var eh in t.GetEvents())
        {
            var ev = md.GetEventDefinition(eh);
            var acc = ev.GetAccessors();
            if (!acc.Adder.IsNil) accessors.Add(acc.Adder);
            if (!acc.Remover.IsNil) accessors.Add(acc.Remover);
            var add = md.GetMethodDefinition(acc.Adder);
            if (!IsPublic(add.Attributes)) continue;
            string evType = BaseName(ev.Type, p);
            bool st = (add.Attributes & MethodAttributes.Static) != 0;
            sb.AppendLine(inner + (isInterface ? "" : "public " + (st ? "static " : "")) + "event " + evType + " " + Name(md.GetString(ev.Name)) + ";");
        }
        foreach (var fh in t.GetFields())
        {
            var f = md.GetFieldDefinition(fh);
            var fa = f.Attributes & FieldAttributes.FieldAccessMask;
            if (fa != FieldAttributes.Public && fa != FieldAttributes.Family) continue;
            string ft = f.DecodeSignature(p, null);
            bool st = (f.Attributes & FieldAttributes.Static) != 0;
            bool lit = (f.Attributes & FieldAttributes.Literal) != 0;
            string fn = Name(md.GetString(f.Name));
            if (lit && !f.GetDefaultValue().IsNil)
                sb.AppendLine(inner + "public const " + ft + " " + fn + " = " + Constant(md.GetConstant(f.GetDefaultValue())) + ";");
            else
                sb.AppendLine(inner + (fa == FieldAttributes.Public ? "public " : "protected ") + (st ? "static " : "") +
                              ((f.Attributes & FieldAttributes.InitOnly) != 0 ? "readonly " : "") + ft + " " + fn + ";");
        }
        foreach (var mh in t.GetMethods())
        {
            if (accessors.Contains(mh)) continue;
            var m = md.GetMethodDefinition(mh);
            string mn = md.GetString(m.Name);
            bool explicitMethod = mn.Contains(".") && !mn.StartsWith(".") && (m.Attributes & MethodAttributes.Virtual) != 0;
            if (!IsPublic(m.Attributes) && !explicitMethod) continue;
            if (mn == ".cctor" || mn == "Finalize" || mn == "GetObjectData") continue;
            var sig = m.DecodeSignature(p, null);
            bool st = (m.Attributes & MethodAttributes.Static) != 0;
            string ps = Params(m, sig);
            if (mn == ".ctor")
            {
                if (sig.ParameterTypes.Length == 0 && !isStruct)
                {
                    continue;   // written above, public when XNA's is
                }
                sb.AppendLine(inner + Access(m.Attributes) + " " + name + "(" + ps + ")" + (isStruct ? " : this()" : baseInit) + " { " + OutDefaults(m, sig) + "}");
                continue;
            }
            if (mn.StartsWith("op_"))
            {
                string op = Operator(mn);
                if (op == null) continue;
                sb.AppendLine(inner + "public static " + (op == "implicit" || op == "explicit" ? op + " operator " + sig.ReturnType : sig.ReturnType + " operator " + op) +
                              "(" + ps + ") { return default(" + sig.ReturnType + "); }");
                continue;
            }
            string mgp = GenericParams(m.GetGenericParameters());
            string head = isInterface || explicitMethod ? "" : Access(m.Attributes) + " " + (st ? "static " : "") + Virtual(m.Attributes, isStruct);
            if (explicitMethod) mn = Explicit(mn);
            if (isInterface) { sb.AppendLine(inner + sig.ReturnType + " " + Name(mn) + mgp + "(" + ps + ");"); continue; }
            if ((m.Attributes & MethodAttributes.Abstract) != 0 && !isInterface)
            {
                sb.AppendLine(inner + Access(m.Attributes) + " abstract " + sig.ReturnType + " " + Name(mn) + mgp + "(" + ps + ");");
                continue;
            }
            string body = sig.ReturnType == "void" ? OutDefaults(m, sig)
                        : sig.ReturnType.EndsWith("System.IAsyncResult") ? OutDefaults(m, sig) + "return XnaPort.Completed.Call(" + CallbackArg(m, sig) + "); "
                        : OutDefaults(m, sig) + "return default(" + sig.ReturnType + "); ";
            sb.AppendLine(inner + head + sig.ReturnType + " " + (explicitMethod ? mn : Name(mn)) + mgp + "(" + ps + ") { " + body + "}");
        }
        foreach (var nh in t.GetNestedTypes())
        {
            var n = md.GetTypeDefinition(nh);
            if ((n.Attributes & TypeAttributes.VisibilityMask) == TypeAttributes.NestedPublic)
                EmitType(sb, n, inner);
        }
        sb.AppendLine(ind + "}");
    }

    // An explicit implementation's metadata name ("System.Collections.Generic.ICollection<...>.Add") as C# writes it.
    static string Explicit(string n) => n.Replace("System.Collections.Generic.", "global::System.Collections.Generic.")
                                         .Replace("System.Collections.I", "global::System.Collections.I")
                                         .Replace("<Microsoft.", "<global::Microsoft.").Replace(", Microsoft.", ", global::Microsoft.")
                                         .Replace("System.IDisposable.", "global::System.IDisposable.");

    // .NET base classes without a parameterless constructor: what a stub's constructors hand them.
    static string BaseInit(string baseName)
    {
        if (baseName == null) return "";
        if (baseName.StartsWith("global::System.Collections.ObjectModel.ReadOnlyCollection<"))
        {
            string arg = baseName.Substring(baseName.IndexOf('<'));
            return " : base(new global::System.Collections.Generic.List" + arg + "())";
        }
        if (baseName == "global::System.IO.BinaryReader" || baseName == "global::System.IO.BinaryWriter")
            return " : base(new global::System.IO.MemoryStream())";
        return "";
    }

    static int CountOuterGenerics(TypeDefinition t)
    {
        var d = t.GetDeclaringType();
        return d.IsNil ? 0 : md.GetTypeDefinition(d).GetGenericParameters().Count;
    }

    static bool Public(EntityHandle h)
    {
        if (h.Kind != HandleKind.TypeDefinition) return true;
        var t = md.GetTypeDefinition((TypeDefinitionHandle)h);
        var v = t.Attributes & TypeAttributes.VisibilityMask;
        return v == TypeAttributes.Public || v == TypeAttributes.NestedPublic;
    }

    static string Virtual(MethodAttributes a, bool isStruct)
    {
        if (isStruct || (a & MethodAttributes.Virtual) == 0) return "";
        if ((a & MethodAttributes.Final) != 0) return "";
        return (a & MethodAttributes.NewSlot) != 0 ? "virtual " : "override ";
    }

    static string Params(MethodDefinition m, MethodSignature<string> sig)
    {
        var names = new Dictionary<int, (string, ParameterAttributes)>();
        foreach (var ph in m.GetParameters())
        {
            var pr = md.GetParameter(ph);
            if (pr.SequenceNumber > 0) names[pr.SequenceNumber] = (md.GetString(pr.Name), pr.Attributes);
        }
        var parts = new List<string>();
        for (int i = 0; i < sig.ParameterTypes.Length; i++)
        {
            string ty = sig.ParameterTypes[i];
            string n = names.TryGetValue(i + 1, out var nn) && nn.Item1 != "" ? Name(nn.Item1) : "p" + i;
            if (ty.EndsWith("&"))
            {
                bool isOut = names.TryGetValue(i + 1, out var x) && (x.Item2 & ParameterAttributes.Out) != 0 && (x.Item2 & ParameterAttributes.In) == 0;
                parts.Add((isOut ? "out " : "ref ") + ty.TrimEnd('&') + " " + n);
            }
            else parts.Add(ty + " " + n);
        }
        return string.Join(", ", parts);
    }

    static string OutDefaults(MethodDefinition m, MethodSignature<string> sig)
    {
        var sb = new StringBuilder();
        var names = new Dictionary<int, (string, ParameterAttributes)>();
        foreach (var ph in m.GetParameters())
        {
            var pr = md.GetParameter(ph);
            if (pr.SequenceNumber > 0) names[pr.SequenceNumber] = (md.GetString(pr.Name), pr.Attributes);
        }
        for (int i = 0; i < sig.ParameterTypes.Length; i++)
            if (sig.ParameterTypes[i].EndsWith("&") && names.TryGetValue(i + 1, out var x) && (x.Item2 & ParameterAttributes.Out) != 0 && (x.Item2 & ParameterAttributes.In) == 0)
                sb.Append((x.Item1 != "" ? Name(x.Item1) : "p" + i) + " = default(" + sig.ParameterTypes[i].TrimEnd('&') + "); ");
        return sb.ToString();
    }

    static string CallbackArg(MethodDefinition m, MethodSignature<string> sig)
    {
        string cb = "null", state = "null";
        int i = 0;
        foreach (var ph in m.GetParameters())
        {
            var pr = md.GetParameter(ph);
            if (pr.SequenceNumber == 0) continue;
            string ty = sig.ParameterTypes[pr.SequenceNumber - 1];
            if (ty.EndsWith("System.AsyncCallback")) cb = Name(md.GetString(pr.Name));
            else if (ty == "object" || ty.EndsWith("System.Object")) state = Name(md.GetString(pr.Name));
            i++;
        }
        return cb + ", " + state;
    }

    static string Operator(string n) => n switch
    {
        "op_Equality" => "==", "op_Inequality" => "!=", "op_Implicit" => "implicit", "op_Explicit" => "explicit",
        "op_Addition" => "+", "op_Subtraction" => "-", "op_LessThan" => "<", "op_GreaterThan" => ">", _ => null
    };

    static bool HasAttribute(CustomAttributeHandleCollection attrs, string name)
    {
        foreach (var ah in attrs)
        {
            var a = md.GetCustomAttribute(ah);
            if (a.Constructor.Kind == HandleKind.MemberReference)
            {
                var mr = md.GetMemberReference((MemberReferenceHandle)a.Constructor);
                if (mr.Parent.Kind == HandleKind.TypeReference && md.GetString(md.GetTypeReference((TypeReferenceHandle)mr.Parent).Name) == name) return true;
            }
        }
        return false;
    }

    static string Constant(Constant c)
    {
        var b = md.GetBlobReader(c.Value);
        return c.TypeCode switch
        {
            ConstantTypeCode.Boolean => b.ReadBoolean() ? "true" : "false",
            ConstantTypeCode.Char => "'\\u" + ((int)b.ReadChar()).ToString("X4") + "'",
            ConstantTypeCode.SByte => b.ReadSByte().ToString(), ConstantTypeCode.Byte => b.ReadByte().ToString(),
            ConstantTypeCode.Int16 => b.ReadInt16().ToString(), ConstantTypeCode.UInt16 => b.ReadUInt16().ToString(),
            ConstantTypeCode.Int32 => b.ReadInt32().ToString(), ConstantTypeCode.UInt32 => b.ReadUInt32() + "u",
            ConstantTypeCode.Int64 => b.ReadInt64() + "L", ConstantTypeCode.UInt64 => b.ReadUInt64() + "UL",
            ConstantTypeCode.Single => b.ReadSingle().ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
            ConstantTypeCode.Double => b.ReadDouble().ToString("R", System.Globalization.CultureInfo.InvariantCulture),
            ConstantTypeCode.String => "\"" + (b.ReadSerializedString() ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
            _ => "default"
        };
    }

    sealed class TypeProvider : ISignatureTypeProvider<string, object>
    {
        public string Named(EntityHandle h) => h.Kind == HandleKind.TypeDefinition ? GetTypeFromDefinition(md, (TypeDefinitionHandle)h, 0)
                                                                                 : GetTypeFromReference(md, (TypeReferenceHandle)h, 0);
        public string GetArrayType(string e, ArrayShape s) => e + "[" + new string(',', s.Rank - 1) + "]";
        public string GetByReferenceType(string e) => e + "&";
        public string GetFunctionPointerType(MethodSignature<string> s) => "IntPtr";
        public string GetGenericInstantiation(string g, ImmutableArray<string> a)
        {
            g = g.Split('`')[0];
            if (g.EndsWith("<T>")) g = g.Substring(0, g.Length - 3);   // a definition named with its parameter
            else if (g.Contains("<T>.")) return g;   // a nested type of a generic one: the outer type carries the argument
            return g + "<" + string.Join(", ", a) + ">";
        }
        public string GetGenericMethodParameter(object c, int i) => "M" + i;
        public string GetGenericTypeParameter(object c, int i) => "T";
        public string GetModifiedType(string m, string u, bool r) => u;
        public string GetPinnedType(string e) => e;
        public string GetPointerType(string e) => e + "*";
        public string GetPrimitiveType(PrimitiveTypeCode t) => t switch
        {
            PrimitiveTypeCode.Boolean => "bool", PrimitiveTypeCode.Byte => "byte", PrimitiveTypeCode.Char => "char",
            PrimitiveTypeCode.Double => "double", PrimitiveTypeCode.Int16 => "short", PrimitiveTypeCode.Int32 => "int",
            PrimitiveTypeCode.Int64 => "long", PrimitiveTypeCode.IntPtr => "IntPtr", PrimitiveTypeCode.Object => "object",
            PrimitiveTypeCode.SByte => "sbyte", PrimitiveTypeCode.Single => "float", PrimitiveTypeCode.String => "string",
            PrimitiveTypeCode.UInt16 => "ushort", PrimitiveTypeCode.UInt32 => "uint", PrimitiveTypeCode.UInt64 => "ulong",
            PrimitiveTypeCode.UIntPtr => "UIntPtr", PrimitiveTypeCode.Void => "void", _ => "object"
        };
        public string GetSZArrayType(string e) => e + "[]";
        public string GetTypeFromDefinition(MetadataReader r, TypeDefinitionHandle h, byte k)
        {
            var t = r.GetTypeDefinition(h);
            var d = t.GetDeclaringType();
            string raw = r.GetString(t.Name);
            string n = raw.Split('`')[0] + (raw.Contains('`') ? "<T>" : "");
            return d.IsNil ? "global::" + r.GetString(t.Namespace) + "." + n : GetTypeFromDefinition(r, d, k) + "." + n;
        }
        public string GetTypeFromReference(MetadataReader r, TypeReferenceHandle h, byte k)
        {
            var t = r.GetTypeReference(h);
            string n = r.GetString(t.Name).Split('`')[0];
            if (t.ResolutionScope.Kind == HandleKind.TypeReference)
                return GetTypeFromReference(r, (TypeReferenceHandle)t.ResolutionScope, k) + "." + n;
            string ns = r.GetString(t.Namespace);
            return (ns == "System" && (n == "Object" || n == "Enum" || n == "ValueType" || n == "MulticastDelegate")) ? "System." + n
                 : "global::" + ns + "." + n;
        }
        public string GetTypeFromSpecification(MetadataReader r, object c, TypeSpecificationHandle h, byte k) =>
            r.GetTypeSpecification(h).DecodeSignature(this, c);
    }
}
