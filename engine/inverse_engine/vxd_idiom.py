#!/usr/bin/env python3
r"""vxd_idiom.py -- re-emit a recovered VxD in the idiomatic DDK-macro source form.

The byte-exact tree (vxd_tree/vxd_masm) is correct but low-level: `db`/`cmp`/`jmp` + raw `int 20h`.
Real Win95 VxD source used the DDK macros (confirmed by the Dr.Dobb's shell + VMM.INC): the DDB is a
`Declare_Virtual_Device`, the control proc is `Begin_Control_Dispatch` / `Control_Dispatch <Msg>,
<Handler>` / `End_Control_Dispatch`, a service call is `VMMcall`/`VxDcall <name>`, functions are
`BeginProc`/`EndProc`, segments are `VxD_LOCKED_CODE_SEG`. Those macros EXPAND to exactly the bytes
we recover (verified: `VMMCall Get_System_Time` -> cd203f000100), so the idiomatic form is not just
readable -- it re-assembles to the same image, `include vmm.inc` and all.

This module transforms the recovered structures into that macro form and (via assemble_and_verify)
checks the macro-generated bytes against the oracle.
"""
import os
import re

from engine.inverse_engine.vxd_asm import VxDDisasm
from engine.inverse_engine import vxd_masm, vxd_services

# a branch operand that is a bare number (optionally SHORT/NEAR PTR-pinned) -- ML's "jump destination
# must specify a label"; these are self-relative call/jmp (e8/e9 rel32=0, a PIC idiom) our disasm
# renders numerically. Byte-preserve them like the converging verifier does.
_NUM_TARGET = re.compile(r"^(?:SHORT |NEAR PTR )?[0-9][0-9A-Fa-f]*h?$")

# VxD device id -> the DDK .INC that defines its services (so `VxDcall <name>` resolves). Only
# devices whose .INC actually ships in INC32 are listed; a call to any other device keeps its raw
# `int 20h`+DWORD bytes (still byte-exact, just not the macro form). VDD, e.g., has no public .INC.
DEVICE_INC = {
    0x0001: "VMM", 0x0003: "VPICD", 0x0004: "VDMAD", 0x0005: "VTD", 0x0006: "V86MMGR",
    0x0007: "PAGESWAP", 0x000B: "VSD", 0x000C: "VMD", 0x000D: "VKD", 0x000E: "VCD",
    0x0010: "BLOCKDEV", 0x0011: "VMCPD", 0x0014: "VNETBIOS", 0x0015: "DOSMGR", 0x0016: "VMPOLL",
    0x0017: "SHELL", 0x001E: "VXDLDR", 0x0021: "PAGEFILE", 0x0028: "VPOWERD", 0x002C: "VWIN32",
    0x002D: "VCOMM", 0x0033: "CONFIGMG", 0x0036: "VFBACKUP", 0x0038: "VCOND", 0x0040: "IFSMGR",
    0x0442: "VTDAPI",
}


def device_incs(D, oi):
    """INC files to include: vmm.inc always, plus one per foreign device this object calls."""
    incs = {"VMM"}
    for (o, a), row in D.insns.items():
        if o == oi and row.get("vxdcall"):
            dev = row["vxdcall"][0]
            if dev in DEVICE_INC:
                incs.add(DEVICE_INC[dev])
    return sorted(incs)


def svc_macro(dev, svc):
    """`VMMcall <name>` / `VxDcall <name>` for an INT 20h service, or None if the name is unknown
    (then the caller keeps the raw `int 20h`+DWORD bytes). PROVEN byte-exact: with vmm.inc included,
    `VMMcall Get_System_Time` assembles to cd203f000100, identical to the oracle."""
    from engine.inverse_engine.vxd_asm import VXD_DEVICES
    if dev not in DEVICE_INC:                              # no .INC to define the service @@equate ->
        return None                                        #  keep the raw int 20h+DWORD (e.g. VDD)
    devname = VXD_DEVICES.get(dev)
    name = vxd_services.load().name(devname, svc) if devname else None
    if not name:
        return None
    return "        %s %s" % ("VMMcall" if dev == 0x0001 else "VxDcall", name)


def ddb_macro(db):
    """`Declare_Virtual_Device` line for a recovered DDB. PROVEN byte-exact: with the recovered
    fields (crucially the REAL init_order, not Undefined_Init_Order) the macro's _LDATA DDB matches
    the oracle byte-for-byte. A VxD with a service table additionally needs Begin_Service_Table."""
    return "Declare_Virtual_Device %s, %d, %d, %s_Control, 0%04Xh, 0%08Xh" % (
        db["name"], db["major"], db["minor"], db["name"], db["device_id"], db["init_order"])


def service_table(D, emittable):
    """Recover the VxD's own exported service table. The DDB (VxD_Desc_Block) carries a
    Service_Table_Ptr (+0x30) and Service_Table_Size (+0x34); the table is Size DWORD pointers, one
    per service, each a fixup to that service's handler. Returns (names, (obj, off, count), extra):

    - names[i] is service i's own DDK name (or 'RESERVED' for a null slot). It is taken per INDEX, not
      from the handler's disasm label, so several services that SHARE one handler routine (retail stubs
      many debug services onto Out_Debug_String) each keep their distinct name instead of colliding.
    - extra maps a handler offset -> the service names to emit as EXTRA labels there (those that are
      not already the disasm label at that offset), so `<name>_Service <svc>` resolves for every one.
    - the tuple locates the raw table bytes so the object walk can skip them.

    Returns (None, None, None) if there is no table, a handler landed mid-instruction (the pointer and a
    branch disagreed on alignment -> stays raw db, DDB keeps the zero fields), or two services carry the
    genuinely identical name. Emitted (see emit_idiomatic) as `Begin_Service_Table` / `<name>_Service
    <svc>, LOCAL` / `End_Service_Table` with `Create_<name>_Service_Table` so Declare_Virtual_Device
    fills the DDB Service_Table_Ptr/Size. Every service is forced LOCAL: the DDK INC marks a few non-
    LOCAL (they lived in a separately-linked object, EXTRN'd), but here every handler IS local."""
    db = D.ddb
    if not db:
        return None, None, None
    obj = db["obj"]
    r = db["rva"]
    # Service_Table_Ptr (+0x30) is stored as a zero-addend relocation on many VxDs: the raw dword is 0
    # and the real base lives in the fixup (exactly as _seeds resolves it via fsite). Prefer the fixup,
    # fall back to the raw dword. The table's object may differ from the DDB's, so read Size from the
    # DDB object and index the table in the object the fixup names.
    st = D.fsite(obj, r + 0x30)
    if st and st["kind"] == "internal":
        obj, ptr = st["obj"], st["target"]
    else:
        ptr = int.from_bytes(D.code[obj][r + 0x30:r + 0x34], "little")
    code = D.code[obj]
    count = int.from_bytes(D.code[db["obj"]][r + 0x34:r + 0x38], "little")
    if not (ptr is not None and 0 < count < 8192 and ptr + 4 * count <= len(code)):
        return None, None, None
    svc = vxd_services.load()
    names = []
    extra = {}
    used = set()
    for i in range(count):
        f = D.fx.get((obj, ptr + 4 * i))
        if not f:
            if int.from_bytes(code[ptr + 4 * i:ptr + 4 * i + 4], "little") == 0:
                names.append("RESERVED")          # genuine null slot -> macro emits dd 0
                continue
            return None, None, None               # non-zero without a fixup -> unexpected, keep raw
        tgt = (f["obj"], f["target"])
        if tgt not in emittable:                  # handler left mid-instruction -> can't be labelled
            return None, None, None
        nm = svc.name(db["name"], i) or "%s_Service_%03d" % (db["name"], i)   # key off the DDB name
        if nm in used:                            # two services with the identical name -> bail
            return None, None, None
        used.add(nm)
        names.append(nm)
        if nm != D.labels.get(tgt):               # emit nm as an extra label at the handler unless it
            extra.setdefault(tgt, []).append(nm)  #  already IS the disasm label there
    return names, (obj, ptr, count), extra


def _branch_label(D, oi, a, row, emittable):
    """The emitted label a direct branch targets, or None. Resolves a same-object target and a cross-
    object one (via the fixup on the branch operand); requires the target to be an emittable label so
    the macro's reference will resolve."""
    from engine.inverse_engine.vxd_asm import _direct_target_row
    t = _direct_target_row(row)
    if t is not None and (oi, t) in emittable:
        return D.labels.get((oi, t))
    for k in range(a + 1, a + row["size"]):
        f = D.fx.get((oi, k))
        if f and f.get("target") is not None and (f["obj"], f["target"]) in emittable:
            return D.labels.get((f["obj"], f["target"]))
    return None


def control_dispatch(D, emittable):
    """Recover the control-dispatch handlers AND the exact byte extent of the dispatch mechanism to
    skip when re-emitting it as `Begin_Control_Dispatch`. Returns (handlers, skip): handlers is
    [(MESSAGE_NAME, handler_label)] and skip is the {(obj,off)} the macro regenerates. Two shapes the
    DDK macro compiles to are recovered: a jump table (cmp/sub eax,N; jae default; jmp [tbl+eax*4] +
    the table, which may sit far from the prologue) and a compare chain (cmp eax,N; je handler,
    repeated). Every handler must resolve to an `emittable` label; if the proc matches neither shape,
    or any handler is unresolved, returns ([], set()) so the caller emits the whole proc verbatim as
    ordinary code -- correct and complete, never losing the routines between prologue and table."""
    from engine.inverse_engine import vxd_symbols
    db = D.ddb
    if not db:
        return [], set()
    cp = next((k for k, nm in D.labels.items() if nm == db["name"] + "_Control"), None)
    if not cp:
        return [], set()
    msgs = vxd_symbols.control_messages()
    oi, a0 = cp
    # --- jump-table form ---
    a = a0
    base = 0
    for _ in range(8):                                     # the prologue is short; do not walk far
        row = D.insns.get((oi, a))
        if not row:
            break
        if row["mnem"] == "sub" and row["ops"].replace(" ", "").startswith("eax,"):
            try:
                base = int(row["ops"].split(",")[1].strip(), 0)
            except ValueError:
                pass
        if row["mnem"] == "jmp" and "*4" in row["ops"]:
            skip = {(oi, k) for k in range(a0, a + row["size"])}          # prologue bytes
            jt = None
            for k in range(a, a + row["size"]):
                f = D.fx.get((oi, k))
                if f and f["kind"] == "internal" and f["obj"] == oi:
                    jt = D.jtables.get((f["obj"], f["target"]))
                    if jt:
                        skip |= {(oi, f["target"] + b) for b in range(len(jt) * 4)}   # table bytes
                    break
            b = a + row["size"]                                          # trailing unhandled stub
            while (oi, b) in D.insns and \
                    D.insns[(oi, b)]["mnem"] in ("clc", "stc", "cmc", "ret", "retn", "retf"):
                skip |= {(oi, k) for k in range(b, b + D.insns[(oi, b)]["size"])}
                b += D.insns[(oi, b)]["size"]
            out = []
            for i, tk in enumerate(jt or []):
                msg = i + base
                if msg in msgs and jt.count(tk) == 1 and tk in D.insns:
                    out.append((msgs[msg], D.labels.get(tk) or "loc_%d_%04X" % tk))
            return (out, skip) if out else ([], set())
        a += row["size"]
    # --- compare-chain form: cmp eax,N ; je handler (repeated) ---
    a = a0
    skip = set()
    out = []
    seen = set()
    while (oi, a) in D.insns:
        row = D.insns[(oi, a)]
        if row["mnem"] != "cmp" or not row["ops"].replace(" ", "").startswith("eax,"):
            break
        try:
            m = int(row["ops"].split(",")[1].strip(), 0)
        except ValueError:
            break
        jr = D.insns.get((oi, a + row["size"]))
        if not jr or jr["mnem"] not in ("je", "jz"):
            break
        lbl = _branch_label(D, oi, a + row["size"], jr, emittable)
        if m not in msgs or not lbl or m in seen:
            return [], set()                               # can't reproduce this arm -> emit verbatim
        seen.add(m)
        out.append((msgs[m], lbl))
        skip |= {(oi, k) for k in range(a, a + row["size"] + jr["size"])}
        a += row["size"] + jr["size"]
    if len(out) < 2:                                       # a lone cmp/je is not a dispatch chain
        return [], set()
    while (oi, a) in D.insns and \
            D.insns[(oi, a)]["mnem"] in ("clc", "stc", "cmc", "ret", "retn", "retf", "jmp"):
        r = D.insns[(oi, a)]                               # trailing default (fall-through / jmp)
        skip |= {(oi, k) for k in range(a, a + r["size"])}
        a += r["size"]
        if r["mnem"] == "jmp":
            break
    return out, skip


_SEG_MACRO = {"LCODE": "VxD_LOCKED_CODE", "ICODE": "VxD_ICODE", "PCODE": "VxD_PAGEABLE_CODE",
              "MCODE": "VxD_LOCKED_CODE"}

# mnemonics whose _masm_line text the period DDK ML (MASM 6.11) rejects or re-encodes -- almost all
# are byte runs the linear disasm reads as exotic/system instructions where the real bytes are data:
#   aam/aad  explicit 0Ah operand ML errors on (implicit base)     int1/int3  capstone's one-token INT
#   lcall/ljmp  capstone far-branch spelling                       ud0/ud1/ud2  undefined-instruction
#   lar/lsl  16-bit selector -> 32-bit reg (operand-size mismatch) salc  0xD6 SET AL on carry
#   les/lds/lfs/lgs/lss  far-pointer loads (capstone `ptr [..]`)
# Byte-preserving keeps the exact bytes and keeps ML out of trouble.
_RAW_MNEMS = {"aam", "aad", "lcall", "ljmp", "lar", "lsl", "int3", "int1", "ud0", "ud1", "ud2",
              "salc", "les", "lds", "lfs", "lgs", "lss",
              "fisttp", "fxsave", "fxrstor",   # SSE-era x87 the 1994 assembler predates (also data)
              "lidt", "lgdt", "sidt", "sgdt", "lldt", "sldt",   # capstone drops the `fword ptr` size
              "sysret", "sysenter", "sysexit"}                  # post-1994 fast-syscall (data misread)

_PREFIX_BYTES = {0x66, 0x67, 0xF0, 0xF2, 0xF3, 0x2E, 0x26, 0x36, 0x3E, 0x64, 0x65}
_SHIFTS = {"rcl", "rcr", "rol", "ror", "shl", "shr", "sal", "sar"}


def _shift_no_count(row):
    """A shift/rotate rendered with a single operand -- the implicit `,1` (D0/D1 encoding) that
    capstone drops but ML requires as an explicit count. Byte-preserve to keep the exact D0/D1 byte
    (rather than risk ML re-encoding `,1` to the C0/C1 imm8 form)."""
    return row["mnem"] in _SHIFTS and "," not in row["ops"]


_XMM_MM = re.compile(r"\b(?:xmm|mm)[0-7]\b")


def _ml611_unknown(row):
    """An instruction the 1994 MASM 6.11 predates and cannot assemble: SSE (xmm regs, 1999), MMX (mm
    regs, 1997), and the P6 conditional moves cmovcc/fcmovcc (1995). In a stripped ring-0 VxD these
    are invariably data the linear sweep mis-decoded; byte-preserve so ML never sees the mnemonic."""
    m = row["mnem"]
    return m.startswith("cmov") or m.startswith("fcmov") or bool(_XMM_MM.search(row["ops"]))


def _x87_stack(row):
    """An x87 op with a stack-register operand (`fadd st(3)`, `faddp st(0)`, capstone's `fstpnce`) --
    capstone's one-operand / non-standard spelling the DDK ML rejects. Rare in ring-0 VxD code and
    almost always data mis-decoded; byte-preserve. (fld/fstp with a memory operand stay symbolic.)"""
    return row["mnem"][:1] == "f" and "st(" in row["ops"]


def _indirect_branch(row):
    """A jmp/call through a memory operand (`call [edx+4]`, `jmp [edi+6fh]`) -- capstone renders it
    with a sizeless `ptr [..]` the DDK ML rejects (A2016). Byte-preserve (an indirect branch has no
    resolvable label target anyway; the recovered dispatch tables are handled separately)."""
    return row["mnem"] in ("jmp", "call") and "[" in row["ops"]


def _cap_size(row):
    """capstone's 80-bit memory-operand size keywords `xword`/`tword ptr` (e.g. `fld xword ptr [ebx]`)
    -- the DDK ML spells 80-bit memory `tbyte ptr` and reads `xword` as an undefined symbol. Byte-
    preserve (a real 80-bit fld/fstp, or data mis-decoded)."""
    return "xword" in row["ops"] or "tword" in row["ops"]


def _addr16(row):
    """True if the instruction carries a 0x67 address-size prefix -- i.e. 16-bit addressing (`[di]`,
    `[bp+si]`, ...) inside a use32 segment, which ML rejects (A2155, 16-bit register with a 32-bit
    address). These are almost always data misread as code or rare real 16-bit refs; byte-preserve."""
    for b in row["raw"][:4]:
        if b == 0x67:
            return True
        if b not in _PREFIX_BYTES:
            break
    return False


def _ddb_size(D, db):
    """Byte length of the on-disk VxD_Desc_Block, so the object walk can skip it (the top-level
    Declare_Virtual_Device re-emits it). The modern DDB carries a DDB_Prev='Prev' marker at +0x3C and
    its own size at +0x40; the classic pre-Win32 DDB has neither and is 0x34 bytes."""
    code = D.code[db["obj"]]
    r = db["rva"]
    if code[r + 0x3C:r + 0x40] == b"Prev":
        sz = int.from_bytes(code[r + 0x40:r + 0x44], "little")
        if 0x34 <= sz <= 0x80:
            return sz
    return 0x34


def _all_incs(D):
    incs = set()
    for o in D.objs.values():
        if o["exec"]:
            incs.update(device_incs(D, o["idx"]))
    incs.discard("VMM")                                    # VMM.INC MUST come first: it defines the
    return ["VMM"] + sorted(incs)                          #  macros (Begin_Service_Table, ...) the
    #                                                         other device INCs invoke at include time


def _db_data(bs, width=60):
    """Render a DATA span readably: coalesce printable-ASCII runs (>=4 bytes) into `db 'text'` (a `'`
    doubled, long runs wrapped at `width`), everything else as `db 0XXh, ...` (16/line). Assembles to
    the SAME bytes as all-hex -- MASM/nasm encode 'text' as its ASCII bytes. For DATA spans only; never
    used on byte-preserved instruction encodings (which stay `_db` hex)."""
    out = []
    n = len(bs)
    i = 0
    while i < n:
        if 0x20 <= bs[i] <= 0x7E:                          # a printable run of >=4 -> string literal
            j = i
            while j < n and 0x20 <= bs[j] <= 0x7E:
                j += 1
            if j - i >= 4:
                for c in range(i, j, width):
                    txt = bytes(bs[c:min(c + width, j)]).decode("latin1").replace("'", "''")
                    out.append("        db  '%s'" % txt)
                i = j
                continue
        j = i                                              # else a hex chunk up to the next such run
        while j < n:
            if 0x20 <= bs[j] <= 0x7E:
                k = j
                while k < n and 0x20 <= bs[k] <= 0x7E:
                    k += 1
                if k - j >= 4:
                    break
            j += 1
        for c in range(i, j, 16):
            out.append("        db  " + ", ".join("0%02Xh" % b for b in bs[c:min(c + 16, j)]))
        i = j
    return out


_JCC = {0x80: "jo", 0x81: "jno", 0x82: "jb", 0x83: "jae", 0x84: "je", 0x85: "jne", 0x86: "jbe",
        0x87: "ja", 0x88: "js", 0x89: "jns", 0x8a: "jp", 0x8b: "jnp", 0x8c: "jl", 0x8d: "jge",
        0x8e: "jle", 0x8f: "jg"}


def _fx_label(D, oi, k):
    """The emitted label an INTERNAL fixup at (oi,k) points to, or None (import / no label)."""
    f = D.fx.get((oi, k))
    if not f or f["kind"] != "internal" or f.get("target") is None:
        return None
    return D.labels.get((f["obj"], f["target"]))


def _loadable_insn(D, oi, a, row):
    """LOADABLE mode: emit an instruction's INTERNAL fixups symbolically so LINK writes real LE
    relocations (the byte-exact path raws them, dropping the relocation -> wrong pointer on load).
    A near call/jmp/jcc whose displacement carries a self-relative fixup becomes `call/jmp/jcc
    <label>` (the assembler recomputes the displacement after LINK places the segments); any other
    32-bit-offset fixup field becomes `dd offset <label>`, splitting the instruction into db + dd + db.
    Returns asm lines, or None to fall through (no fixup / int 20h service / import / unlabelled)."""
    from engine.inverse_engine.vxd_masm import _db
    fixes = sorted(k for k in range(a, a + row["size"]) if (oi, k) in D.fx)
    if not fixes or row.get("vxdcall") or any(_fx_label(D, oi, k) is None for k in fixes):
        return None
    code = D.code[oi]; op = code[a]
    if row["size"] == 5 and op in (0xE8, 0xE9) and fixes == [a + 1]:
        return ["        %-6s %s" % ("call" if op == 0xE8 else "jmp", _fx_label(D, oi, a + 1))]
    if row["size"] == 6 and op == 0x0F and code[a + 1] in _JCC and fixes == [a + 2]:
        return ["        %-6s %s" % (_JCC[code[a + 1]], _fx_label(D, oi, a + 2))]
    out = []; prev = a
    for k in fixes:
        if k > prev:
            out.append(_db(code[prev:k]))
        out.append("        dd  offset %s" % _fx_label(D, oi, k))
        prev = k + 4
    if prev < a + row["size"]:
        out.append(_db(code[prev:a + row["size"]]))
    return out


def _db_split_labels(code, a, b, labels):
    """Emit code[a:b] as raw db, inserting `<name> label byte` at each interior offset in `labels`
    (a fixup target that fell mid-instruction). Byte-preserving, and gives the target an address."""
    from engine.inverse_engine.vxd_masm import _db
    out = []; run = a
    for off in sorted(k for k in labels if a <= k < b):
        if off > run:
            out.append(_db(code[run:off]))
        out.append("%s label byte" % labels[off])
        run = off
    if run < b:
        out.append(_db(code[run:b]))
    return out


def _loadable_data(D, oi, a, b):
    """LOADABLE mode: emit a data span [a,b), turning each INTERNAL-fixup DWORD into `dd offset
    <label>` (a real relocation) and the rest through the readable _db_data (strings/bytes)."""
    out = []; run = a; k = a; code = D.code[oi]
    while k < b:
        lbl = _fx_label(D, oi, k)
        if lbl and k + 4 <= b:
            if k > run:
                out.extend(_db_data(code[run:k]))
            out.append("        dd  offset %s" % lbl)
            k += 4; run = k
        else:
            k += 1
    if run < b:
        out.extend(_db_data(code[run:b]))
    return out


def emit_idiomatic(D, loadable=False):
    """Emit one VxD as idiomatic DDK-macro source: `include`s, `Declare_Virtual_Device`, per-segment
    `VxD_..._CODE_SEG`, the control proc as `Begin_Control_Dispatch`/`Control_Dispatch`/`End_Control_
    Dispatch`, functions as `BeginProc`/`EndProc`, service calls as `VMMcall`/`VxDcall <name>`. Reads
    like Microsoft's source; the DDB + service calls are byte-exact, the dispatch/segment layout
    resolve through the DDK ML+LINK build.

    A VxD's own *exported* service table (when every entry resolves, see service_table) is emitted
    idiomatically as `Begin_Service_Table`/`<name>_Service <handler>, LOCAL`/`End_Service_Table` with
    `Create_<name>_Service_Table` set, so Declare_Virtual_Device fills the DDB's Service_Table_Ptr/Size
    correctly -- otherwise those DDB fields would be zero. Every service is forced LOCAL (correct here:
    the whole VxD is one file), which sidesteps the EXTRN-vs-definition collision the INC's own
    (partly non-LOCAL) table would cause. A table that can't be fully resolved stays raw db."""
    from engine.inverse_engine.vxd_tree import seg_class
    from engine.inverse_engine.vxd_masm import _masm_line, _db, has_abs_mem, has_seg_prefix
    from engine.inverse_engine.vxd_asm import _BRANCHES, _direct_target_row
    db = D.ddb
    name = db["name"] if db else "DEVICE"
    # a reconstructed label (often from a .SYM) can collide with a symbol the DDK macros generate --
    # <name>_DDB (Declare_Virtual_Device) or <name>_Service_Table (Begin_Service_Table) -- e.g. VDD's
    # .SYM names a routine VDD_DDB at an offset that is NOT the real DDB. Rename it to the offset-based
    # sub_ name (consistently, in D.labels, so its references follow) or ML reports A2005 redefinition.
    for k in [k for k, nm in D.labels.items() if nm in (name + "_DDB", name + "_Service_Table")]:
        D.labels[k] = "sub_%d_%04X" % k
    force_lbl = {}                                            # (oi,off) -> label, for a fixup target that
    if loadable:                                              # lands MID-INSTRUCTION (a data byte the
        from engine.inverse_engine.vxd_link import _label_fixup_targets   # disassembler swept into an
        _label_fixup_targets(D)                              # instruction). loadable: every internal
        interior_of = {}                                     # fixup target needs a label the symbolic
        for (o2, a2), r2 in D.insns.items():                #  emit can reference; a mid-instruction
            for k in range(a2 + 1, a2 + r2["size"]):        #  target forces its instruction to raw db
                interior_of[(o2, k)] = a2                    #  so the label can sit at the exact byte
        for (soi, soff), f in list(D.fx.items()):
            if f["kind"] != "internal" or f.get("target") is None:
                continue
            tgt = (f["obj"], f["target"])
            if tgt in D.labels:
                continue
            lab = "loc_%d_%04X" % tgt
            D.labels[tgt] = lab
            if tgt in interior_of:
                force_lbl[tgt] = lab
    # base set of offsets that will carry an emitted label -- a label at an instruction start, or on a
    # data byte, but NOT one landing mid-instruction. control_dispatch needs it to only reference
    # handlers we actually emit; the branch gate below needs it minus the macro-absorbed regions.
    starts, interior = {}, {}
    for (o2, a2), row in D.insns.items():
        starts.setdefault(o2, set()).add(a2)
        iv = interior.setdefault(o2, set())
        for k in range(a2 + 1, a2 + row["size"]):
            iv.add(k)
    emittable = {(o2, a2) for (o2, a2) in D.labels
                 if a2 in starts.get(o2, ()) or a2 not in interior.get(o2, set())}
    # Resolve the control dispatch and DDB skip FIRST, so the service table is validated against what
    # the walk will actually emit (a handler inside the dispatch region would be referenced but skipped).
    handlers, cp_skip = control_dispatch(D, emittable)       # ([], set()) unless a recognised jump
    cp = next((k for k, nm in D.labels.items()               #  table / compare chain -> then emit
              if nm == name + "_Control"), None) if handlers else None   # Begin_Control_Dispatch and
    #                                                          skip it; else emit the proc verbatim
    if db:                                                    # the DDB struct is re-emitted by the
        cp_skip |= {(db["obj"], k)                            #  top-level Declare_Virtual_Device, so
                    for k in range(db["rva"], db["rva"] + _ddb_size(D, db))}   # skip it in the walk
    svc_labels, svc_loc, svc_extra = service_table(D, emittable - cp_skip)   # own exported service table;
    svc_extra = svc_extra or {}                                   #  handlers must be emitted, not skipped
    if svc_loc:
        so, sp, sc = svc_loc                                  # skip the raw service-table pointers;
        cp_skip |= {(so, k) for k in range(sp, sp + 4 * sc)}  #  Begin_Service_Table re-emits them
    # .586p (privileged, superset of .386p) so ring-0 486/Pentium ops -- invd/wbinvd/cpuid/cmpxchg/
    # rdmsr/wrmsr/rdtsc -- assemble as themselves instead of hitting A2085 (not-in-current-CPU-mode).
    L = [".586p"] + ["include %s.inc" % i.lower() for i in _all_incs(D)] + [""]
    if svc_labels:
        svcset = {lbl for lbl in svc_labels if lbl != "RESERVED"}
        # Begin_Service_Table regenerates a PUBLIC caller-thunk `_<service>` for each service; drop any
        # reconstructed label of that exact name (a .SYM ships those thunks) or ML reports A2005.
        for k in [k for k, nm2 in D.labels.items() if nm2.startswith("_") and nm2[1:] in svcset]:
            D.labels[k] = "sub_%d_%04X" % k
        L.append("IFNDEF %s_Device_ID" % name)             # the service macro forms each ordinal from
        if db:                                             #  <name>_Device_ID; define it from the DDB
            L.append("%s_Device_ID EQU 0%04Xh" % (name, db["device_id"]))   # since the device's own
        L.append("ENDIF")                                  #  INC (which would define it) may be absent
        L.append("Create_%s_Service_Table EQU 1" % name)  # (Create_ before the DDB so Declare_Virtual_
        L.append("Begin_Service_Table %s" % name)         #  Device fills Service_Table_Ptr/Size). All
        for lbl in svc_labels:                             #  LOCAL: every handler is in this one file.
            L.append("        %s_Service %s, LOCAL" % (name, lbl) if lbl != "RESERVED"
                     else "        %s_Service RESERVED" % name)
        L += ["End_Service_Table %s" % name, ""]
    if db:
        L += [ddb_macro(db), ""]
    # a symbolic branch may resolve only to a label the walk emits: emittable minus the control-proc /
    # DDB / service-table regions the macros absorb. A branch to anything else is byte-preserved.
    emitted = emittable - cp_skip
    # a control handler whose target label we do not actually emit (a stub VxD whose messages all
    # dispatch into the control-proc region, or a shared do-nothing stub) would make Control_Dispatch
    # reference an undefined symbol -- drop it, and that message falls through to the macro default.
    emitted_names = {D.labels[k] for k in emitted}
    handlers = [(m, h) for (m, h) in handlers if h in emitted_names]
    for o in D.v.objects if hasattr(D, "v") else D.objs.values():
        oi = o["idx"]
        cls, _ = seg_class(o["flags"])
        segm = _SEG_MACRO.get(cls, "VxD_LOCKED_CODE")
        L.append("%s_SEG" % segm)
        code = D.code[oi]
        n = len(code)
        cur_proc = None
        a = 0
        while a < n:
            if cp and (oi, a) == cp:                       # emit the control dispatch macro block
                L.append("Begin_Control_Dispatch %s" % name)
                for msg, h in handlers:
                    L.append("        Control_Dispatch %-22s %s" % (msg + ",", h))
                L.append("End_Control_Dispatch %s" % name)
                a += 1
                continue
            if (oi, a) in cp_skip:                          # rest of the control proc / dispatch
                a += 1                                      #  table is generated by the macros above
                continue
            for xnm in svc_extra.get((oi, a), ()):         # extra service-name labels: several services
                L.append("%s:" % xnm)                      #  may share one handler routine
            lbl = D.labels.get((oi, a))
            if lbl and lbl.startswith(("sub_", name + "_")) and not lbl.endswith("_Control"):
                if cur_proc:
                    L.append("EndProc %s" % cur_proc)
                cur_proc = lbl
                L.append("BeginProc %s" % lbl)
            elif lbl:
                L.append("%s:" % lbl)
            row = D.insns.get((oi, a))
            if row is None:                                # data
                b = a
                while b < n and (oi, b) not in D.insns and (oi, b) not in cp_skip \
                        and (b == a or (not D.labels.get((oi, b)) and (oi, b) not in svc_extra)):
                    b += 1
                if loadable:                            # data pointers / jump tables -> real relocations
                    L.extend(_loadable_data(D, oi, a, b))
                else:
                    L.extend(_db_data(code[a:b]))       # readable `db 'text'` for the carved strings
                a = b
                continue
            if loadable and any((oi, k) in force_lbl for k in range(a + 1, a + row["size"])):
                lbls = {k: force_lbl[(oi, k)] for k in range(a, a + row["size"]) if (oi, k) in force_lbl}
                L.extend(_db_split_labels(code, a, a + row["size"], lbls))   # target sits mid-instruction
                a += row["size"]; continue
            load_lines = _loadable_insn(D, oi, a, row) if loadable else None
            if row.get("vxdcall"):
                m = svc_macro(row["vxdcall"][0], row["vxdcall"][1])
                L.append(m if m else _db(row["raw"]))
            elif load_lines is not None:                       # loadable: internal fixup -> symbolic ref
                L.extend(load_lines)
            elif row["fx"] or has_abs_mem(row) or has_seg_prefix(row) or _addr16(row) \
                    or _shift_no_count(row) or _ml611_unknown(row) or _x87_stack(row) \
                    or _indirect_branch(row) or _cap_size(row) or row["mnem"] in _RAW_MNEMS:
                L.append(_db(row["raw"]))                       # byte-preserve the encodings ML will
            else:                                              #  not reproduce (abs-mem, seg-override,
                line = _masm_line(D, oi, row)                  #  16-bit addr, aam/aad, int3, far ...)
                if line and row["mnem"] in _BRANCHES:
                    op = line.split(None, 1)
                    tgt = _direct_target_row(row)
                    if (len(op) > 1 and _NUM_TARGET.match(op[1].strip())) \
                            or (tgt is not None and (oi, tgt) not in emitted):
                        line = None                            # target we don't emit a label for
                    else:                                      #  (bare number / mid-instruction) -> raw
                        line = line.replace("SHORT ", "").replace("NEAR PTR ", "")   # let ML size the
                #  branch: keeping the oracle's rel8/rel32 is the byte-exact tree's job; the readable
                #  form's object layout shifts (macros, skipped DDB, size-drifting db) can push a pinned
                #  SHORT out of range, and unpinned reads more like MS source anyway.
                L.append(line or _db(row["raw"]))
            a += row["size"]
        if cur_proc:
            L.append("EndProc %s" % cur_proc)
        L.append("%s_ENDS" % segm)
        L.append("")
    L.append("        end")
    return "\r\n".join(L) + "\r\n"


_HEADER = """\
; {name}.ASM -- {name} reconstructed in idiomatic VMM DDK-macro source form.
;
; Recovered from the stripped LE binary by recursive-descent disassembly and re-emitted with the
; period Virtual Device DDK macros (Declare_Virtual_Device, Begin_Control_Dispatch / Control_
; Dispatch / End_Control_Dispatch, VMMcall / VxDcall <service>, BeginProc / EndProc, VxD_..._SEG) so
; it reads like Microsoft's own VxD source. It assembles through the 1996 DDK ML.EXE (COFF) with the
; stock INC32 headers. Encodings ML will not reproduce byte-for-byte (mov eAX,[disp], segment/16-bit-
; address prefixes, aam/aad, shift-by-1, self-relative call) are kept as `db` to stay byte-exact.
;
; The original source file names, comments and most internal labels are not present in a stripped LE
; image: internal routines are sub_<offset> except where a debug .SYM gives the real name. Exported
; service names and control-dispatch handler names ARE the real DDK names.
"""


def emit_idiomatic_tree(v, name, outdir):
    """Write outdir/<name>/<name>.asm -- the whole VxD as one idiomatic DDK-macro source file.
    Returns the path written."""
    D = VxDDisasm(v).run()
    D.v = v
    d = os.path.join(outdir, name.lower())
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "%s.asm" % name.lower())
    head = _HEADER.format(name=name)
    open(path, "w", newline="").write(head + "\r\n" + emit_idiomatic(D))
    return path


def verify_corpus(srcdir, root=".", budget=40000, only=None):
    """Assemble every module's idiomatic source through the period DDK ML.EXE and report which fail.
    Assemblies are BATCHED -- many modules' `ml.exe` calls run in ONE DOSBox session (one BLD.BAT),
    grouped so each session stays under `budget` source lines (a module larger than that runs solo).
    That turns ~215 cold DOSBox starts into ~15-45 sessions; startup, not the assembler, was the cost.
    Returns {name: bool}. `only` limits to a set of lowercase module names."""
    import glob
    from engine.format_loaders import le
    from engine.inverse_engine import vxd_masm
    from engine.backbone.dosbox import run_dos
    tc = vxd_masm._stage_toolchain(root)
    incsrc = os.path.join(root, "binaries", "media", "Microsoft Windows 95 DDK", "INC32")
    incdst = os.path.join(tc, "inc")
    os.makedirs(incdst, exist_ok=True)
    for f in glob.glob(incsrc + "/*.INC"):
        dst = os.path.join(incdst, os.path.basename(f))
        if not os.path.exists(dst):
            __import__("shutil").copy(f, dst)
    mods = []
    for p in sorted(glob.glob(os.path.join(srcdir, "*.vxd")) + glob.glob(os.path.join(srcdir, "*.386"))):
        try:
            ms = le.open_vxds(p)
        except Exception:
            continue
        for nm, v in ms:
            k = nm.split(".")[0].lower()
            if only and k not in only:
                continue
            D = VxDDisasm(v).run(); D.v = v
            mods.append((k, emit_idiomatic(D)))
    batches, cur, cl = [], [], 0
    for m in sorted(mods, key=lambda x: x[1].count("\n")):
        nl = m[1].count("\n")
        if nl > budget:
            batches.append([m]); continue
        if cl + nl > budget and cur:
            batches.append(cur); cur, cl = [], 0
        cur.append(m); cl += nl
    if cur:
        batches.append(cur)
    cmd = r"c:\ml.exe -coff -c -DBLD_COFF -DIS_32 -DMASM6 -Ic:\inc -Fo%s.obj %s.asm > %s.txt"
    res = {}
    for batch in batches:
        files, bat, arts = {}, [], []
        for i, (k, asm) in enumerate(batch):
            fn = "m%d" % i
            files[fn + ".asm"] = asm
            bat.append(cmd % (fn, fn, fn))
            arts += [fn + ".obj", fn + ".txt"]
        tot = sum(m[1].count("\n") for m in batch)
        _, out, _ = run_dos({"c": tc}, bat, arts, files=files, timeout=min(600, 40 + tot // 100))
        for i, (k, asm) in enumerate(batch):
            res[k] = bool(out.get("m%d.obj" % i))
    return res


