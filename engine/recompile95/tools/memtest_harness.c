/* memtest_harness.c -- host-side (WOW64) differential tester for MEMORY functions.
 *
 * Companion to memdifftest.py. For each win95 function that takes caller BUFFER pointers, it
 * marshals the buffers, calls the recompiled Lifted C (LIFTM.DLL), and compares BOTH the return
 * value AND every buffer's after-state against an embedded reference computed by emulating win95's
 * real shipped bytes. A fault (a function that chases a pointer out of its buffer) is caught with
 * signal()+longjmp -- i686 mingw has no __try/__except -- and reported, never fatal.
 *
 * Built as a normal 32-bit CRT exe (runs under WOW64). memtests.h is generated by memdifftest.py. */
#include <stdio.h>
#include <windows.h>
#include <signal.h>
#include <setjmp.h>
typedef unsigned u32;
#include "memtests.h"

typedef u32 (__cdecl *F1)(u32); typedef u32 (__cdecl *F2)(u32, u32);
typedef u32 (__cdecl *F3)(u32, u32, u32); typedef u32 (__cdecl *F4)(u32, u32, u32, u32);
typedef u32 (__cdecl *F5)(u32, u32, u32, u32, u32); typedef u32 (__cdecl *F6)(u32, u32, u32, u32, u32, u32);
typedef u32 (__cdecl *F7)(u32, u32, u32, u32, u32, u32, u32);
typedef u32 (__cdecl *F8)(u32, u32, u32, u32, u32, u32, u32, u32);
typedef void (__cdecl *ZF)(void);
static u32 calln(void *f, int n, u32 *a){
  switch(n){ case 1: return ((F1)f)(a[0]); case 2: return ((F2)f)(a[0], a[1]);
  case 3: return ((F3)f)(a[0], a[1], a[2]); case 4: return ((F4)f)(a[0], a[1], a[2], a[3]);
  case 5: return ((F5)f)(a[0],a[1],a[2],a[3],a[4]); case 6: return ((F6)f)(a[0],a[1],a[2],a[3],a[4],a[5]);
  case 7: return ((F7)f)(a[0],a[1],a[2],a[3],a[4],a[5],a[6]);
  default: return ((F8)f)(a[0],a[1],a[2],a[3],a[4],a[5],a[6],a[7]); } }

static jmp_buf jb;
static void onfault(int s){ (void)s; longjmp(jb, 1); }

int main(void){
  HMODULE h = LoadLibraryA("LIFTM.DLL");
  if(!h){ printf("MEMORY: FATAL LIFTM.DLL failed to load\n"); return 1; }
  ZF z = (ZF)GetProcAddress(h, "__zero");
  signal(SIGSEGV, onfault); signal(SIGILL, onfault);
  int okc=0, totc=0, okf=0, nf=0, crashf=0;
  for(int i=0;i<NMT;i++){
    const MT *t = &MT_[i];
    void *f = GetProcAddress(h, t->name);
    unsigned char *bufs[MAXPTR]; int fok=1, crashed=0;
    for(int j=0;j<t->nptr;j++)
      bufs[j] = (unsigned char*)VirtualAlloc(0, BUFSZ, MEM_COMMIT|MEM_RESERVE, PAGE_READWRITE);
    for(int k=0;k<t->nc;k++){
      u32 args[8];
      for(int a=0;a<t->arity;a++) args[a] = t->args[k*t->arity + a];
      for(int j=0;j<t->nptr;j++){
        const unsigned char *src = &t->bin[(k*t->nptr + j)*BUFSZ];
        for(int b=0;b<BUFSZ;b++) bufs[j][b] = src[b];
        args[t->pidx[j]] = (u32)(size_t)bufs[j];
      }
      if(z) z();
      u32 rv; totc++;
      if(setjmp(jb)==0){ rv = calln(f, t->arity, args); }
      else { crashed=1; signal(SIGSEGV,onfault); signal(SIGILL,onfault); fok=0; continue; }
      /* pointer-identity return: a returned `this`/`this+k` points into a buffer; the emulated ref
       * holds the emulation address, so rebuild the expected value from THIS run's buffer j. */
      u32 expret = (t->retbuf[k] >= 0) ? (u32)(size_t)bufs[t->retbuf[k]] + t->retoff[k] : t->ret[k];
      int good = (rv == expret);
      for(int j=0;j<t->nptr && good;j++){
        const unsigned char *exp = &t->bout[(k*t->nptr + j)*BUFSZ];
        for(int b=0;b<BUFSZ;b++) if(bufs[j][b] != exp[b]){ good=0; break; }
      }
      if(good) okc++; else fok=0;
    }
    for(int j=0;j<t->nptr;j++) VirtualFree(bufs[j], 0, MEM_RELEASE);
    nf++; if(fok) okf++; else if(crashed) crashf++;
    if(!fok) printf("  XX %s:%s\n", t->mod, t->name);
  }
  printf("MEMORY SELF: %d/%d cases identical (return+buffers); %d/%d functions fully identical to "
         "Windows 95 (%d crashed uncallable)\n", okc, totc, okf, nf, crashf);
  return 0;
}
