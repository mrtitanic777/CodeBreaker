"""Unified analysis report — point it at any file, get a one-page markdown
summary. Ties the workbench together: format identification, XEX metadata, build
date, sections, imports, function count, and notable strings, each from the same
parsers the individual commands use. Every section is best-effort — one that
can't be produced is skipped, never fatal.
"""

import datetime
import importlib
import os
import struct
import sys

DESCRIPTION = "one-page markdown analysis report for a XEX/Xbox file (format, build, imports, strings, ...)"


def _imp(name):
    here = os.path.dirname(os.path.abspath(__file__))
    for d in (here, os.path.join(os.path.dirname(here), "ppc")):
        if d not in sys.path:
            sys.path.insert(0, d)
    return importlib.import_module(name)


def _pe_timestamp(img):
    if len(img) < 0x40 or img[:2] != b"MZ":
        return None
    e = struct.unpack_from("<I", img, 0x3C)[0]
    if e + 12 > len(img) or img[e:e + 4] != b"PE\x00\x00":
        return None
    return struct.unpack_from("<I", img, e + 8)[0]


def _fmt_time(ts):
    if not ts:
        return "unknown"
    try:
        return datetime.datetime.fromtimestamp(
            ts, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    except Exception:
        return "0x%08X (invalid)" % ts


def _sz(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return "%.0f %s" % (n, unit) if unit == "B" else "%.1f %s" % (n, unit)
        n /= 1024.0


def report(path):
    """Return a markdown report string for `path`."""
    md = []
    name = os.path.basename(path)
    fsize = os.path.getsize(path)
    md.append("# Analysis report: `%s`" % name)
    md.append("")
    md.append("- **File size:** %s (%d bytes)" % (_sz(fsize), fsize))

    # ---- format identification ----
    fmt_tool = None
    try:
        identify = _imp("identify")
        matches = identify.identify(path)
        if matches:
            f, detail, tool = matches[0]
            fmt_tool = tool
            md.append("- **Format:** %s%s" % (f, ("  (%s)" % detail) if detail else ""))
        else:
            md.append("- **Format:** unrecognised")
    except Exception as e:
        md.append("- **Format:** (detection failed: %s)" % e)

    # ---- XEX-specific report ----
    if fmt_tool == "xex":
        _xex_report(path, md)
    md.append("")
    md.append("*Generated by XboxTranspiler `report`.*")
    return "\n".join(md)


def _xex_report(path, md):
    try:
        xex = _imp("xex")
        x = xex.open_xex(path)
        s = x.summary()
    except Exception as e:
        md.append("\n_(XEX parse failed: %s)_" % e)
        return

    md.append("")
    md.append("## XEX header")
    md.append("")
    rows = [
        ("Title ID", s.get("title_id", "?")),
        ("Media ID", s.get("media_id", "?")),
        ("Version", s.get("version", "?")),
        ("Module type", s.get("module_type", "?")),
        ("Module flags", ", ".join(s.get("module_flags", [])) or "-"),
        ("Image base", "0x%08X" % (s.get("image_base") or 0)),
        ("Entry point", "0x%08X" % (s.get("entry_point") or 0)),
        ("Encryption", s.get("encryption", "?")),
        ("Compression", s.get("compression", "?")),
    ]
    md.append("| Field | Value |")
    md.append("|---|---|")
    for k, v in rows:
        md.append("| %s | %s |" % (k, v))

    # basefile-derived: build time, sections, function count
    try:
        img = x.basefile()
    except Exception:
        img = None
    if img:
        ts = _pe_timestamp(img)
        md.append("")
        md.append("- **Build time (PE TimeDateStamp):** %s" % _fmt_time(ts))
        try:
            secs = xex._pe_sections(img)
            md.append("")
            md.append("## Sections")
            md.append("")
            md.append("| Name | VA | Virtual size | Flags |")
            md.append("|---|---|---|---|")
            for sec in secs:
                flags = []
                ch = sec.get("chars", 0)
                if sec.get("code") or ch & 0x20:
                    flags.append("code")
                if ch & 0x40:
                    flags.append("data")
                if ch & 0x80000000:
                    flags.append("write")
                md.append("| %s | 0x%08X | %s | %s |"
                          % (sec["name"], (x.image_base or 0) + sec["vaddr"],
                             _sz(sec["vsize"]), "/".join(flags) or "-"))
            # function count from .pdata (each RUNTIME_FUNCTION is 8 bytes)
            pd = next((se for se in secs if se["name"] == ".pdata"), None)
            if pd:
                md.append("")
                md.append("- **Functions (.pdata entries):** ~%d" % (pd["vsize"] // 8))
        except Exception:
            pass

    # imports per library
    try:
        imps = x.imports()
        if imps:
            md.append("")
            md.append("## Imports")
            md.append("")
            md.append("| Library | Functions | Data slots |")
            md.append("|---|---|---|")
            for lib, entries in sorted(imps.items()):
                thunks = sum(1 for _a, _o, k in entries if k == "thunk")
                slots = sum(1 for _a, _o, k in entries if k != "thunk")
                md.append("| %s | %d | %d |" % (lib, thunks, slots))
    except Exception:
        pass

    # notable strings — scan only the data sections (where strings live), so a
    # large image doesn't make the report crawl.
    try:
        strings = _imp("strings")
        if img:
            scan_regions = []
            try:
                for sec in xex._pe_sections(img):
                    if sec["name"].lower() in (".rdata", ".data"):
                        o = sec["raw_off"]
                        scan_regions.append(img[o:o + min(sec.get("raw_size", 0)
                                                          or sec["vsize"], 8 << 20)])
            except Exception:
                pass
            blob = b"\x00".join(scan_regions) if scan_regions else img[: 8 << 20]
            found = strings.scan_strings(blob, 0, 8)
            # keep distinct, prefer path/format-looking strings, cap the list
            seen, picks = set(), []
            for _a, sv in found:
                if sv in seen:
                    continue
                seen.add(sv)
                # prefer readable, word-like strings (mostly letters/spaces),
                # skip binary-looking runs that merely passed the length gate
                letters = sum(c.isalpha() or c == " " for c in sv)
                dominant = max(sv.count(c) for c in set(sv))
                if (sv.isprintable() and letters >= max(6, int(len(sv) * 0.6))
                        and any(c.isalpha() for c in sv)
                        and dominant <= len(sv) * 0.4):          # not one char spammed
                    picks.append(sv)
                if len(picks) >= 25:
                    break
            if picks:
                md.append("")
                md.append("## Notable strings (%d of %d distinct)" % (len(picks), len(seen)))
                md.append("")
                for sv in picks:
                    md.append("- `%s`" % (sv if len(sv) < 110 else sv[:110] + "..."))
    except Exception:
        pass


def _selfcheck():
    # a synthetic XEX header is too involved; verify the format-dispatch + helpers.
    if _fmt_time(0x4F75C3C7) != "2012-03-30 14:31:35 UTC":
        return False, "timestamp format wrong"
    if _sz(2048) != "2.0 KB" or _sz(512) != "512 B":
        return False, "size format wrong: %r %r" % (_sz(2048), _sz(512))
    # report() on a non-XEX buffer file should still produce a header + format line
    import tempfile
    p = os.path.join(tempfile.mkdtemp(), "t.bin")
    open(p, "wb").write(b"FATX" + b"\x00" * 60)
    r = report(p)
    if "# Analysis report" not in r or "FATX" not in r:
        return False, "report on FATX blob wrong:\n" + r
    return True, "timestamp + size formatting + report dispatch (FATX blob identified)"


def main():
    a = sys.argv[1:]
    if a and a[0] == "--selftest":
        ok, msg = _selfcheck()
        print(("PASS: " if ok else "FAIL: ") + msg)
        sys.exit(0 if ok else 1)
    if not a or a[0] in ("-h", "--help"):
        print("usage: report <file> [out.md]   one-page markdown analysis report")
        return
    text = report(a[0])
    if len(a) > 1:
        open(a[1], "w", encoding="utf-8").write(text)
        print("wrote %s (%d bytes)" % (a[1], len(text)))
    else:
        print(text)


if __name__ == "__main__":
    main()
